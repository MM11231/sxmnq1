// 直接跑: node src/sxmnq/家园/房型.test.mjs
//
// 房型图是**画出来的地形**, 抄错一格不会报错, 只会让「四号房跑到了中间」。
// 所以这里逐格点名。数据源是 spec §4.2 那两张图。
//
// 顺序也在测: 九宫格是按这个数组的顺序铺进 3×3 网格的, 顺序错了整张图就转了个个儿。
import '../测试钩子.mjs';

const F = await import(new URL('./房型.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};

console.log('--- 九个方位 ---');
等于(F.方位序.length, 9, '九个');
等于(new Set(F.方位序).size, 9, '不重复');
等于(F.方位序, ['西北', '北', '东北', '西', '中', '东', '西南', '南', '东南'], '就是九宫格从左到右、从上到下');

console.log('--- L2: 五个房间 + 一扇门 + 三条过道 (spec §4.2) ---');
等于(F.二层房型.map(格 => 格.方位), [...F.方位序], '九个方位一个不缺, 且顺序与 方位序 一致');
等于(F.二层房型.map(格 => 格.类), ['房间', '房间', '房间', '路', '路', '路', '房间', '门', '房间'], '按方位逐格点名');
等于(F.二层房型.filter(格 => 格.类 === '房间').map(格 => 格.房名), ['一号', '二号', '三号', '四号', '五号'], '五间房, 按图上的顺序');
等于(F.二层房型.find(格 => 格.类 === '门').方位, '南', '门在南格 (中列最下)');
等于(F.二层房型.filter(格 => 格.类 === '路').map(格 => 格.方位), ['西', '中', '东'], '中间一整条横向过道');
断言(F.二层房型.every(格 => 格.类 !== '房间' || !!格.房名), '每个房间格都带了房名');

console.log('--- L3: 4 自由 + 1 床 + 1 门 + 3 格灰 (spec §4.2) ---');
等于(F.三层房型.map(格 => 格.方位), [...F.方位序], '外框与 L2 一致');
等于(F.三层房型.map(格 => 格.类), ['自由', '床', '自由', '自由', '门', '自由', '路', '路', '路'], '按方位逐格点名');
等于(F.三层房型.find(格 => 格.类 === '床').方位, '北', '床在中列最上');
等于(F.三层房型.find(格 => 格.类 === '门').方位, '中', '门在正中');
等于(F.三层房型.filter(格 => 格.类 === '自由').map(格 => 格.方位), ['西北', '东北', '西', '东'], '四个自由格绕着中列');
等于(F.三层房型.filter(格 => 格.类 === '路').map(格 => 格.方位), ['西南', '南', '东南'], '下排三格是灰的');

console.log('--- 格收什么类家具 (spec §4.1) ---');
const 取 = (类, 方位 = '北') => F.格收什么类({ 方位, 类 });
等于(取('床'), '床', '床格只收床');
等于(取('自由'), '装饰', '自由格只收装饰');
等于(取('房间'), null, '房间格不收东西 —— 点它是下钻');
等于(取('门'), null, '门不收东西');
等于(取('路'), null, '路点都点不动');

console.log('--- 开局那张床摆在哪 (spec §8.1) ---');
等于(F.房间名表[0], '一号', '第一间房叫一号');
等于(F.开局床位, '一号·北', '开局那张折叠床摆在一号房的北格');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
