/**
 * 家具的派生值与动作。
 *
 * **`诊所.家具` 数组是唯一的真值源** (spec §8): 一件家具「摆在哪」写在它自己的
 * `在哪` 上, 不另存一张摆位表 —— 那样会出现「摆位指向一件已经不存在的家具」
 * 这种修不好的坏状态。同款买两件也不需要额外机制, 数组天然允许。
 *
 * 本模块里所有 `算*` 都是纯函数, **不进 schema**; 只有 `气氛` 是持久化的派生值
 * (写在 schema 里、每次解析时重算, 照 `$称号` 的既有做法)。
 *
 * 动作 (收起来 / 摆上 / 从仓库摆) 是**就地改数组**的 —— 传进来的是 store 里那个
 * 响应式数组, 改完由 store 的深度监听写回变量。这和 结算.ts 的 应用结算 一个路子。
 */
import { 开局床位 } from './房型';
import { 找物品, type 家具类型, type 物品 } from './物品';

export interface 家具件 {
  名称: string;
  类型: 家具类型;
  /** 摆出来才加气氛。它跟着家具走而不是每次去查表, 是为了改表之后老存档不变样 */
  氛围: number;
  /** `''` = 还在仓库。否则是 `${房间}·${方位}`, 如 `一号·北` (spec §8) */
  在哪: string;
}

/**
 * 数组下标 + 那件家具。**两个一起带着走** ——
 * 同款买了两件时, 光凭名称分不出要动的是哪一件。
 */
export interface 带序 {
  序: number;
  件: 家具件;
}

/** `一号·北` → `一号`。空字符串(仓库)原样返回空字符串 */
export function 房间名(在哪: string): string {
  return 在哪.split('·')[0] ?? '';
}

/** 仓库 = 买了还没摆的 (spec §6.3)。它就是「家园」按钮上那个角标。 */
export function 算仓库(家具: 家具件[]): 带序[] {
  return 家具.map((件, 序) => ({ 序, 件 })).filter(项 => !项.件.在哪);
}

/** 摆位: `一号·北` → 那件家具。空格子不在里面 —— 界面判「有没有」就是查它。 */
export function 算摆位(家具: 家具件[]): Record<string, 带序> {
  const 表: Record<string, 带序> = {};
  家具.forEach((件, 序) => {
    if (件.在哪) 表[件.在哪] = { 序, 件 };
  });
  return 表;
}

/**
 * 床位 = 摆出来的床有几张 (spec §7.1)。**这是「床位」唯一的定义** ——
 * 它不再是变量。前序 §5.2 那道床位闸门 (能接诊吗) 逻辑一个字没改,
 * 只是入参从写死的数字换成了这个。
 */
export function 算床位(家具: 家具件[]): number {
  return 家具.filter(件 => 件.在哪 && 件.类型 === '床').length;
}

/**
 * 气氛 = 摆出来的家具的氛围之和 (spec §7.2)。**本身不封顶** ——
 * 封顶的是它换来的信赖加成。仓库里的不算。
 */
export function 算气氛(家具: 家具件[]): number {
  return 家具.reduce((和, 件) => (件.在哪 ? 和 + 件.氛围 : 和), 0);
}

/** 气氛换来的信赖加成。硬上限 +5 —— 前序 §7 就是这么定的 (spec §7.2) */
export function 算信赖加成(气氛: number): number {
  return Math.min(5, Math.floor(气氛 / 20));
}

/** 气氛的档位描述 (spec §9.3)。状态栏里那一句就是它。 */
export function 气氛档(气氛: number): string {
  if (气氛 >= 60) return '让人不想走';
  if (气氛 >= 40) return '待着舒服';
  if (气氛 >= 20) return '还算整洁';
  return '有点冷清';
}

/**
 * 一个房间里摆了几件、几张床、多少氛围 —— L2 那张房间卡上的小字。
 *
 * 按**解析出来的房间名**比, 不用 `startsWith`: 房间名是 `一号` 的时候,
 * `startsWith` 会把 `十一号·北` 也算进来。
 */
export function 房间概况(家具: 家具件[], 房名: string): { 床: number; 件: number; 氛围: number } {
  const 在里面 = 家具.filter(件 => 件.在哪 && 房间名(件.在哪) === 房名);
  return {
    床: 在里面.filter(件 => 件.类型 === '床').length,
    件: 在里面.length,
    氛围: 在里面.reduce((和, 件) => 和 + 件.氛围, 0),
  };
}

/**
 * 开局那张折叠床 (spec §8.1)。
 *
 * 老存档里 `诊所.床位 = 1`、没有 `家具`, 新 schema 派生出来的床位会是 **0**
 * —— 等于把所有人的开局那张床弄丢了。空数组 == 开局态 (本卡没有「卖掉所有家具」
 * 这条路), 所以拿它当判据播种是幂等的。
 *
 * 数值照物品表取, **不另写一个数**: 表改了这里跟着改, 不会悄悄脱钩。
 */
export function 开局家具(): 家具件[] {
  const 床 = 找物品('折叠床');
  if (!床) throw Error('物品表里没有「折叠床」—— 开局那张床是照它播种的 (spec §8.1)');
  return [{ 名称: 床.名称, 类型: 床.类型, 氛围: 床.氛围, 在哪: 开局床位 }];
}

/**
 * 把一个格子清空: 那件家具**退回仓库**, 不是卖掉 (spec §5)。
 * 于是「给一号房换诊疗床」顺带就把退下来的折叠床给了二号房。
 */
export function 收起来(家具: 家具件[], 在哪: string): void {
  const 项 = 算摆位(家具)[在哪];
  if (项) 项.件.在哪 = '';
}

/**
 * 买一件并**直接摆进这个格子** (spec §5: 从这里买就直接摆上, 不要求先去仓库取)。
 * 格子上原来那件退回仓库 —— 这就是「换成更好的床」。
 *
 * 扣钱**不在这里**: 钱在 `主角.金钱` 上, 是另一个字段, 由调用方先确认买得起。
 * 本函数只管 `家具` 数组这一件事。
 */
export function 摆上(家具: 家具件[], 在哪: string, 物: 物品): void {
  收起来(家具, 在哪);
  家具.push({ 名称: 物.名称, 类型: 物.类型, 氛围: 物.氛围, 在哪 });
}

/** 把仓库里第 `序` 件摆进这个格子 (spec §5 的「这里能放的」) */
export function 从仓库摆(家具: 家具件[], 序: number, 在哪: string): void {
  const 件 = 家具[序];
  if (!件) return;
  收起来(家具, 在哪);
  件.在哪 = 在哪;
}
