// 直接跑: node src/sxmnq/家园/物品.test.mjs
//
// 物品表是**手抄的数字**, 所以这里盯的是那几件抄错了不会报错的事:
// 名字打重、氛围与价钱写反(60 氛围的窗帘卖 8 块)、类型拼错成 '家俱'。
// 这些在界面上都表现为「某个格子列不出东西」或「气氛莫名其妙」, 不报错。
import '../测试钩子.mjs';

const I = await import(new URL('./物品.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};

console.log('--- 表本身的性质 ---');
等于(I.物品表.length, 8, '八件货: 三张床 + 五件装饰 (spec §6.1/§6.2)');
等于(new Set(I.物品表.map(物 => 物.名称)).size, 8, '名字不重复 —— 重了 找物品 只会命中头一个');
断言(I.物品表.every(物 => 物.价钱 > 0), '每件都有价钱');
断言(I.物品表.every(物 => 物.氛围 > 0), '每件都给氛围 (本子项目里家具只产这一个数)');
断言(I.物品表.every(物 => 物.类型 === '床' || 物.类型 === '装饰'), "类型只有 '床' 和 '装饰'");

console.log('--- 床: 越贵越暖 (spec §6.1 的升级路线) ---');
const 床 = I.同类物品('床');
等于(床.map(物 => 物.名称), ['折叠床', '单人床', '诊疗床'], '三张床由便宜到贵');
断言(床[0].氛围 < 床[1].氛围 && 床[1].氛围 < 床[2].氛围, '氛围随价钱单调涨 —— 否则「升级」是亏的');
断言(床[0].价钱 < 床[1].价钱 && 床[1].价钱 < 床[2].价钱, '价钱也单调涨');
等于(床[0].氛围, 10, '折叠床 +10 (spec §6.1)');
等于(床[2].氛围, 45, '诊疗床 +45');

console.log('--- 装饰 (spec §6.2) ---');
等于(I.同类物品('装饰').length, 5, '五件装饰');
等于(I.找物品('助眠香薰').氛围, 15, '助眠香薰 +15 —— 表里最高的装饰');
等于(I.找物品('素色窗帘').价钱, 60, '素色窗帘 60 —— 表里最便宜的');

console.log('--- 找物品: 找不到要返回 undefined, 不能抛 ---');
等于(I.找物品('不存在的东西'), undefined, '表里没有 → undefined (存档里的名字对不上表时会走到这儿)');

console.log('--- 更贵的同类: 格子上有东西时列这个 (spec §5) ---');
等于(I.更贵的同类('折叠床').map(物 => 物.名称), ['单人床', '诊疗床'], '折叠床 → 往上两档');
等于(I.更贵的同类('诊疗床'), [], '已经是顶配 → 没有更好的了');
等于(I.更贵的同类('素色窗帘').map(物 => 物.名称), ['旧书架', '助眠香薰', '诊疗躺椅', '恒温灯'], '装饰按价钱排');
断言(!I.更贵的同类('素色窗帘').some(物 => 物.类型 === '床'), '只列同类型的');
等于(I.更贵的同类('不存在的东西'), [], '查不到 → 空数组, 不抛');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
