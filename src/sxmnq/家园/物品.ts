/**
 * 家具物品表。**这是全工程唯一一处定义「一件家具值多少」的地方。**
 *
 * 前序 §6.1 原来有四个效果字段 (床位 / 疗效 / 减耗 / 氛围), 本子项目删到只剩氛围
 * —— 疗法侧那两条整个下线了 (spec §2.1)。
 *
 * 床**不写「床位 +1」这个字段**: 一件床给几个床位恒为 1, 所以床位是**数出来的**
 * (见 家具.ts 的 算床位), 不是每件物品各写一遍 —— 写一遍就多一处能写错。
 *
 * 数字全部来自 spec §6.1 / §6.2, **是待调的保守值** (前序 §15 待定 #1):
 * 定价原则是「一件功能家具 ≈ 3–5 场 D 级治疗的收入」。
 */

export type 家具类型 = '床' | '装饰';

export interface 物品 {
  名称: string;
  类型: 家具类型;
  /** 摆出来之后加多少气氛 (spec §7.2) */
  氛围: number;
  /** 买它要多少金 */
  价钱: number;
}

/** 商店的全部货。床从便宜到贵就是升级路线 (spec §6.1)。 */
export const 物品表: readonly 物品[] = [
  { 名称: '折叠床', 类型: '床', 氛围: 10, 价钱: 300 },
  { 名称: '单人床', 类型: '床', 氛围: 25, 价钱: 700 },
  { 名称: '诊疗床', 类型: '床', 氛围: 45, 价钱: 1400 },

  // 装饰同理: 由便宜到贵, 氛围跟着涨 —— 更贵必须更暖 (spec §6.2)
  { 名称: '素色窗帘', 类型: '装饰', 氛围: 8, 价钱: 60 },
  { 名称: '旧书架', 类型: '装饰', 氛围: 12, 价钱: 100 },
  { 名称: '助眠香薰', 类型: '装饰', 氛围: 15, 价钱: 120 },
  { 名称: '诊疗躺椅', 类型: '装饰', 氛围: 18, 价钱: 150 },
  { 名称: '恒温灯', 类型: '装饰', 氛围: 22, 价钱: 180 },
];

/**
 * 找不到就返回 `undefined`, **不要抛** —— 存档里的家具名可能对不上表
 * (改过表、或者玩家自己写进去过)。为一个名字让整个界面崩掉不划算,
 * 界面上表现为「这件家具没有名字」总比白屏强。
 */
export function 找物品(名称: string): 物品 | undefined {
  return 物品表.find(物 => 物.名称 === 名称);
}

/** 某个类型能买的全货, 由便宜到贵。空格子的弹层列这个 (spec §5)。 */
export function 同类物品(类型: 家具类型): 物品[] {
  return 物品表.filter(物 => 物.类型 === 类型);
}

/**
 * 同类型里比它贵的那些, 由便宜到贵。格子上已经有东西时, 弹层列的是这个
 * —— 「换成更好的」而不是「还能买什么」(spec §5)。
 *
 * 已经是顶配就返回空数组, 界面据此只显示「收起来」。
 */
export function 更贵的同类(名称: string): 物品[] {
  const 现在 = 找物品(名称);
  if (!现在) return [];
  return 物品表.filter(物 => 物.类型 === 现在.类型 && 物.价钱 > 现在.价钱);
}
