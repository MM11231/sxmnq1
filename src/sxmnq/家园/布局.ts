/**
 * 九宫格的**视图模型** —— 把「房型 + 家具」烤成九张格子卡该显示什么。
 *
 * 单开这一层是为了让 `九宫格.vue` 只干渲染: 组件不该知道 `一号·北` 这种键是怎么
 * 拼的, 也不该知道 L2 的房间卡副标题写「床位 1」还是「空着」。那些住在 `.vue` 里
 * 就没法在 node 里测 —— 而 `.vue` 文件 node 直接 import 不了。
 *
 * 三层共用同一个组件、同一套格子, 只是喂进来的数据不同 (spec §4):
 * L1 全是房间卡 (② 才做), L2 是房间卡 + 门 + 过道, L3 是床 / 自由 / 门 / 灰。
 */
import { 算摆位, 房间概况, type 家具件 } from './家具';
import { 三层房型, 二层房型, type 方位, type 格类 } from './房型';

/** 一张格子卡。`主` 是那行大字, `副` 是底下的小字 */
export interface 宫格 {
  方位: 方位;
  类: 格类;
  主: string;
  /** 小字第二行。没有就单行 */
  副?: string;
  可点: boolean;
}

/** L2 · 诊所: 五张房间卡 + 一扇门 + 三条过道 */
export function 二层格子(家具: 家具件[]): 宫格[] {
  return 二层房型.map(格 => {
    if (格.类 === '房间') {
      const 概况 = 房间概况(家具, 格.房名 ?? '');
      return {
        方位: 格.方位,
        类: 格.类,
        主: 格.房名 ?? '',
        副: 概况.床 ? `▶ 床位 ${概况.床}` : '▶ 空着',
        可点: true,
      };
    }
    if (格.类 === '门') return { 方位: 格.方位, 类: 格.类, 主: '门', 副: '返回', 可点: true };
    // 过道: 不写字、点不动。三格连成一条带子才看得出那是走廊 (spec §4.1)
    return { 方位: 格.方位, 类: 格.类, 主: '', 可点: false };
  });
}

/**
 * L3 · 一间房。
 *
 * 格子上摆了东西就显示**家具名**; 空着就显示它收什么 —— 「空床」与「自由」
 * 一眼分得出这个格子是干嘛的 (spec §4.1)。
 */
export function 三层格子(家具: 家具件[], 房名: string): 宫格[] {
  const 摆位 = 算摆位(家具);
  return 三层房型.map(格 => {
    const 摆着的 = 摆位[`${房名}·${格.方位}`]?.件.名称;
    if (格.类 === '床') return { 方位: 格.方位, 类: 格.类, 主: 摆着的 ?? '空床', 可点: true };
    if (格.类 === '自由') return { 方位: 格.方位, 类: 格.类, 主: 摆着的 ?? '自由', 可点: true };
    if (格.类 === '门') return { 方位: 格.方位, 类: 格.类, 主: '门', 副: '返回', 可点: true };
    return { 方位: 格.方位, 类: 格.类, 主: '', 可点: false };
  });
}
