// 这里盯的是「格子上显示的那行字对不对」—— 显示错了不报错, 只是玩家看不懂。
import '../测试钩子.mjs';

const L = await import(new URL('./布局.ts', import.meta.url).href);
const I = await import(new URL('./物品.ts', import.meta.url).href);
const T = await import(new URL('./房型.ts', import.meta.url).href);
// 不 import 家具.ts —— 布局.ts 已经在内部用了它, 而它自己那套测试在
// 家具.test.mjs 里。这里再 import 一次只会是个没用到的变量。

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};

const 造 = (名称, 在哪) => {
  const 物 = I.找物品(名称);
  return { 名称: 物.名称, 类型: 物.类型, 氛围: 物.氛围, 在哪 };
};
// 一张床摆在一号房, 一件装饰摆在二号房, 一件在仓库
const 家 = () => [造('折叠床', '一号·北'), 造('素色窗帘', '二号·西'), 造('恒温灯', '')];

const 取 = (格子们, 方位) => 格子们.find(格 => 格.方位 === 方位);

console.log('--- L2: 九个格子, 顺序就是铺进网格的顺序 ---');
const 二层 = L.二层格子(家());
等于(二层.length, 9, '九个');
等于(二层.map(格 => 格.方位), [...T.方位序], '按 方位序 排 —— 错了整张图会转个个儿');
等于(二层.map(格 => 格.类), T.二层房型.map(格 => 格.类), '格类照房型图');

console.log('--- L2: 房间卡显示「有没有床」(spec §4.1) ---');
等于(取(二层, '西北').主, '一号', '一号房');
等于(取(二层, '西北').副, '▶ 床位 1', '有床的房间写床位几');
等于(取(二层, '北').主, '二号', '二号房');
等于(取(二层, '北').副, '▶ 空着', '没床的房间写空着');
断言(二层.filter(格 => 格.类 === '房间').every(格 => 格.可点), '房间格都可以点 (点它进 L3)');
断言(二层.filter(格 => 格.类 === '房间').every(格 => !格.副.includes('undefined')), '副标题里不该出现 undefined');

console.log('--- L2: 门与路 ---');
等于(取(二层, '南').主, '门', '门在南格');
等于(取(二层, '南').可点, true, '门可以点 (① 里是收起家园块回正文)');
等于(取(二层, '南').副, '返回', '副标题写明点它干嘛');
断言(二层.filter(格 => 格.类 === '路').every(格 => !格.可点), '三条过道点不动');
断言(二层.filter(格 => 格.类 === '路').every(格 => 格.主 === ''), '过道不写字 —— 三格连成一条带子才看得出是过道');

console.log('--- L3: 一间房 ---');
const 三层 = L.三层格子(家(), '一号');
等于(三层.length, 9, '九个');
等于(三层.map(格 => 格.方位), [...T.方位序], '外框与 L2 一致');
等于(取(三层, '北').主, '折叠床', '摆了东西的床格显示家具名');
等于(取(三层, '北').类, '床', '它的类还是 床');
等于(取(三层, '西北').主, '自由', '空格子显示它收什么');
等于(取(三层, '西北').类, '自由', '自由格');
等于(取(三层, '中').主, '门', '门在正中');
等于(取(三层, '中').副, '返回', 'L3 的门回 L2');
等于(取(三层, '西南').主, '', '灰格什么都不显示');
断言(取(三层, '西南').可点 === false, '灰格点不动');

console.log('--- L3: 只认自己这间房的家具 ---');
等于(取(L.三层格子(家(), '二号'), '西').主, '素色窗帘', '二号房西格是那件窗帘');
等于(取(L.三层格子(家(), '二号'), '北').主, '空床', '二号房没床, 床格显示空床');
等于(取(L.三层格子(家(), '三号'), '北').主, '空床', '三号房也没床');
等于(取(L.三层格子(家(), '三号'), '西').主, '自由', '三号房西格空着');
断言(L.三层格子(家(), '一号').every(格 => 格.主 !== '恒温灯'), '仓库里那件不该出现在任何房间里');

console.log('--- 可点的格子 ---');
断言(取(三层, '北').可点 && 取(三层, '西北').可点, '床格与自由格都可点 (点开商店)');
断言(取(三层, '中').可点, '门可点');
等于(三层.filter(格 => 格.可点).length, 6, 'L3 实的 6 格: 4 自由 + 1 床 + 1 门');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
