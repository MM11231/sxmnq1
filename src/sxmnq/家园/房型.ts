/**
 * 两层房型图。**是代码常量, 不是变量** —— 一层的地形是写死的, 玩家改不动它
 * (spec §4.2)。
 *
 * 九宫格的**外框三层保持一致** (西北/北/东北 · 西/中/东 · 西南/南/东南),
 * 只是「哪些格是实的」不同:
 *
 *   L2 诊所    一号  二号  三号        上排三间、下排两间夹着门,
 *              路    路    路          中间一整条横向过道
 *              四号  门    五号
 *
 *   L3 一间房  自由  床    自由        实的 6 格 + 灰的 3 格,
 *              自由  门    自由        床和门都在中列
 *              路    路    路
 */
import type { 家具类型 } from './物品';

export const 方位序 = ['西北', '北', '东北', '西', '中', '东', '西南', '南', '东南'] as const;
export type 方位 = (typeof 方位序)[number];

/** 这一格**是干什么的** —— 决定颜色、能不能点、点了做什么 (spec §4.1) */
export type 格类 = '房间' | '床' | '自由' | '门' | '路';

export interface 格 {
  方位: 方位;
  类: 格类;
  /** 只有 `类 = '房间'` 有。它同时是 在哪 里的房间名, 如 `一号` (spec §8) */
  房名?: string;
}

/** L2 · 诊所的五个房间。开局只有一号房有床, 其余四间空着等你买。 */
export const 二层房型: readonly 格[] = [
  { 方位: '西北', 类: '房间', 房名: '一号' },
  { 方位: '北', 类: '房间', 房名: '二号' },
  { 方位: '东北', 类: '房间', 房名: '三号' },
  { 方位: '西', 类: '路' },
  { 方位: '中', 类: '路' },
  { 方位: '东', 类: '路' },
  { 方位: '西南', 类: '房间', 房名: '四号' },
  { 方位: '南', 类: '门' },
  { 方位: '东南', 类: '房间', 房名: '五号' },
];

/** 五个房间, 按房型图上的顺序。存档迁移要往第一间播种, 所以顺序是有意义的 (§8.1) */
export const 房间名表: readonly string[] = ['一号', '二号', '三号', '四号', '五号'];

/** 开局那张床摆在哪 —— 第一间房的北格 (spec §8.1 的存档迁移照它播种) */
export const 开局床位 = `${房间名表[0]}·北`;

/** L3 · 一间房。**五间房共用这一张图** —— 每间房长得一模一样。 */
export const 三层房型: readonly 格[] = [
  { 方位: '西北', 类: '自由' },
  { 方位: '北', 类: '床' },
  { 方位: '东北', 类: '自由' },
  { 方位: '西', 类: '自由' },
  { 方位: '中', 类: '门' },
  { 方位: '东', 类: '自由' },
  { 方位: '西南', 类: '路' },
  { 方位: '南', 类: '路' },
  { 方位: '东南', 类: '路' },
];

/**
 * 这种格子收哪一类家具。`null` = 不收东西。
 *
 * 这**一条规则**同时管住了两件事 (spec §4.1/§5): 弹层里列什么, 以及
 * 类型不匹配的东西根本不出现在那儿。
 */
export function 格收什么类(格: 格): 家具类型 | null {
  if (格.类 === '床') return '床';
  if (格.类 === '自由') return '装饰';
  return null;
}
