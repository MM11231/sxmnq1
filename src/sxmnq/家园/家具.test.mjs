// 直接跑: node src/sxmnq/家园/家具.test.mjs
//
// 这个模块里最值钱的两条性质:
//   1. **只有摆出来的算数** —— 仓库里的家具不产气氛、不占床位
//   2. **动作按「序」不按「名称」** —— 同款买两件时名称分不出是哪一件
import '../测试钩子.mjs';

const F = await import(new URL('./家具.ts', import.meta.url).href);
const I = await import(new URL('./物品.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};

/** 照物品表造一件 —— 数值不与表脱钩 */
const 造 = (名称, 在哪) => {
  const 物 = I.找物品(名称);
  if (!物) throw Error(`物品表里没有 ${名称}`);
  return { 名称: 物.名称, 类型: 物.类型, 氛围: 物.氛围, 在哪 };
};

const 一副 = () => [
  造('折叠床', '一号·北'),   // 0
  造('单人床', '二号·北'),   // 1
  造('素色窗帘', '一号·西'), // 2
  造('旧书架', '二号·西'),   // 3
  造('恒温灯', ''),          // 4 ← 在仓库
];

console.log('--- 在哪 的格式 (spec §8) ---');
等于(F.房间名('一号·北'), '一号', '一号·北 的房间名是一号');
等于(F.房间名('五号·东南'), '五号', '最后一个房间也一样');
等于(F.房间名(''), '', '空字符串 = 还在仓库, 房间名也是空');

console.log('--- 仓库 = 买了没摆的 (spec §6.3) ---');
等于(F.算仓库(一副()).map(项 => 项.件.名称), ['恒温灯'], '只有那件 在哪 为空的');
等于(F.算仓库(一副())[0].序, 4, '带出来的是它在数组里的下标 —— 动作靠它认人');
等于(F.算仓库([]), [], '一件都没有 → 空');

console.log('--- 摆位: 键是 房间·方位 (spec §8) ---');
const 摆位 = F.算摆位(一副());
等于(Object.keys(摆位).sort(), ['一号·北', '一号·西', '二号·北', '二号·西'], '仓库里那件不在摆位里');
等于(摆位['一号·北'].件.名称, '折叠床', '一号房的北格摆着折叠床');
等于(摆位['一号·北'].序, 0, '带出来的是数组下标');

console.log('--- 床位 = 摆出来的床有几张 (spec §7.1) ---');
等于(F.算床位(一副()), 2, '两张床摆着 → 2 (仓库里那件是灯, 不算)');
等于(F.算床位([造('折叠床', '')]), 0, '床买来放仓库不占床位');
等于(F.算床位([]), 0, '空数组 → 0');

console.log('--- 气氛 = 摆出来的氛围之和, 不封顶 (spec §7.2) ---');
等于(F.算气氛(一副()), 10 + 25 + 8 + 12, '55 —— 仓库那件 +22 不算在内');
等于(F.算气氛([造('诊疗床', '')]), 0, '放仓库不产气氛');
等于(F.算气氛([]), 0, '空 → 0');

console.log('--- 气氛换来的信赖加成, 硬上限 +5 (spec §7.2) ---');
等于(F.算信赖加成(0), 0, '0 → +0');
等于(F.算信赖加成(19), 0, '19 → +0 (差一分)');
等于(F.算信赖加成(20), 1, '20 → +1');
等于(F.算信赖加成(39), 1, '39 → +1');
等于(F.算信赖加成(40), 2, '40 → +2');
等于(F.算信赖加成(55), 2, '假数据那副 55 → +2');
等于(F.算信赖加成(100), 5, '100 → +5, 撞到天花板');
等于(F.算信赖加成(900), 5, '再多也是 +5');

console.log('--- 气氛的档位描述 (spec §9.3) ---');
等于(F.气氛档(0), '有点冷清', '0–19');
等于(F.气氛档(19), '有点冷清', '上界含在冷清里');
等于(F.气氛档(20), '还算整洁', '20–39');
等于(F.气氛档(39), '还算整洁', '上界');
等于(F.气氛档(40), '待着舒服', '40–59');
等于(F.气氛档(59), '待着舒服', '上界');
等于(F.气氛档(60), '让人不想走', '60 以上');
等于(F.气氛档(999), '不想走'.replace('不想走', '让人不想走'), '再多也就这一档');

console.log('--- 一个房间里有什么 (L2 的房间卡副标题) ---');
等于(F.房间概况(一副(), '一号'), { 床: 1, 件: 2, 氛围: 18 }, '一号房: 一张床一件窗帘');
等于(F.房间概况(一副(), '三号'), { 床: 0, 件: 0, 氛围: 0 }, '三号房空着');
断言(F.房间概况(一副(), '一号').床 === 1, '只数这个房间的, 不串到二号房去');

console.log('--- 开局播种 (spec §8.1) ---');
const 开局 = F.开局家具();
等于(开局.length, 1, '就一张');
等于(开局[0].名称, '折叠床', '折叠床');
等于(开局[0].类型, '床', '类型是床');
等于(开局[0].在哪, '一号·北', '摆在一号房的北格');
等于(开局[0].氛围, I.找物品('折叠床').氛围, '氛围照物品表, 不另写一个数 —— 否则改表时这里会悄悄脱钩');
等于(F.算床位(开局), 1, '开局床位是 1 (改动前那个写死的数字也是 1)');
等于(F.算气氛(开局), 10, '开局气氛 10');

console.log('--- 动作: 收起来 = 退回仓库, 不是卖掉 (spec §5) ---');
const 甲 = 一副();
F.收起来(甲, '一号·北');
等于(甲[0].在哪, '', '那件家具的 在哪 清空了');
等于(F.算床位(甲), 1, '床位跟着掉到 1');
等于(F.算仓库(甲).length, 2, '仓库里多了一件');
等于(甲.length, 5, '**没有删掉它** —— 收起来的床还能摆进另一间空房');
F.收起来(甲, '三号·东');
等于(甲.length, 5, '收一个空格子什么也不发生');

console.log('--- 动作: 买来直接摆进这个格子 (spec §5) ---');
const 乙 = 一副();
const 诊疗床 = I.找物品('诊疗床');
F.摆上(乙, '二号·北', 诊疗床);
等于(F.算摆位(乙)['二号·北'].件.名称, '诊疗床', '新的摆上了');
等于(乙[1].在哪, '', '被换下来的单人床退回仓库, **不是消失**');
等于(F.算床位(乙), 2, '床位还是 2 —— 换床不涨床位');
等于(F.算气氛(乙), 10 + 45 + 8 + 12, '气氛 75 —— 换更好的床就是房间更舒服');

const 丙 = [造('折叠床', '')];
F.摆上(丙, '一号·北', 诊疗床);
等于(F.算床位(丙), 1, '空格子上买 → 床位 1');
等于(丙.length, 2, '仓库那件还在, 没有被顶掉');

console.log('--- 动作: 从仓库摆进去 (spec §5 的「这里能放的」) ---');
const 丁 = 一副();
F.从仓库摆(丁, 4, '三号·北');
等于(丁[4].在哪, '三号·北', '仓库那件摆进去了');
等于(F.算仓库(丁).length, 0, '仓库空了');
F.从仓库摆(丁, 4, '一号·北');
等于(丁[4].在哪, '一号·北', '再摆一次 —— 挪到另一格');
等于(丁[0].在哪, '', '原来那格的折叠床退回仓库');
等于(丁.length, 5, '**一件都没多也一件都没少**');
F.从仓库摆(丁, 99, '二号·东');
等于(丁.length, 5, '序号不存在 → 什么也不做, 不抛');

console.log('--- 同款两件: 动作必须按「序」而不是按「名称」 ---');
const 戊 = [造('折叠床', '一号·北'), 造('折叠床', '二号·北')];
F.收起来(戊, '一号·北');
等于(戊[0].在哪, '', '只收起了一号房那件');
等于(戊[1].在哪, '二号·北', '二号房那件纹丝不动');
等于(F.算床位(戊), 1, '床位掉到 1');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
