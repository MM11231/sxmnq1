// 直接跑: node src/sxmnq/地图/平面图.test.mjs
//
// 图纸的失败**全是静默的**: 少写一格的坐标, 那格根本不出现 —— 面包屑照走、别的格照点,
// 看起来只是「这张图少了一个房间」, 不像报错。摆错方位也一样安静: 北翼画到下面去,
// 玩家只会觉得「这图怎么跟我记的不一样」。
//
// 所以这里只钉两件事, 但那两件是这张图能看的前提:
//   1. 图上每一格都有坐标, 坐标里的每一格都在图上 (两边都不许有空的)
//   2. 摆位跟世界书说的方位对得上
//
// 另外顺手挡掉「画出纸外」—— 那也是一样安静: 元素画在 150% 的地方, 屏幕上什么都没有。
import './../测试钩子.mjs';

const 数 = await import(new URL('./数据.ts', import.meta.url).href);
const 图 = await import(new URL('./平面图.ts', import.meta.url).href);
const { 世界地图, 白塔地图 } = 数;
const { 世界图, 塔内图 } = 图;

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};

/** 层 → 它的图纸。改层名的时候这里会红, 正好提醒两份得对上。 */
const 配对 = [
  { 层: 世界地图, 纸: 世界图, 叫: '世界大地图' },
  { 层: 白塔地图, 纸: 塔内图, 叫: '白塔内部' },
];

console.log('--- ★ 纸上的格子和数据里的格子, 一一对上 (少一个就是那格不出现) ---');
配对.forEach(({ 层, 纸, 叫 }) => {
  const 该有 = 层.格.filter(Boolean).map(格 => 格.id);
  const 画了 = Object.keys(纸.位);
  该有.forEach(id => 断言(画了.includes(id), `「${叫}」的 ${id} 有坐标 (没有就整格不出现, 不报错)`));
  // 反过来: 坐标表里躺着一个没人认领的 id, 就是死数据 —— 而且你根本看不出它没画出来,
  // 因为「没画出来」和「不存在」在屏幕上长得一样。
  画了.forEach(id => 断言(该有.includes(id), `坐标表里的 ${id} 在「${叫}」上有对应的格子 (没人在用的坐标就是死数据)`));
  断言(画了.length === 该有.length, `「${叫}」两边数量一样 (数据 ${该有.length} / 坐标 ${画了.length})`);
});

console.log('--- ★ 谁都不许画到纸外面去 ---');
配对.forEach(({ 纸, 叫 }) => {
  Object.entries(纸.位).forEach(([id, 块]) => {
    const 好 = 块.w > 0 && 块.h > 0 && 块.x >= 0 && 块.y >= 0 && 块.x + 块.w <= 100 && 块.y + 块.h <= 100;
    断言(好, `「${叫}」的 ${id} 整块都在 0-100 里 (画出去 = 屏幕上什么都没有)`);
  });
  纸.廊.forEach((廊, i) => {
    断言(廊.x >= 0 && 廊.y >= 0 && 廊.x + 廊.w <= 100 && 廊.y + 廊.h <= 100, `「${叫}」第 ${i + 1} 条走廊在纸内`);
  });
  纸.饰.forEach((饰, i) => {
    断言(饰.x >= 0 && 饰.x <= 100 && 饰.y >= 0 && 饰.y <= 100, `「${叫}」第 ${i + 1} 个点缀在纸内`);
  });
});

console.log('--- ★ 房间不许叠在一起 (叠了就是一层盖住另一层, 不报错) ---');
配对.forEach(({ 纸, 叫 }) => {
  const 项 = Object.entries(纸.位);
  for (let i = 0; i < 项.length; i++) {
    for (let j = i + 1; j < 项.length; j++) {
      const [甲, a] = 项[i];
      const [乙, b] = 项[j];
      const 碰上 = a.x < b.x + b.w && b.x < a.x + a.w && a.y < b.y + b.h && b.y < a.y + a.h;
      断言(!碰上, `「${叫}」的 ${甲} 和 ${乙} 不重叠`);
    }
  }
});

console.log('--- ★ 摆位照世界书: 说北的就得在北边 ---');
// 世界书「世界 - 白塔」: 「位于大陆中央」。四个特区: 北端 / 南端 / 东侧 / 西端。
const 世 = 世界图.位;
const 塔 = 世.tower;
断言(世.north.y + 世.north.h <= 塔.y, '极北在白塔上方');
断言(世.south.y >= 塔.y + 塔.h, '极南在白塔下方');
断言(世.west.x + 世.west.w <= 塔.x, '极西在白塔左边');
断言(世.east.x >= 塔.x + 塔.w, '极东在白塔右边');
// 世界书「地点 - 深渊地块」: 「四大区交界处的地下裂隙网络」—— 交界处就是紧挨着白塔那一圈。
const 塔心 = { x: 塔.x + 塔.w / 2, y: 塔.y + 塔.h / 2 };
const 渊心 = { x: 世.abyss.x + 世.abyss.w / 2, y: 世.abyss.y + 世.abyss.h / 2 };
const 离塔 = Math.max(Math.abs(渊心.x - 塔心.x) - 塔.w / 2, Math.abs(渊心.y - 塔心.y) - 塔.h / 2);
断言(离塔 < 20, `深渊贴着白塔那一圈 (交界处; 实得离白塔边缘约 ${离塔.toFixed(1)}%)`);

// 白塔内部。世界书: 治疗中心=北翼 / 维护站=治疗中心东侧附属 / 训练场=西翼 /
// 任务大厅=核心区一层中庭 / 宿舍区=东翼 / 商业区=南翼地面二层。
const 内 = 塔内图.位;
const 厅 = 内.mission;
断言(内.medical.y + 内.medical.h <= 厅.y, '治疗中心在任务大厅上方 (北翼)');
断言(内.commercial.y >= 厅.y + 厅.h, '商业区在任务大厅下方 (南翼)');
断言(内.training.x + 内.training.w <= 厅.x, '训练场在任务大厅左边 (西翼)');
断言(内.dorm.x >= 厅.x + 厅.w, '宿舍区在任务大厅右边 (东翼)');
断言(内.inhibitor.x >= 内.medical.x + 内.medical.w, '维护站在治疗中心东侧 (世界书: 东侧附属)');
// 「核心区一层中庭」—— 中庭是正当中, 不是偏在一角。
断言(Math.abs(厅.x + 厅.w / 2 - 50) < 3, `任务大厅横向居正中 (中庭; 实得中心在 ${(厅.x + 厅.w / 2).toFixed(1)}%)`);

console.log('--- 走廊把该连的连上 (每条至少挨着两块地方) ---');
配对.forEach(({ 纸, 叫 }) => {
  const 地方 = [
    ...Object.entries(纸.位).map(([id, b]) => ({ id, b })),
  ];
  const 碰得上 = (a, b) => a.x < b.x + b.w && b.x < a.x + a.w && a.y < b.y + b.h && b.y < a.y + a.h;
  纸.廊.forEach((廊, i) => {
    const 挨着 = 地方.filter(({ b }) => 碰得上(廊, b)).map(({ id }) => id);
    断言(挨着.length >= 2, `「${叫}」第 ${i + 1} 条走廊真的连上了两块地方 (实得连上 ${挨着.join('+') || '没有'})`);
  });
});

console.log('--- 图纸是横的 (参考图是横的; 竖过来房间名会挤成一列) ---');
配对.forEach(({ 纸, 叫 }) => {
  断言(纸.比 > 1.2, `「${叫}」的宽高比是横的 (实得 ${纸.比})`);
});

console.log('--- 点缀不许压在房间上 (压上去了就是房间名底下有朵花) ---');
配对.forEach(({ 纸, 叫 }) => {
  const 项 = Object.entries(纸.位);
  纸.饰.forEach((饰, i) => {
    const 压 = 项.some(([, b]) => 饰.x >= b.x && 饰.x <= b.x + b.w && 饰.y >= b.y && 饰.y <= b.y + b.h);
    断言(!压, `「${叫}」第 ${i + 1} 个点没压在房间上`);
  });
});

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
