// 平面图的**画法** —— 每一格画在纸上哪个位置。
//
// 为什么单独一个文件: `数据.ts` 是**生成**出来的(名/键/说明, 源头是老卡的 MAP_DATA),
// 重新生成会整个盖掉。而「治疗中心在图纸左上角那一块、宽 22% 高 16%」这种话是**手摆**
// 的, 生成不出来, 也不该混进生成物里。
//
// 为什么不继续用九宫格: 九宫格只能表达「右上 / 正中 / 左下」九个位置, 而世界书说的是
// 方位(北翼/西翼/东翼/南翼/核心区中庭/治疗中心东侧)。六个设施硬塞进九宫, 出来的是一张
// 表格, 不是一张图。改成手摆坐标之后, 每个方位都摆得下, 还能画走廊和点缀。
//
// **全部是百分比**, 相对画布。画布的宽高比在 `比` 里, 组件拿它撑 `aspect-ratio` ——
// 所以这张图在任何宽度下都是同一个形状, 只会整体缩放, 不会变形。
//
// ⚠ 这一份的失败**全是静默的**: 少写一格的坐标 → 那格根本不出现, 面包屑照走、别的格
//   照点, 看起来只是「这张图少了一个房间」。所以 `平面图.test.mjs` 拿断言把两件事钉死:
//     · 图上每一格都有坐标, 坐标里的每一格都在图上 (不许有一边是空的)
//     · 摆位跟世界书说的方位对得上 (北的就真的在上面)

/** 纸上一块地方。四个数都是相对画布的百分比 (0-100)。 */
export type 块 = {
  x: number;
  y: number;
  w: number;
  h: number;
  /** 填充纹理。`木` 是深色板条, `石` 是灰砖。抄的是参考图里那两种。 */
  样?: '木' | '石';
};

/** 撒在底纹上的点缀。 */
export type 点缀 = { x: number; y: number; 样: '花' | '水' | '木' };

export type 平面 = {
  /** 画布宽 / 高。组件拿它撑 aspect-ratio, 保证图纸不变形。 */
  比: number;
  /** 图纸上下的两块区域标, 像参考图的「城外 / 城内」。不填就不画。 */
  外标?: string;
  内标?: string;
  /** 格子 id(跟 `数据.ts` 里的 id 对上) → 它画在哪。 */
  位: Readonly<Record<string, 块>>;
  /** 走廊。就是一块窄条, 铺同样的板条纹理, 把两间房接起来。 */
  廊: ReadonlyArray<{ x: number; y: number; w: number; h: number }>;
  /** 底纹上的花和水池。纯装饰, 不接事件 —— 老卡那张图上也有。 */
  饰: ReadonlyArray<点缀>;
};

