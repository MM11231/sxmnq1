// 「玩家现在在哪一格」这条判断。
//
// 为什么单独一个文件、不写在 界面/地图/App.vue 里: 它是这张图上**唯一一条会静默
// 出错的逻辑**。写错了不会报错、不会崩、地图照画 —— 只是那一格永远不亮, 或者亮错格。
// 而 .vue 里的函数在这个仓里没有测试能碰到(测试是 node 直接跑 .mjs, 跑不了 .vue)。
// 挪出来就是为了让它进得了 schema.test.mjs 那一套。
//
// 数据在 `数据.ts`(那是生成出来的, 别往里加手写的东西 —— 重新生成会盖掉)。
import type { 格 } from './数据';

/**
 * 存档里那句「你在哪」跟这一格对不对得上。
 *
 * 比的是**包含**不是等于: 存档里那句话是 AI 写的, 长短不定 ——
 * 「任务大厅」「白塔·任务大厅」「任务大厅的前台受理区」都该算在任务大厅。
 *
 * 代价是**会同时点亮多格**: 存档写「白塔·任务大厅」时, 世界地图上那格「白塔」和
 * 白塔地图上那格「任务大厅」都亮。这是故意的 —— 你确实同时在白塔里、也在任务大厅里,
 * 只是这两格分属两层, 一屏只会看见其中一格。
 *
 * **`名` 和 `键` 两个都比**, 因为存档里那句话有两个来源, 两边的用词不一样:
 *   - 玩家用 `@` 移步 → 写进去的是 `写`(世界书里的全名, 如「抑制器维护站」)。
 *   - AI 写正文 → 它多半照着 `名` 来(「维护站」), 不会知道 `键` 是什么。
 * 只认门当户对的那一个, 另一条路就点不亮, 而且不报错。
 *
 * 所以 `写` 必须含 `键`(移步之后自己得亮), 这条由测试钉住。
 */
export function 是不是这格(格: 格, 玩家在哪: string): boolean {
  const 地 = String(玩家在哪 ?? '').trim();
  if (!地) return false;
  return 地.includes(格.键) || 地.includes(格.名);
}
