/** 地图上的一格。`null` = 空槽, 渲染成虚线框占位。 */
export type 格 = {
  id: string;
  /** 格子上的大字, 比如「任务大厅」。 */
  名: string;
  /** 大字底下的小字, 比如「接单/组队」。 */
  副?: string;
  /**
   * 跟存档里 `世界.地点` 比对用的**关键词**。
   * 比的是「包含」不是「等于」—— 存档里可能写「白塔·任务大厅前台」,
   * 而关键词是「任务大厅」。见 `认出在哪格`。
   */
  键: string;
  /** 点开这格弹出来的说明。没有就是点不出说明(只能钻)。 */
  说?: string;
  /** 这一格底下还有一层。 */
  可钻?: boolean;
  /**
   * 「移步」时**写进存档**的地名。不填就用 `名`。
   *
   * 为什么单独留一个字段: 高亮是拿存档里的 `世界.地点` 去 `includes` 每一格的
   * `键`。老卡格子上写「维护站」而它的 `键` 是「抑制器」—— 移过去之后下一次
   * 刷新这格就不亮了, 而且**不报错**, 看起来只是「地图高亮时灵时不灵」。
   * 所以写世界书里的全名(「抑制器维护站」「觉醒者宿舍区」)。
   */
  写?: string;
};

/**
 * 一格的三行字：大字、小字、说明。
 * 单独拎出来是因为「说明」有两种来源 —— 分区自带一句, 房间明细里另有一句;
 * 房间明细优先(它更具体)。这个选择只该有一处, 所以不散在模板里写。
 */
export type 层 = {
  /** 面包屑上显示的名字, 也用来认「现在在第几层」。 */
  名: string;
  /** 九格。`null` 是空槽。 */
  格: ReadonlyArray<格 | null>;
};

