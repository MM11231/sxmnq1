//   `.prefault('待接')` 的**缺失兜底**一直没人验 —— 把整键删掉是它唯一的回归保护。
//   它跟「值写坏」是两条不同的路: 值写坏走 transform, 键不在走 prefault。
const 无状态条 = { ...Object.values(假变量.stat_data.今日.申请列表)[0] };
delete 无状态条.状态;
