console.log('--- ★ 申请列表.状态: 写坏一个字只毁这一条, 不毁存档 ---');
// 这个洞**一直开着**, 不是「2026-10-06 才变成必须」: 旧世界书本来就指令 AI 写这个
// 字段 (旧「待登记/登场」段里那句「主角在正文里明确把人打发走时, 把 状态 改成
// 「已婉拒」」), 那时没炸只是因为被指令写的那个值**正好在 enum 里** —— 写「婉拒」
// (少一个字) 就会让整份存档报废。
// 配套的另一半**已经落地** (2026-10-06「名单直出」Task 5): 世界书改成「【你】不要写
// `状态`」了。但落地的是**提示词**, 不是闸门 —— 下面这组断言照样成立, 因为 schema
// 依旧拦不住 AI 自己写 `已婉拒`。世界书那句话的措辞是这条契约**唯一**的防线,
// 见本文件末尾那条「不要把旧行为的原文抄一遍」的测试。
// 而名单从此每轮都进提示词 (变量列表 把整份 stat_data 注进提示词), 它读得更勤,
// 伸手改的时候带的还是**它自己的用词**。
//
// 状态 原本是 z.enum(['待接','已接','已婉拒']), enum 认不出就 safeParse 整体失败,
// util/mvu.ts 的 2 秒轮询与 watch 两处都是 `if (result.error) return`,
// 界面上只表现为「所有数字不再变」—— 一条错都不报。这正是这个仓最怕的失败。
const 造状态 = (状) => {
  const 底 = Object.values(假变量.stat_data.今日.申请列表)[0];
  return Schema.safeParse({
    ...假变量.stat_data,
    今日: { ...假变量.stat_data.今日, 申请列表: { 沈砚: { ...底, 状态: 状 } } },
  });
};
// ★ 后五个是**非字符串**: AI 的输出不带类型, 它完全可能把状态写成 null (想清掉这一格)、
//   写成数字码 (照 等级 的样子)、写成布尔, 或者把整个对象/数组塞进来。这些值一个都
//   不能毁掉整份 stat_data —— 这正是这条断言要买的东西。
for (const 坏 of ['婉拒', '已拒绝', '待诊', '待 接', '', null, 3, true, [], {}]) {
  const 果 = 造状态(坏);
  断言(果.success, `状态写成 ${JSON.stringify(坏)} 时整份存档仍然解析成功`);
  断言(果.success && 果.data.今日.申请列表.沈砚.状态 === '待接', `  ${JSON.stringify(坏)} 被收窄回「待接」`);
}
// ★ 控制组: 三个**认得**的值一个都不能被收窄掉。少了这一段, 一个「永远返回待接」
//   的坏 transform 也能让上面每一条全绿 —— 那是拿坏仪表验阴性断言。
for (const 好 of ['待接', '已接', '已婉拒']) {
  const 果 = 造状态(好);
  断言(果.success && 果.data.今日.申请列表.沈砚.状态 === 好, `控制组: 「${好}」原样保留`);
}

