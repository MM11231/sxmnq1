// 直接跑: node src/sxmnq/schema.test.mjs
//
// 这个测试存在的唯一理由: schema 改动引发的失败是**静默**的。
// ts-loader 是 transpileOnly, 枚举值写错不在构建期报错; MVU 那边 safeParse 失败
// 直接把整份数据丢掉(util/mvu.ts: `if (result.error) return`), 界面上只表现为
// 「所有数字都变成了默认值」—— 看起来像数据没加载, 而不是像代码错了。
//
// 所以每动一次 schema, 就拿真实的预览假数据过一遍 safeParse。
//
import './测试钩子.mjs';

const { Schema } = await import(new URL('./schema.ts', import.meta.url).href);
const { 假变量 } = await import(new URL('../预览/假数据.ts', import.meta.url).href);
const F = await import(new URL('./家园/家具.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};

console.log('--- 假数据能过 schema (不过的话预览里一切数字都是假的) ---');
const 果 = Schema.safeParse(假变量.stat_data);
if (!果.success) {
  console.log(JSON.stringify(果.error.issues, null, 2));
}
断言(果.success, 'safeParse 通过');
if (!果.success) {
  console.log('\n1 项失败');
  process.exit(1);
}
const 数 = 果.data;

console.log('--- 五档 ---');
等于(数.诊所.等级, 'C', '诊所.等级 读到了 C');
等于(数.诊所.$称号, '略有耳闻', '$称号 由 等级 算出 (C → 略有耳闻, 见 spec §3.2 称号表)');
断言(!('星级' in 数.诊所), '星级 字段已删除');
断言(!('诊室等级' in 数.诊所), '诊室等级 字段已删除');
断言(!('躺椅等级' in 数.诊所), '躺椅等级 字段已删除');
断言(!('减耗' in 数.诊所), '减耗 字段已删除');
断言(!('床位' in 数.诊所), '床位 不再是变量 —— 它由 算床位(家具) 现算 (spec §7.1)');
断言('气氛' in 数.诊所, '气氛 是变量 (持久化的派生值)');
等于(数.诊所.气氛, 55, '气氛 = 已摆放的氛围之和 (10+25+8+12), 仓库那件 +22 不算');
等于(F.算床位(数.诊所.家具), 2, '床位 从家具数出来 = 2, 与改动前那个写死的 2 一致');
断言(!('执业等级' in 数.主角), '执业等级 字段已删除');

console.log('--- 假数据里每个人的等级都是五档之一 ---');
const 五档 = new Set(['D', 'C', 'B', 'A', 'S']);
const 申请等级们 = Object.values(数.今日.申请列表).map(项 => 项.等级);
const 哨兵等级们 = Object.values(数.哨兵).map(项 => 项.等级);
断言([...申请等级们, ...哨兵等级们].every(级 => 五档.has(级)), '申请列表与哨兵里没有 F/E 这种旧档');

console.log('--- 旧档会被拒 ---');
const 坏 = structuredClone(假变量.stat_data);
坏.哨兵.白露.等级 = 'E';
断言(!Schema.safeParse(坏).success, "等级写 'E' 时 safeParse 失败 (这正是那个静默坑)");

console.log('--- 今日.登场: AI 报到的口子 (spec §5.1) ---');
断言(Array.isArray(数.今日.登场), '今日 有 登场 这个字段, 且是数组');
// 用 `?.` 而不是 `.` —— 字段还没加的时候 `.length` 会抛异常, 整个测试文件当场中断,
// 后面三条断言一条都跑不到, RED 就只剩一行。`?.length === 0` 在两种情况下都对。
断言(数.今日.登场?.length === 0, '假数据里 登场 是空的 (非空的话预览一开就会吃掉一张待登记单子)');

// 一个只写了 姓名 的报到 —— 这是最常见的样子, AI 只会写它关心的那个字段
const 报到 = Schema.parse({ ...假变量.stat_data, 今日: { ...假变量.stat_data.今日, 登场: [{ 姓名: '沈砚' }] } });
等于(报到.今日.登场[0].战损来源, '', '登场 只写 姓名 时, 战损来源 补空串 (缺 prefault 的话整份数据会被丢掉)');
等于(报到.今日.登场[0].自创, false, '登场 没写 自创 时补 false —— ★ 不是 true, 否则每次报到都白烧一张申请单');

// 老存档: 整个 登场 字段都不在
const 老存档 = Schema.parse({ ...假变量.stat_data, 今日: { 已生成于: '霜降月第一日', 待登记: [], 申请列表: {} } });
断言(Array.isArray(老存档.今日.登场), '老存档没有 登场 字段时, prefault 出空数组 (零迁移)');

console.log('--- 今日.登场: 形状写歪也要兜住 ---');
// `登场` 是 AI 每楼新写的**嵌套对象**, 比原来那个扁平的 待登记[i].姓名 更容易歪。
// 歪一下的代价不是「这一条没收下」, 而是**整份 stat_data 解析失败**: util/mvu.ts 的
// 2 秒轮询与 watch 两处都是 `if (result.error) return`, 界面上只表现为
// 「所有数字不再变」, 一条错都报不出来 —— schema.ts 开头自己写着这是最怕的那种失败。
//
// 用 safeParse 而不是 parse: parse 会抛异常当场中断整个文件, 后面的断言一条都跑不到,
// RED 就只剩一行堆栈, 看不出是哪条判据挂了。
const 歪 = (登场, 说明) => {
  const r = Schema.safeParse({ ...假变量.stat_data, 今日: { ...假变量.stat_data.今日, 登场 } });
  断言(r.success, `${说明} —— 整份 stat_data 仍要解析成功`);
  return r.success ? r.data : null;
};

// 最像的一种歪法: 它以为这里只放名字 (旧契约就是「回填一个姓名」, 惯性很大)
const 裸串 = 歪(['沈砚'], 'AI 把 登场 写成裸名字的数组');
if (裸串) {
  等于(裸串.今日.登场[0].姓名, '沈砚', '  裸名字当成人名收下, 而不是丢掉这个人');
  等于(裸串.今日.登场[0].自创, false, '  裸名字没给 自创 信号, 按 false 占一张单子');
  等于(裸串.今日.登场[0].战损来源, '', '  裸名字没有 战损来源, 补空串');
}

// 掺坏一条: 重点是**别的条和 stat_data 的其它部分要活着**
const 掺坏 = 歪([123, { 姓名: '沈砚' }], '一批里混进一条写坏的 (数字)');
if (掺坏) {
  等于(掺坏.今日.登场.length, 2, '  一条写坏不该让同批别的条一起消失');
  等于(掺坏.今日.登场[0].姓名, '', '  写坏的那条退化成空姓名 —— 处理登场 会跳过它 (流转.ts:167)');
  等于(掺坏.今日.登场[1].姓名, '沈砚', '  同批里写对的那条照常收下');
  等于(掺坏.世界.日期, 假变量.stat_data.世界.日期, '  ★ stat_data 的其它部分照常解析 (这才是要防的「整份报废」)');
}

console.log('--- 档案形状三个结构共用 ---');
const 待 = 数.今日.待登记[0];
断言(!!待 && !!待.精神体 && Array.isArray(待.特征), '待登记 条目有 精神体 与 特征');
断言(待.姓名 === '' && 待.战损来源 === '', '待登记 的 姓名/战损来源 是空的 (等 AI 填)');
// 别把日期写死 —— 真正的不变量是「已生成于 与 世界.日期 逐字相等」。
// 两者不等的话, 盯住日期 一挂载就会重掷一批, 把假数据里手写的 申请列表 整个清空
// (预览里踩过一次)。写死字面量只会在改假数据时变成一个看不懂的 FAIL。
等于(数.今日.已生成于, 数.世界.日期, '今日.已生成于 与 世界.日期 相等 —— 否则预览一开就重掷');
const 某申请 = Object.values(数.今日.申请列表)[0];
断言(!!某申请.精神体.纲, '申请列表 条目带着 精神体');
// 哨兵 是顶层字段, 不在 今日 底下 (计划里写成了 数.今日.哨兵, 是笔误)
断言(!('精神体' in (Object.values(数.哨兵)[0] ?? {})) || !!Object.values(数.哨兵)[0].精神体.纲, '哨兵 条目也带着 精神体');

console.log('--- 每一条记录都齐了 (漏一个字段 zod 会静默填默认值, 界面上看不出来) ---');
let 都齐 = true;
const 查 = (结构名, 项, 要战损) => {
  const 缺 = ['年龄', '地域', 'A面', 'B面']
    .filter(键 => !项[键])
    .concat(项.精神体?.纲 ? [] : ['精神体.纲'])
    .concat(项.特征?.length ? [] : ['特征'])
    .concat(要战损 && !项.战损来源 ? ['战损来源'] : []);
  if (缺.length) {
    断言(false, `${结构名} 缺字段: ${缺.join(' / ')}`);
    都齐 = false;
  }
};
数.今日.待登记.forEach((项, i) => 查(`待登记[${i}]`, 项, false)); // 姓名/战损来源 空着是设计
Object.entries(数.今日.申请列表).forEach(([名, 项]) => 查(`申请列表.${名}`, 项, true));
Object.entries(数.哨兵).forEach(([名, 项]) => 查(`哨兵.${名}`, 项, true));
断言(都齐, '三个结构里每一条记录都带着 年龄/地域/精神体/特征/A面/B面 (+ 申请列表与哨兵的 战损来源)');

console.log('--- 老存档迁移: 家具 为空就播种一张折叠床 (spec §8.1) ---');
// 老存档的样子: 有 `床位: 1`, 没有 `家具`。派生出来的床位会是 0 —— 等于把开局那张床弄丢了。
const 老 = Schema.parse({
  ...假变量.stat_data,
  诊所: { 名称: '听雨诊所', 等级: 'C', 名声: 43, 床位: 1 },
});
等于(F.算床位(老.诊所.家具), 1, '老存档那张写死的床补回来了');
等于(老.诊所.家具[0].名称, '折叠床', '补的是一张折叠床');
等于(老.诊所.家具[0].在哪, '一号·北', '摆在一号房的北格');
等于(老.诊所.气氛, 10, '气氛跟着算出来 10');
断言(!('床位' in 老.诊所), '解析结果里没有 床位 了');

const 再 = Schema.parse(老);
等于(再.诊所.家具.length, 1, '**幂等**: 再解析一次不会又播一张');

console.log('--- 世界 那一层是 2026-10-05 加的: 老存档不能因此整份挂掉 ---');
// 这是这一层最大的风险: MVU 每次 parse 的是**整份** stat_data, 这些字段只要有一个
// 没给 prefault, 老存档一加载就整体 safeParse 失败, 界面上表现成「数据全没了」。
// 所以这里喂一份**完全没有这些字段**的存档, 它必须照样解析成功。
const 无世界 = Schema.parse({ ...假变量.stat_data, 世界: { 日期: '霜降月第一日', 时段: '清晨', 地点: '诊所' } });
断言(无世界.世界.时刻 === '' && 无世界.世界.天气 === '', '老存档缺的字段补成空串, 不是整份解析失败');
等于(无世界.世界.近期事件, [], '老存档的 近期事件 补成空数组');
断言(无世界.世界.日期 === '霜降月第一日', '老存档自己有的字段原样留着');
// 报纸那两个数组同理 —— 这是第 3 期新加的, 每个老存档都没有它们。
等于(无世界.世界.报纸供稿, [], '老存档没有 报纸供稿 → 空数组 (报纸退回池子, 不空版)');
等于(无世界.世界.报纸投稿, [], '老存档没有 报纸投稿 → 空数组');

console.log('--- 近期事件 截断到最近 5 条 ---');
// 它是 AI 用 append 追加的, 界面又不显示全部 —— 不截的话它会一直长,
// 而整份 stat_data 每轮都会被 format_message_variable 注进提示词, 长的是 token。
const 六条 = Schema.parse({
  ...假变量.stat_data,
  世界: {
    ...假变量.stat_data.世界,
    近期事件: Array.from({ length: 6 }, (_, i) => ({ 名称: `势力${i}`, 状态: '进行中', 说明: `第 ${i} 条` })),
  },
});
等于(六条.世界.近期事件.length, 5, '六条只留五条');
等于(六条.世界.近期事件[0].名称, '势力1', '砍掉的是**最旧**那条, 不是最新那条');
等于(六条.世界.近期事件[4].名称, '势力5', '最新的那条还在');

console.log('--- 报纸供稿/投稿: 截断与收窄 ---');
const 一堆 = n => Array.from({ length: n }, (_, i) => ({ 日期: `日${i}`, 标题: `题${i}`, 正文: `文${i}` }));
const 截 = Schema.parse({ ...假变量.stat_data, 世界: { ...假变量.stat_data.世界, 报纸供稿: 一堆(7) } });
等于(截.世界.报纸供稿.length, 5, '七条供稿只留五条');
等于(截.世界.报纸供稿[0].标题, '题2', '砍掉的是最旧的');
// 投稿同理, 但它的元素还多一步 transform, 得确认截断没把 transform 绕过去。
const 截投 = Schema.parse({
  ...假变量.stat_data,
  世界: { ...假变量.stat_data.世界, 报纸投稿: Array.from({ length: 7 }, (_, i) => ({ 日期: `日${i}`, 版面: '社会', 标题: `题${i}`, 正文: 'x', 署名: 'y' })) },
});
等于(截投.世界.报纸投稿.length, 5, '七条投稿只留五条');
等于(截投.世界.报纸投稿[0].版面, '社会', '截剩下的投稿还带着它自己买的版面');

// 版面名写坏了不能连累整份存档 —— 这正是它用 z.string() 而不是 z.enum() 的理由。
// 用 enum 的话这里 safeParse 直接失败, 整个 store 退回默认值, 界面上是「数据全没了」。
const 坏版面 = Schema.safeParse({
  ...假变量.stat_data,
  世界: { ...假变量.stat_data.世界, 报纸投稿: [{ 日期: '三月十四', 版面: '头版头条', 标题: 't', 正文: 'b', 署名: 's' }] },
});
断言(坏版面.success, "投稿版面写成「头版头条」时整份存档**照样解析成功** (换成 enum 就全没了)");
等于(坏版面.success ? 坏版面.data.世界.报纸投稿[0].版面 : null, '广告', '认不出的版面收窄到分类广告, 不静默丢掉这一条');

// ★ 2026-10-05 改版把「要闻/经济/讣告/宣传」四个版面名废掉了。老存档里正躺着一批
//   用旧名字的投稿 (2026-10-05 之前的存档) —— 它们必须**照样解析成功**, 只是收窄成
//   分类广告版。这是上面那条 z.string() 决定真正要兜住的东西: 换成 enum, 一张旧卡
//   加载时整个 stat_data 会 safeParse 失败退回默认值, 玩家的存档看着就像没了。
const 旧版面 = ['宣传', '要闻', '经济', '讣告'];
const 旧存档 = Schema.safeParse({
  ...假变量.stat_data,
  世界: { ...假变量.stat_data.世界, 报纸投稿: 旧版面.map((b, i) => ({ 日期: `日${i}`, 版面: b, 标题: 't', 正文: 'b', 署名: 's' })) },
});
断言(旧存档.success, `四个旧版面名 (${旧版面.join('/')}) 全都解析得过去 —— 旧存档不会整个失效`);
断言(旧存档.success && 旧存档.data.世界.报纸投稿.length === 4, '四条旧投稿一条都没被丢掉');
断言(旧存档.success && 旧存档.data.世界.报纸投稿.every(稿 => 稿.版面 === '广告'), '它们被收窄到分类广告版, 而不是整条删掉');

console.log('--- 假数据把这一层填满了 (留空的话预览里那一行会被 v-if 整个挡掉) ---');
const 世 = 数.世界;
断言(!!世.时刻 && !!世.星期 && !!世.季节 && !!世.天气 && !!世.温度,
  '假数据的诊所页那一行渲染得出来');
断言(!!世.世界主线 && 世.近期事件.length > 0, '世界主线与近期事件也有值可看');
// 报纸那两个数组的日期必须对得上 —— 对不上的话预览里那份报纸会**静悄悄地**只剩
// 池子内容, 跟「供稿这条路根本没接上」长得一模一样, 而那正是预览唯一能验的东西。
断言(世.报纸供稿.every(条 => 条.日期 === 世.日期), '假数据的供稿日期对得上, 预览里能看到 AI 头条');
断言(世.报纸投稿.some(条 => 条.日期 === 世.日期), '假数据有一条**今天**的投稿 (嵌在版面里那条)');
断言(世.报纸投稿.some(条 => 条.日期 !== 世.日期), '假数据还留了一条往期的投稿 —— 不然「往期」那块永远渲染不到');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
