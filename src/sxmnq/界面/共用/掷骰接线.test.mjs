// 直接跑: node src/sxmnq/界面/共用/掷骰接线.test.mjs
//
// 这个测试守的是一个**真踩过的死循环**, 不是理论风险。
//
// 历史上那次事故是: watch 的源里带了 今日.登场 (该字段 2026-10-06 已随「名单直出」
// 删除), 而回调 (跑一次 → 处理登场) 每次都会把 登场 赋成一个**新数组**。
// 源要是「一个返回新数组的 getter」, Vue 用 Object.is 比容器 —— 新数组永远"变了",
// 于是每一轮 flush 都再叫一次回调, 回调再写一次, flushJobs 就自己递归下去。
// 渲染线程被占死, **一行日志都不打**。
//
// 字段没了, 但那条教训没变: 源里每多一项「会被回调改的东西」就是这个坑。
// 下面第一条测试现在盯的是同一件事的一般形式 —— 两项都要是 getter, 且都不是回调写的。
//
// 症状和判据: 点进主界面整个页面卡住, 控制台空白。
//
// 为什么要一个 node 测试而不是只在浏览器里看: 那个循环是同步的, 表现是「卡住」
// 不是「报错」, 在浏览器里既没栈也没日志, 只能靠 Debugger.pause 去抓。
// 这里用真实的 vue, 几毫秒就能判。
import '../../测试钩子.mjs';

const { ref, watch, nextTick } = await import('vue');
const { 盯的源, 盯住日期 } = await import(new URL('./掷骰接线.ts', import.meta.url).href);
const { 每日人数 } = await import(new URL('../../生成/生成.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};

/** 最小的接线源。数据得是响应式的, watch 才追得到。 */
const 造源 = () => {
  const 数据 = ref({
    日期: '霜降月第一日',
    等级: 'C',
    今日: { 已生成于: '霜降月第一日', 申请列表: {} },
    哨兵: {},
  });
  return {
    数据,
    源: {
      日期: () => 数据.value.日期,
      等级: () => 数据.value.等级,
      今日: () => 数据.value.今日,
      哨兵: () => 数据.value.哨兵,
    },
  };
};

console.log('--- ★ 源必须是「getter 数组」, 而且不盯回调自己写的字段 ---');
{
  const { 数据, 源 } = 造源();
  const 项 = 盯的源(源);
  断言(Array.isArray(项) && 项.length === 2, `盯的源 返回**两项**的数组 (实得 ${项.length} 项)`);
  断言(项.every(f => typeof f === 'function'), '每一项都是 getter —— 传值的话它一次都不会变');

  let 跑了几次 = 0;
  watch(
    盯的源(源),
    () => {
      跑了几次++;
      // 复刻 跑一次 里真正会发生的那两次写: 申请列表 与 已生成于。
      // **两个都不是源** —— 这正是「不再自我激荡」的结构性理由。
      //
      // 那个 `<= 20` 是**测试自己的刹车**, 不是生产逻辑 —— 真死循环时它是同步的,
      // 不加刹车 `await nextTick()` 永远不返回, 测试会挂住而不是失败。
      // 刹住之后循环会退出, 下面那条断言就能报出真实次数。
      if (跑了几次 <= 20) {
        数据.value.今日.申请列表 = { 沈砚: { 状态: '待接' } };
        数据.value.今日.已生成于 = '霜降月第一日';
      }
    },
    { immediate: true },
  );

  await nextTick();
  await nextTick();
  断言(跑了几次 <= 2, `回调写自己写的东西不会激荡 (实跑 ${跑了几次} 次; 20 次说明源在自我激荡)`);
}

console.log('--- ★ 盯住日期 真的把 申请列表 掷出来了 (不是"看着接线对了") ---');
{
  const { 数据, 源 } = 造源();
  // 必须先让 已生成于 与 日期 不等 —— 该掷了吗 的早退分支会让这条测试
  // **绿得很正常**, 而绿的原因是它根本没跑。我实测过这两个早退分支确实早退。
  数据.value.今日.已生成于 = '';
  断言(
    数据.value.今日.已生成于 !== 数据.value.日期,
    '(前置) 已生成于 与 日期 不等, 该掷了吗 才会放行',
  );

  盯住日期(源);

  const 键 = Object.keys(数据.value.今日.申请列表);
  等于(键.length, 每日人数('C'), '跑一次 按等级 C 掷出了正确的人数');
  等于(数据.value.今日.已生成于, '霜降月第一日', '掷完盖上了 已生成于 的日期戳');

  // 日期再变一次 → 昨天的名单整个作废, 换一批新的
  数据.value.日期 = '霜降月第二日';
  await nextTick();
  await nextTick();
  等于(数据.value.今日.已生成于, '霜降月第二日', '日期变了会再掷一批');
}

console.log('--- 日期/等级 变了同样要叫醒 ---');
{
  const { 数据, 源 } = 造源();
  let 跑了几次 = 0;
  watch(盯的源(源), () => { 跑了几次++; }, { immediate: true });
  await nextTick();

  const 之前 = 跑了几次;
  数据.value.日期 = '霜降月第二日';
  await nextTick();
  await nextTick();
  断言(跑了几次 === 之前 + 1, '日期一变就叫醒 (这条是改动前就有的行为, 别修回归了)');

  const 又之前 = 跑了几次;
  数据.value.等级 = 'B';
  await nextTick();
  await nextTick();
  断言(跑了几次 === 又之前 + 1, '等级一变也叫醒');
}

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
