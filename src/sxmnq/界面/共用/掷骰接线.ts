/**
 * 把 生成/ 那一层纯函数接到 MVU store 上。
 *
 * **这是整个 生成/ 目录里唯一有副作用的一层** —— 上面四个文件
 * (池子/掷骰/闸门/生成/流转) 全是纯函数, 所以它们能在 node 里直接测。
 * 有副作用的部分全部挤在这里, 一共三行。
 *
 * 为什么要单独一个文件而不是直接写在 App.vue 里:
 * 「什么时候该掷」是一条有幂等要求的规则 (spec §8.4), 值得有自己的注释和位置,
 * 而不是散在组件的 setup 里。
 */
import { watch } from 'vue';
import type { 等级 } from '../../等级';
import { 跑一次, type 今日数据 } from '../../生成/流转';

export interface 接线源 {
  /** 今日那一块 —— 注意要传 store 上的那个 reactive 对象, 不要传副本 */
  今日: () => 今日数据;
  /** 读 世界.日期。AI 写, 前端只读 (spec §9) */
  日期: () => string;
  /** 诊所当前等级 —— 掷骰的概率池由它决定 */
  等级: () => 等级;
}

/**
 * watch 的源。**必须是一个「getter 数组」**（Vue 的多源 watch），每一项都返回原始值。
 *
 * ⚠ 这里踩过一次死循环, 整页卡死且一行日志都不打 —— 别把它改回单 getter。
 *
 * 单 getter 写成 `() => [日期(), 等级(), JSON.stringify(登场)]` 是**错的**:
 * 它每次返回一个**新数组**, 而 Vue 对单源用 `Object.is` 比容器 —— 新数组永远
 * 判定为「变了」。碰巧回调 (跑一次 → 处理登场) 每次都会把 登场 赋成新数组,
 * 于是: 回调写 → 源变脏 → 又要跑回调 → 又写 …… flushJobs 自我递归, 渲染线程占死。
 *
 * 写成 getter 数组后 Vue 走 isMultiSource 分支, **逐项** `Object.is`。三项都是
 * 字符串, 内容一样就不触发 —— 这正是下面 JSON.stringify 想要的比较语义。
 *
 * 用 JSON.stringify 而不是 deep: true: MVU 的 insert 是就地对数组 push, 引用不换,
 * 所以必须比内容; 而 deep 会连带深挖 今日 底下的 待登记(6 条) 与 申请列表,
 * 唤醒次数多过需要。第三项只盯 登场 这一小块。
 *
 * 导出是为了让 掷骰接线.test.mjs 能直接验它 —— 这个坑在浏览器里既没栈也没日志。
 */
export function 盯的源(源: 接线源) {
  return [
    // 第三项是 登场 —— **不能只盯日期和等级**。
    // 同一天里 AI 报到时, 前两项都不变, 只靠 iframe 重建兜底太脆
    // (那是个我们没写在任何地方的假设)。
    源.日期,
    源.等级,
    () => JSON.stringify(源.今日().登场),
  ] as const;
}

/**
 * 盯住 世界.日期 + 今日.登场: 日期变了就重掷一批, 没变就把 AI 报到/命名的人收下。
 *
 * `immediate: true` 是必须的 —— 挂载的那一刻也得跑一次,
 * 否则玩家刷新页面之后, 昨天掷好的一批人永远晋级不了。
 *
 * **不需要防抖**: 跑一次() 本身是幂等的 (去看 流转.test.mjs 里
 * 「连跑 20 次仍然只有一批」那一段), 重复触发只会白跑一遍。
 */
export function 盯住日期(源: 接线源) {
  return watch(
    盯的源(源),
    ([日期]) => {
      跑一次(源.今日(), 日期, 源.等级());
    },
    { immediate: true },
  );
}
