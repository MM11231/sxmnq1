/**
 * 把 生成/ 那一层纯函数接到 MVU store 上。
 *
 * **这是整个 生成/ 目录里唯一有副作用的一层** —— 上面四个文件
 * (池子/掷骰/闸门/生成/流转) 全是纯函数, 所以它们能在 node 里直接测。
 * 有副作用的部分全部挤在这里, 一共三行。
 *
 * 为什么要单独一个文件而不是直接写在 App.vue 里:
 * 「什么时候该掷」是一条有幂等要求的规则 (spec §8.4), 值得有自己的注释和位置,
 * 而不是散在组件的 setup 里。
 */
import { watch } from 'vue';
import type { 等级 } from '../../等级';
import { 跑一次, type 今日数据 } from '../../生成/流转';

export interface 接线源 {
  /** 今日那一块 —— 注意要传 store 上的那个 reactive 对象, 不要传副本 */
  今日: () => 今日数据;
  /** 读 世界.日期。AI 写, 前端只读 (spec §9) */
  日期: () => string;
  /** 诊所当前等级 —— 掷骰的概率池由它决定 */
  等级: () => 等级;
}

/**
 * 盯住 世界.日期: 变了就重掷一批, 没变就只把 AI 命好名的人晋级。
 *
 * `immediate: true` 是必须的 —— 挂载的那一刻也得跑一次,
 * 否则玩家刷新页面之后, 昨天掷好的一批人永远晋级不了。
 *
 * **不需要防抖**: 跑一次() 本身是幂等的 (去看 流转.test.mjs 里
 * 「连跑 20 次仍然只有一批」那一段), 重复触发只会白跑一遍。
 */
export function 盯住日期(源: 接线源) {
  return watch(
    () => [源.日期(), 源.等级()] as const,
    ([日期]) => {
      跑一次(源.今日(), 日期, 源.等级());
    },
    { immediate: true },
  );
}
