/**
 * 把 生成/ 那一层纯函数接到 MVU store 上。
 *
 * **这是整个 生成/ 目录里唯一有副作用的一层** —— 上面四个文件
 * (池子/掷骰/闸门/生成/流转) 全是纯函数, 所以它们能在 node 里直接测。
 * 有副作用的部分全部挤在这里, 一共三行。
 *
 * 为什么要单独一个文件而不是直接写在 App.vue 里:
 * 「什么时候该掷」是一条有幂等要求的规则 (spec §8.4), 值得有自己的注释和位置,
 * 而不是散在组件的 setup 里。
 */
import { watch } from 'vue';
import type { 等级 } from '../../等级';
import { 跑一次, type 今日数据 } from '../../生成/流转';

export interface 接线源 {
  /** 今日那一块 —— 注意要传 store 上的那个 reactive 对象, 不要传副本 */
  今日: () => 今日数据;
  /** 读 世界.日期。AI 写, 前端只读 (spec §9) */
  日期: () => string;
  /** 诊所当前等级 —— 掷骰的概率池与每天的来客数都由它决定 */
  等级: () => 等级;
  /**
   * 哨兵表。**只为了挑回头客** (已出院的老熟人, 见 生成.ts 的 掷一批)。
   *
   * ⚠ 它是**掷骰那一刻读一次**的输入, **不是 watch 的源** —— 见 盯的源 的注释。
   */
  哨兵: () => Record<string, { 状态: string }>;
  生成后?: () => void;
}

/**
 * watch 的源。**必须是一个「getter 数组」**（Vue 的多源 watch），每一项都返回原始值。
 *
 * ⚠ 这里踩过一次死循环, 整页卡死且一行日志都不打 —— 别把它改回单 getter。
 *
 * 单 getter 写成 `() => [日期(), 等级()]` 是**错的**: 它每次返回一个**新数组**,
 * 而 Vue 对单源用 `Object.is` 比容器 —— 新数组永远判定为「变了」, 于是
 * 回调写 → 源变脏 → 又要跑回调 → 又写 …… flushJobs 自我递归, 渲染线程占死。
 *
 * 写成 getter 数组后 Vue 走 isMultiSource 分支, **逐项** `Object.is`。
 * 两项都是字符串, 内容一样就不触发。
 *
 * ★ 2026-10-06「名单直出」把第三项 (`JSON.stringify(今日.登场)`) 删掉了。
 * 它当初存在是因为「同一天里 AI 报到时前两项都不变, 只靠 iframe 重建兜底太脆」。
 * 现在**同一天里没有任何外部的东西会改名单** —— 名单是掷骰那一刻就定死的,
 * AI 只读不写 —— 所以日期不变就真的不需要再跑。
 *
 * ⚠ 也**不要**把 哨兵 加成第三项。它是给回头客用的**输入**, 一天之内怎么变
 * (有人出院、有人被收编) 都不该触发重掷 —— 重掷会把玩家已经看过、
 * 正在挑的那份名单整个换掉。这与上面那个死循环是**同源**的一类错误:
 * 多盯一个会变的东西。
 *
 * 导出是为了让 掷骰接线.test.mjs 能直接验它 —— 这个坑在浏览器里既没栈也没日志。
 */
export function 盯的源(源: 接线源) {
  return [源.日期, 源.等级] as const;
}

/**
 * 盯住 世界.日期 + 诊所.等级: 日期变了就掷一批新的, 没变就什么都不做。
 *
 * `immediate: true` 是必须的 —— 挂载的那一刻也得跑一次,
 * 否则玩家刷新页面之后, 今天该有的名单永远不会掷出来。
 *
 * **不需要防抖**: 跑一次() 本身是幂等的 (去看 流转.test.mjs 里
 * 「连跑 20 次仍然只有一批」那一段), 重复触发只会白跑一遍。
 */
export function 盯住日期(源: 接线源) {
  return watch(
    盯的源(源),
    ([日期]) => {
      const 结果 = 跑一次(源.今日(), 日期, 源.等级(), 源.哨兵());
      if (结果.掷了) 源.生成后?.();
    },
    { immediate: true },
  );
}
