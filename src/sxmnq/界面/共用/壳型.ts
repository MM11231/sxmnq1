// 主界面那层壳要的两张表的**形状**。
//
// 单独放一个文件, 不写进 主界面壳.vue 的 `<script>`: 壳里那份是 setup 语法糖,
// 再挂一个普通 `<script>` 只为了让外面 import 到类型, 得多验一层 vue-loader 的
// 合并行为(这仓里加载器的坑都是静默的)。类型单独一个 .ts 谁都能 import,
// 而且它没有运行时代码, 进不了打包产物。
import type { Component } from 'vue';

/**
 * 标签栏上的一页。
 *
 * `件` 不给 = 这一页就是正文本身(「剧情」那种)。壳**不会**给它铺一层盖板 ——
 * 正文常年挂在底下, 铺盖板会把正文整块盖死(而且是全对的、不报错的死法)。
 */
export interface 页 {
  /** 这一页的身份。`展块` 存的就是它, 也拿它当 v-for 的 key。 */
  键: string;
  /** 标签上写的字。 */
  名: string;
  /** 这一页的面板。不给 = 正文那页。 */
  件?: Component;
  /** 标签右上角那个小圈里的数。0 或不给 = 不显示。 */
  角标?: number;
  /** 这一页自己铺满, 不要壳给的留白和滚动条(地图那种落满整屏的)。 */
  填?: boolean;
}

/** 顶栏上那个「开一层浮盖」的按钮, 和它盖下来的那层。 */
export interface 浮层 {
  /** 身份。`开的浮层` 存的就是它。 */
  键: string;
  /** 按钮上写的字。 */
  名: string;
  /** 按钮上那个图标, fontawesome 的类名。 */
  图: string;
  /** 盖下来的那一层。它会收到一个 `关` 事件 —— 里面点关闭时 emit 它。 */
  件: Component;
}
