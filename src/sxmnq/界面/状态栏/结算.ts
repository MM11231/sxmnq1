/**
 * 结算 —— 把小游戏的结果翻译成两样东西:
 *
 *   1. 变量改动 (应用结算) —— 精神力、金钱、名声、星级、信赖、污染度
 *   2. 一段元指令 (构建元指令) —— 发给 LLM, 让它把这一局写成剧情
 *
 * 分工原则 (设计文档 §8): **能用确定的公式算的, 不由 LLM 决定**。
 * 诊金、名声、精神力、信赖全部在这里算死, LLM 只负责把状态写成身体和情绪。
 * 变量更新规则里也写明了这些字段不让 AI 碰, 免得重复记账。
 */
import { 好感分档, 信赖分档 } from '../../分档';
import { 算信赖加成 } from '../../家园/家具';
import { 算实际诊金 } from '../../生成/闸门';
import { 升一档, type 等级 } from '../../等级';
import { 算单次清除量, 算预计次数, type 评级, type 治疗结果 } from '../治疗/game';

export interface 结算上下文 {
  世界: { 日期: string; 时段: string };
  主角: {
    姓名: string;
    /** 扣减**之前**的精神力 —— 元指令描述的是场面开始时主角的状态 */
    精神力: number;
    精神力上限: number;
  };
  /** 等级与称号合并了旧的 执业等级 + 星级 (spec §3) */
  诊所: { 名称: string; 等级: 等级; $称号: string; 名声: number; 床位: number };
  /**
   * 诊所的气氛 —— Σ 已摆放家具的氛围 (spec §7.2/§8)。
   *
   * 它取代的是原来的「减耗」, 而减耗取代的是更早的「躺椅等级」。
   * 三者是同一个位置上的同一个东西: **诊所本身有多好**。
   * 现在这个位置由玩家自己装修出来, 而不是一个写死的等级。
   */
  气氛: number;
  /**
   * 病人。**带着整份档案** —— 第一次接诊时 应用结算 就是照这个建档的,
   * 少一个字段, 那条记录就会被 schema 的 prefault 悄悄填成空串
   * (表现为「这个病人没有精神体」, 而界面上什么都不报)。
   */
  患者: {
    姓名: string;
    等级: 等级;
    污染度: number;
    战损来源: string;
    年龄: number;
    地域: string;
    精神体: { 纲: string; 方向: string; 栖息: string; 体型: string; 危险: string };
    特征: string[];
    A面: string;
    B面: string;
    信赖: number;
    /** 好感只由 AI 按剧情写, 这里纯粹是为了在元指令里把当前档位念给它听 */
    好感: number;
    /** 申请列表里的**基础**诊金, 结算时按评级乘系数 */
    基础诊金: number;
    $信赖: string;
    $好感: string;
  };
}

/**
 * 评级决定收益。
 *
 * **`评级系数` 同时乘两样东西**: 诊金, 和这一趟能清掉多少污染度 (spec §5.3)。
 * 一个系数管两件事, 是「评级第一次有了数值后果之外的意义」那句的意思 ——
 * 打得烂不只是少拿钱, 是这个病人要多占你两天床。
 *
 * 旧字段 `污染降幅` 已退役: 那是乘性衰减 (污染度 × (1 − 降幅)),
 * 天然收敛但**次数不可预测**, 玩家没法在接单前知道要跑几趟。改成加性。
 */
const 收益表: Record<评级, { 名声: number; 评级系数: number; 信赖: number }> = {
  S: { 名声: 8, 评级系数: 1.5, 信赖: 8 },
  A: { 名声: 6, 评级系数: 1.2, 信赖: 5 },
  B: { 名声: 4, 评级系数: 1.0, 信赖: 3 },
  C: { 名声: 2, 评级系数: 0.8, 信赖: 1 },
};

export function 评级收益(评级: 评级, 基础诊金: number) {
  const 档 = 收益表[评级];
  return { 名声: 档.名声, 诊金: 算实际诊金(基础诊金, 档.评级系数), 信赖: 档.信赖 };
}

/**
 * 这一趟实际清掉多少。**评级系数同时管诊金和清除量, 所以只能有一个出处。**
 *
 * `Math.max(1, …)` 是兜底: C 评级 × D 级诊所 = round(10 × 0.8) = 8, 够不着下限;
 * 但若 ② 之后有人把系数调到 0.05, 一次疏导一点都清不掉会让病人永远出不了院。
 */
export function 算实际清除量(诊所等级: 等级, 评级: 评级): number {
  return Math.max(1, Math.round(算单次清除量(诊所等级) * 收益表[评级].评级系数));
}

/**
 * 气氛越足、哨兵越信赖, 精神海就越放松。
 *
 * `12` 是基准分。它原来长成 `(减耗 + 1) * 12` —— 那个 `+ 1` 是为了跟更早的
 * `躺椅等级 * 12` 对得上。减耗下线之后留一个裸的 `12` 就够,
 * **气氛 0 / 信赖 0 时的文案与改动前逐字相同**。
 *
 * 四个档位要跨过去, 气氛和信赖得一起凑:
 *
 * | 气氛 | 信赖 | 值 | 档位 |
 * |---|---|---|---|
 * | 0 | 0 | 12 | 很不自在 |
 * | 0 | 100 | 52 | 还算安稳 |
 * | 70 | 100 | 80 | 敞开 |
 * | 170 | 0 | 80 | 敞开 —— 光靠装修也够得着 |
 *
 * 于是装修有**两个**回报: 气氛换来的信赖加成 (§7.2), 和这段文案。
 * 最高档要「装修和感情都要」, 正好是这句话该有的分量。
 */
export function 舒适描述(气氛: number, 信赖: number): string {
  const 值 = 12 + (气氛 + 信赖) * 0.4;
  if (值 >= 80) return '整个人陷进躺椅里，精神海完全向你敞开，连防线都懒得维持';
  if (值 >= 60) return '舒服地靠着，呼吸慢慢放缓，肩膀一点点松下来';
  if (值 >= 40) return '还算安稳，只是每当你碰到痛处会轻轻绷一下';
  if (值 >= 20) return '有些紧张，身体一直半僵着，不太敢放松';
  return '很不自在，像是随时准备起身离开';
}

/** 污染度是疼的根源, 失手则是在这之上又添的新伤 */
export function 痛苦描述(污染度: number, 失误率: number): string {
  const 值 = 污染度 * 0.85 + Math.min(失误率, 0.5) * 30;
  if (值 >= 80) return '精神海痛得厉害，他要拼上全部力气才压得住本能的反扑';
  if (值 >= 60) return '精神海很痛，需要用理智努力压抑自己对向导的渴望';
  if (值 >= 40) return '隐隐作痛，但还在能忍的范围内';
  if (值 >= 20) return '没什么痛感，只是有点疲惫';
  return '精神海很平静，几乎感觉不到痛';
}

export function 构建元指令(上: 结算上下文, 果: 治疗结果): string {
  const { 名声: 名声加, 诊金: 诊金加 } = 评级收益(果.评级, 上.患者.基础诊金);
  const 实际清除量 = 算实际清除量(上.诊所.等级, 果.评级);
  const 剩余次数 = 算预计次数(上.患者.污染度 - 实际清除量, 算单次清除量(上.诊所.等级));
  const 失误记录 = 果.失误日志.length
    ? 果.失误日志.map(({ 条, 短句 }) => `· 第 ${条} 条时手重了 —— ${短句}`).join('\n')
    : '· （全程没有失手）';

  // 外面这层 <疏导指令> 是给酒馆正则认的: 它会被当成一条用户消息塞进聊天记录,
  // 正文玩家不该看见 (设计上也不该看见里面的数字), 所以 index.yaml 里有一条
  // 只作用于显示、不作用于提示词的正则把这整块抹掉。改标签名记得同步那边。
  return `<疏导指令>
以下为要求你编写剧情的元指令：

<info>
时间：${上.世界.日期} · ${上.世界.时段}
向导：${上.主角.姓名}｜精神力：${上.主角.精神力}/${上.主角.精神力上限}
诊所：${上.诊所.名称}｜${上.诊所.$称号}｜等级：${上.诊所.等级}｜名声：${上.诊所.名声}/100｜床位：${上.诊所.床位}
</info>

<patient>
姓名：${上.患者.姓名}｜等级：${上.患者.等级}｜污染度：${上.患者.污染度}
战损来源：${上.患者.战损来源}
</patient>

<state>
信赖度：${上.患者.$信赖 || 信赖分档(上.患者.信赖)}
好感：${上.患者.$好感 || 好感分档(上.患者.好感)}
舒适度：${舒适描述(上.气氛, 上.患者.信赖)}
痛苦度：${痛苦描述(上.患者.污染度, 果.失误次数 / Math.max(1, 果.线数))}
</state>

<session>
本次疏导清理了 ${果.线数} 条精神力丝线，失误 ${果.失误次数} 次，污染度下降 ${实际清除量}。
预计还需 ${剩余次数} 次。
失误记录：
${失误记录}
</session>

<result>
评级：${果.评级}｜诊金：+${诊金加}｜名声：+${名声加}｜精神力消耗：${果.精神力消耗}
</result>

请据此编写本次疏导的完整场面：从他精神海的景象、丝线被一根根理顺的过程，到他每一次反应的细节，再到疏导结束后的余韵。
不要复述上面的数字，把它们写成身体感受和情绪。
</疏导指令>`;
}

type 可写数据 = {
  主角: { 精神力: number; 金钱: number };
  诊所: { 名声: number; 等级: 等级 };
  哨兵: Record<
    string,
    {
      等级: 等级;
      污染度: number;
      战损来源: string;
      年龄: number;
      地域: string;
      精神体: { 纲: string; 方向: string; 栖息: string; 体型: string; 危险: string };
      特征: string[];
      A面: string;
      B面: string;
      信赖: number;
      好感: number;
      已治疗: number;
      状态: string;
      $信赖: string;
      $好感: string;
    }
  >;
  今日: { 申请列表: Record<string, { 状态: string }> };
};

/** 在诊的才占床。出院和收编都不占 (spec §5.2) */
export function 在诊人数(哨兵: Record<string, { 状态: string }>): number {
  return Object.values(哨兵).filter(哨 => 哨.状态 === '在诊').length;
}

/**
 * 接得了吗。**床位是继精神力之后的第二个稀缺资源** (spec §5.2)。
 *
 * 已经在诊的那个人不受床位限制 —— 那是复诊, 他本来就占着床。
 * 挡的是「新病人进不来」, 不是「老病人治不了」。
 */
export function 能接诊吗(哨兵: Record<string, { 状态: string }>, 床位: number, 姓名: string): boolean {
  if (哨兵[姓名]?.状态 === '在诊') return true;
  return 在诊人数(哨兵) < 床位;
}

/**
 * 把结算写回变量。顺序无所谓 —— store 会在下一拍把整份数据重新 parse 一遍,
 * 派生字段和钳制都由 schema 收拾。
 */
export function 应用结算(数据: 可写数据, 上: 结算上下文, 果: 治疗结果) {
  const { 名声: 名声加, 诊金: 诊金加, 信赖: 信赖加 } = 评级收益(果.评级, 上.患者.基础诊金);

  数据.主角.精神力 = Math.max(0, 数据.主角.精神力 - 果.精神力消耗);
  数据.主角.金钱 += 诊金加;

  // 名声攒满 100 就进位一档等级并清零重算 (spec §3)
  数据.诊所.名声 += 名声加;
  while (数据.诊所.名声 >= 100 && 数据.诊所.等级 !== 'S') {
    数据.诊所.名声 -= 100;
    数据.诊所.等级 = 升一档(数据.诊所.等级);
  }
  // 满级之后名声顶在 100 —— 没有更高的一档可以进, 让它一直亮着
  数据.诊所.名声 = Math.min(数据.诊所.名声, 100);

  // 第一次接诊时就建档。**整份档案照搬 上.患者** —— 少写一个字段,
  // schema 的 prefault 就会把它填成空串, 于是界面上出现一个「没有精神体」
  // 的病人, 而哪里都不报错。上.患者 带着整份档案正是为了这里。
  const 哨 = (数据.哨兵[上.患者.姓名] ??= {
    等级: 上.患者.等级,
    污染度: 上.患者.污染度,
    战损来源: 上.患者.战损来源,
    年龄: 上.患者.年龄,
    地域: 上.患者.地域,
    精神体: 上.患者.精神体,
    特征: 上.患者.特征,
    A面: 上.患者.A面,
    B面: 上.患者.B面,
    信赖: 0,
    好感: 0,
    已治疗: 0,
    状态: '在诊',
    // 派生字段, 下一拍由 schema 重算, 这里只是让类型成立
    $信赖: '',
    $好感: '',
  });

  // 这一趟算数了。治疗界面靠它显示「第 N / M 趟」——
  // 在 应用结算 里加而不是在 接诊 里加: 接诊之后玩家可能直接退出小游戏,
  // 那一趟没做完, 不该记进就诊史。
  哨.已治疗 += 1;
  哨.信赖 = Math.min(100, 哨.信赖 + 信赖加 + 算信赖加成(上.气氛));
  // **加性**: 每趟固定清掉这么多, 与当前污染度无关 ——
  // 玩家在接单前就能用 算预计次数 算出差几趟 (spec §5.3)。
  // 以本次申请里写的污染度为基准, 而不是 哨兵 里存着的旧值 ——
  // 回头客重新出现在申请列表时, 只有申请列表是他此刻最新的状态。
  哨.污染度 = Math.max(0, 上.患者.污染度 - 算实际清除量(上.诊所.等级, 果.评级));
  if (哨.污染度 <= 0) 哨.状态 = '已出院';

  // 今天这个人已经接过了
  const 申请 = 数据.今日.申请列表[上.患者.姓名];
  if (申请) 申请.状态 = '已接';

  return { 诊金: 诊金加, 名声: 名声加 };
}
