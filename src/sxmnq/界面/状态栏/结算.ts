/**
 * 结算 —— 把小游戏的结果翻译成两样东西:
 *
 *   1. 变量改动 (应用结算) —— 精神力、金钱、名声、星级、信赖、污染度
 *   2. 一段元指令 (构建元指令) —— 发给 LLM, 让它把这一局写成剧情
 *
 * 分工原则 (设计文档 §8): **能用确定的公式算的, 不由 LLM 决定**。
 * 诊金、名声、精神力、信赖全部在这里算死, LLM 只负责把状态写成身体和情绪。
 * 变量更新规则里也写明了这些字段不让 AI 碰, 免得重复记账。
 */
import { 好感分档, 信赖分档 } from '../../分档';
import type { 评级, 治疗结果 } from '../治疗/game';

export interface 结算上下文 {
  世界: { 日期: string; 时段: string };
  主角: {
    姓名: string;
    执业等级: string;
    /** 扣减**之前**的精神力 —— 元指令描述的是场面开始时主角的状态 */
    精神力: number;
    精神力上限: number;
  };
  诊所: { 名称: string; $称号: string; 名声: number; 星级: number };
  躺椅等级: number;
  患者: {
    姓名: string;
    等级: string;
    污染度: number;
    战损来源: string;
    信赖: number;
    /** 好感只由 AI 按剧情写, 这里纯粹是为了在元指令里把当前档位念给它听 */
    好感: number;
    /** 申请列表里的基础诊金, 结算时按评级乘系数 */
    基础诊金: number;
    $信赖: string;
    $好感: string;
  };
}

/** 评级决定收益。B 档是基准 1.0 倍, 对应设计文档 §8 里那个「诊金 +120 / 名声 +4」的例子 */
const 收益表: Record<评级, { 名声: number; 诊金系数: number; 信赖: number; 污染降幅: number }> = {
  S: { 名声: 8, 诊金系数: 1.5, 信赖: 8, 污染降幅: 0.6 },
  A: { 名声: 6, 诊金系数: 1.2, 信赖: 5, 污染降幅: 0.45 },
  B: { 名声: 4, 诊金系数: 1.0, 信赖: 3, 污染降幅: 0.3 },
  C: { 名声: 2, 诊金系数: 0.8, 信赖: 1, 污染降幅: 0.15 },
};

export function 评级收益(评级: 评级, 基础诊金: number) {
  const 档 = 收益表[评级];
  return { 名声: 档.名声, 诊金: Math.round(基础诊金 * 档.诊金系数), 信赖: 档.信赖 };
}

/** 躺椅越高级、哨兵越信赖, 精神海就越放松 —— 和 §7.2 里「躺椅减少失误惩罚」是同一件事的两面 */
export function 舒适描述(躺椅等级: number, 信赖: number): string {
  const 值 = 躺椅等级 * 12 + 信赖 * 0.4;
  if (值 >= 80) return '整个人陷进躺椅里，精神海完全向你敞开，连防线都懒得维持';
  if (值 >= 60) return '舒服地靠着，呼吸慢慢放缓，肩膀一点点松下来';
  if (值 >= 40) return '还算安稳，只是每当你碰到痛处会轻轻绷一下';
  if (值 >= 20) return '有些紧张，身体一直半僵着，不太敢放松';
  return '很不自在，像是随时准备起身离开';
}

/** 污染度是疼的根源, 失手则是在这之上又添的新伤 */
export function 痛苦描述(污染度: number, 失误率: number): string {
  const 值 = 污染度 * 0.85 + Math.min(失误率, 0.5) * 30;
  if (值 >= 80) return '精神海痛得厉害，他要拼上全部力气才压得住本能的反扑';
  if (值 >= 60) return '精神海很痛，需要用理智努力压抑自己对向导的渴望';
  if (值 >= 40) return '隐隐作痛，但还在能忍的范围内';
  if (值 >= 20) return '没什么痛感，只是有点疲惫';
  return '精神海很平静，几乎感觉不到痛';
}

export function 构建元指令(上: 结算上下文, 果: 治疗结果): string {
  const { 名声: 名声加, 诊金: 诊金加 } = 评级收益(果.评级, 上.患者.基础诊金);
  const 失误记录 = 果.失误日志.length
    ? 果.失误日志.map(({ 条, 短句 }) => `· 第 ${条} 条时手重了 —— ${短句}`).join('\n')
    : '· （全程没有失手）';

  // 外面这层 <疏导指令> 是给酒馆正则认的: 它会被当成一条用户消息塞进聊天记录,
  // 正文玩家不该看见 (设计上也不该看见里面的数字), 所以 index.yaml 里有一条
  // 只作用于显示、不作用于提示词的正则把这整块抹掉。改标签名记得同步那边。
  return `<疏导指令>
以下为要求你编写剧情的元指令：

<info>
时间：${上.世界.日期} · ${上.世界.时段}
向导：${上.主角.姓名}｜等级：${上.主角.执业等级}｜精神力：${上.主角.精神力}/${上.主角.精神力上限}
诊所：${上.诊所.名称}｜${上.诊所.$称号}｜名声：${上.诊所.名声}/100｜星级：Lv${上.诊所.星级}
</info>

<patient>
姓名：${上.患者.姓名}｜等级：${上.患者.等级}｜污染度：${上.患者.污染度}
战损来源：${上.患者.战损来源}
</patient>

<state>
信赖度：${上.患者.$信赖 || 信赖分档(上.患者.信赖)}
好感：${上.患者.$好感 || 好感分档(上.患者.好感)}
舒适度：${舒适描述(上.躺椅等级, 上.患者.信赖)}
痛苦度：${痛苦描述(上.患者.污染度, 果.失误次数 / Math.max(1, 果.线数))}
</state>

<session>
本次疏导清理了 ${果.线数} 条精神力丝线，失误 ${果.失误次数} 次。
失误记录：
${失误记录}
</session>

<result>
评级：${果.评级}｜诊金：+${诊金加}｜名声：+${名声加}｜精神力消耗：${果.精神力消耗}
</result>

请据此编写本次疏导的完整场面：从他精神海的景象、丝线被一根根理顺的过程，到他每一次反应的细节，再到疏导结束后的余韵。
不要复述上面的数字，把它们写成身体感受和情绪。
</疏导指令>`;
}

type 可写数据 = {
  主角: { 精神力: number; 金钱: number };
  诊所: { 名声: number; 星级: number };
  哨兵: Record<
    string,
    {
      等级: string;
      污染度: number;
      战损来源: string;
      信赖: number;
      好感: number;
      状态: string;
      $信赖: string;
      $好感: string;
    }
  >;
  今日: { 申请列表: Record<string, { 状态: string }> };
};

/**
 * 把结算写回变量。顺序无所谓 —— store 会在下一拍把整份数据重新 parse 一遍,
 * 派生字段和钳制都由 schema 收拾。
 */
export function 应用结算(数据: 可写数据, 上: 结算上下文, 果: 治疗结果) {
  const { 名声: 名声加, 诊金: 诊金加, 信赖: 信赖加 } = 评级收益(果.评级, 上.患者.基础诊金);

  数据.主角.精神力 = Math.max(0, 数据.主角.精神力 - 果.精神力消耗);
  数据.主角.金钱 += 诊金加;

  // 名声攒满 100 就升一星并清零重算 (§7.1)
  数据.诊所.名声 += 名声加;
  while (数据.诊所.名声 >= 100 && 数据.诊所.星级 < 5) {
    数据.诊所.名声 -= 100;
    数据.诊所.星级 += 1;
  }
  数据.诊所.名声 = Math.min(数据.诊所.名声, 100);

  const 哨 = (数据.哨兵[上.患者.姓名] ??= {
    等级: 上.患者.等级,
    污染度: 上.患者.污染度,
    战损来源: 上.患者.战损来源,
    信赖: 0,
    好感: 0,
    状态: '在诊',
    // 派生字段, 下一拍由 schema 重算, 这里只是让类型成立
    $信赖: '',
    $好感: '',
  });

  哨.信赖 = Math.min(100, 哨.信赖 + 信赖加);
  // 以本次申请里写的污染度为基准, 而不是 哨兵 里存着的旧值 ——
  // 回头客重新出现在申请列表时, 只有申请列表是他此刻最新的状态。
  哨.污染度 = Math.max(0, Math.round(上.患者.污染度 * (1 - 收益表[果.评级].污染降幅)));
  if (哨.污染度 <= 0) 哨.状态 = '已出院';

  // 今天这个人已经接过了
  const 申请 = 数据.今日.申请列表[上.患者.姓名];
  if (申请) 申请.状态 = '已接';

  return { 诊金: 诊金加, 名声: 名声加 };
}
