// 直接跑: node src/sxmnq/界面/状态栏/结算.test.mjs
//
// 结算里最值钱的两条性质:
//   1. 加性 —— 玩家在接单前就能算出要跑几趟 (这是改掉乘性衰减的**唯一**理由)
//   2. 名声跨过 100 会进位成一档等级, 而不是无限涨
import '../../测试钩子.mjs';
const S = await import(new URL('./结算.ts', import.meta.url).href);
const G = await import(new URL('../治疗/game.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};

const 造数据 = (名声 = 0, 等级 = 'D', 精神力 = 100) => ({
  主角: { 精神力, 金钱: 0 },
  诊所: { 名声, 等级, 床位: 2 },
  哨兵: {},
  今日: { 申请列表: {} },
});
const 造上下文 = (患者污染度 = 50, 诊所等级 = 'D', 基础诊金 = 180) => ({
  世界: { 日期: '霜降月第一日', 时段: '上午' },
  主角: { 姓名: '林晚', 精神力: 100, 精神力上限: 100 },
  诊所: { 名称: '听雨诊所', 等级: 诊所等级, $称号: '', 名声: 0, 床位: 2 },
  气氛: 0,
  患者: {
    姓名: '沈砚', 等级: 'C', 污染度: 患者污染度, 战损来源: '清剿三号污染区',
    年龄: 29, 地域: '极北凛冬(军备重工)',
    精神体: { 纲: '哺乳纲', 方向: '食肉目', 栖息: '陆行', 体型: '偏大(超越人类)', 危险: '力量型' },
    特征: ['伤疤截断眉'], A面: '高冷', B面: '独占本能',
    信赖: 0, 好感: 0, 基础诊金, $信赖: '', $好感: '',
  },
});
const 造果 = (评级, 线数 = 10, 失误次数 = 0) => ({
  线数, 已完成: 线数, 失误次数, 失误日志: [], 评级, 精神力消耗: 线数,
});

console.log('--- 单次清除量 (spec §5.1) ---');
等于(G.算单次清除量('D'), 10, 'D 级诊所 10');
等于(G.算单次清除量('C'), 14, 'C 级 14');
等于(G.算单次清除量('B'), 18, 'B 级 18');
等于(G.算单次清除量('A'), 22, 'A 级 22');
等于(G.算单次清除量('S'), 26, 'S 级 26');

console.log('--- 预计次数 = ceil(污染度 ÷ 单次清除量) (spec §5.2) ---');
等于(G.算预计次数(50, 10), 5, '污染 50 / 单次 10 → 5 次');
等于(G.算预计次数(55, 10), 6, '除不尽一律向上取整 (55/10 = 5.5 → 6)');
等于(G.算预计次数(0, 10), 0, '污染 0 → 0 次, 不该冒出 1');
等于(G.算预计次数(30, 0), 30, '单次清除量是 0 时不让它除零崩掉');

console.log('--- ★ 全表最坏情况 ≤ 7 次 (spec §5.1 那句自证) ---');
// 闸门把 等级锁在 [诊所-1, 诊所+1], 污染度由 §4.2 的区间给。
// 逐格算一遍, 表里说的「最坏 7 次」得是真的。
const 污染度区间 = { D: [20, 45], C: [35, 65], B: [55, 85], A: [70, 95], S: [85, 100] };
const 可来 = { D: ['D', 'C'], C: ['D', 'C', 'B'], B: ['D', 'C', 'B', 'A'], A: ['D', 'C', 'B', 'A', 'S'], S: ['D', 'C', 'B', 'A', 'S'] };
let 最坏 = 0;
for (const [诊所, 客们] of Object.entries(可来)) {
  for (const 客 of 客们) {
    const 次 = G.算预计次数(污染度区间[客][1], G.算单次清除量(诊所));
    最坏 = Math.max(最坏, 次);
  }
}
等于(最坏, 7, `全表预计次数的最大值是 7 (实得 ${最坏})`);
等于(G.算预计次数(65, G.算单次清除量('D')), 7, 'D 级诊所治 C 级病人、污染拉满 → 7 次 (spec 点名的那个格子)');

console.log('--- 应用结算: 污染度是加性下降, 不是乘性 ---');
const 数据 = 造数据();
S.应用结算(数据, 造上下文(50, 'D', 180), 造果('A', 10, 0));
等于(数据.哨兵.沈砚.污染度, 50 - Math.round(10 * 1.2), '污染 50 − round(10 × 1.2) = 38, 不是 50 × (1 − 0.45) = 28');
// 再来一次, 同一个病人
S.应用结算(数据, 造上下文(38, 'D', 180), 造果('A', 10, 0));
等于(数据.哨兵.沈砚.污染度, 26, '第二次再减 12 → 26。每趟减多少是恒定的');
S.应用结算(数据, 造上下文(26, 'D', 180), 造果('A', 10, 0));
等于(数据.哨兵.沈砚.污染度, 14, '第三次 → 14。玩家在接单前就能算出差 3 趟');
S.应用结算(数据, 造上下文(14, 'D', 180), 造果('A', 10, 0));
等于(数据.哨兵.沈砚.污染度, 2, '第四次 → 2');
S.应用结算(数据, 造上下文(2, 'D', 180), 造果('A', 10, 0));
等于(数据.哨兵.沈砚.污染度, 0, '第五次归零');
等于(数据.哨兵.沈砚.状态, '已出院', '归零即出院, 床让出来');
等于(G.算预计次数(50, G.算单次清除量('D')), 5, '预计 5 次, 实际 A 评级正好 5 次 —— 预计次数是准的');

console.log('--- 评级决定每趟减多少 (spec §5.3) ---');
const 各评级 = {};
for (const 评 of ['S', 'A', 'B', 'C']) {
  const d = 造数据();
  S.应用结算(d, 造上下文(100, 'D', 180), 造果(评, 10, 0));
  各评级[评] = 100 - d.哨兵.沈砚.污染度;
}
等于(各评级, { S: 15, A: 12, B: 10, C: 8 }, 'S 15 / A 12 / B 10 / C 8 —— 打得烂就是病人要多占两天床');
断言(各评级.C >= 1, 'C 评级至少也能清掉 1 点 (Math.max(1, …) 兜着)');

console.log('--- 低评级 + 低污染 也不会卡住 ---');
const d2 = 造数据();
S.应用结算(d2, 造上下文(2, 'D', 180), 造果('C', 10, 0));
断言(d2.哨兵.沈砚.污染度 < 2, `污染 2 遇到 C 评级仍然下降 (降到 ${d2.哨兵.沈砚.污染度})`);

console.log('--- 首次接诊建档: 整份档案都要带过去 (A 案) ---');
// 这条盯的是最阴的一种坏法: 建档时少写一个字段, schema 的 prefault 会把它
// 悄悄填成空串 —— 界面上出现一个「没有精神体」的病人, 而哪里都不报错。
// 所以 结算上下文.患者 必须带着整份档案, 而不是只带结算用得着的那几个数。
const d6 = 造数据();
S.应用结算(d6, 造上下文(50, 'D', 180), 造果('A', 10, 0));
const 建 = d6.哨兵.沈砚;
等于(
  {
    等级: 建.等级, 年龄: 建.年龄, 地域: 建.地域, 精神体: 建.精神体,
    特征: 建.特征, A面: 建.A面, B面: 建.B面, 战损来源: 建.战损来源,
  },
  {
    等级: 'C', 年龄: 29, 地域: '极北凛冬(军备重工)',
    精神体: { 纲: '哺乳纲', 方向: '食肉目', 栖息: '陆行', 体型: '偏大(超越人类)', 危险: '力量型' },
    特征: ['伤疤截断眉'], A面: '高冷', B面: '独占本能', 战损来源: '清剿三号污染区',
  },
  '新建的那条记录逐字照搬了上.患者 —— 一个字段都不能是 prefault 填的空串',
);

console.log('--- 已治疗 每趟 +1 (治疗界面的「第 N / M 趟」靠它) ---');
const d5 = 造数据();
S.应用结算(d5, 造上下文(50, 'D', 180), 造果('A', 10, 0));
等于(d5.哨兵.沈砚.已治疗, 1, '新建档的人第一趟做完 → 已治疗 1 (接诊时显示的「第 1 趟」正是这么来的)');
S.应用结算(d5, 造上下文(38, 'D', 180), 造果('A', 10, 0));
等于(d5.哨兵.沈砚.已治疗, 2, '同一人第二趟 → 2, 界面下一趟会显示「第 3 趟」');

console.log('--- 元指令: 诊所要念等级与床位, 还要预告剩下几趟 ---');
const 词 = S.构建元指令(造上下文(62, 'C', 244), 造果('S', 9, 0));
断言(词.includes('等级：C'), '诊所那一行带等级 (旧的向导等级那行已删)');
断言(词.includes('床位：2'), '诊所那一行带床位');
断言(!/^向导：.*等级/m.test(词), '向导那一行不再念等级 —— 等级是诊所的, 不是人身上的');
断言(词.includes('污染度下降 21'), 'S 评级 × C 级诊所 → 下降 round(14 × 1.5) = 21');
断言(词.includes('预计还需 3 次'), '减完剩 41: ceil(41 / 14) = 3 —— 这个数是玩家下一趟的预期');

console.log('--- 名声攒满 100 进位一档等级, 不是无限涨 (spec §3) ---');
const d3 = 造数据(98, 'D');
S.应用结算(d3, 造上下文(50, 'D', 180), 造果('A', 10, 0)); // A 档名声 +6
等于(d3.诊所.等级, 'C', '98 + 6 = 104 → 进位成 C, 余 4');
等于(d3.诊所.名声, 4, '进位后名声留 4, 不是 104');
const d4 = 造数据(50, 'S');
S.应用结算(d4, 造上下文(50, 'S', 180), 造果('S', 10, 0)); // S 档名声 +8
等于(d4.诊所.等级, 'S', '已经是 S 就不再进位');
等于(d4.诊所.名声, 58, 'S 级名声照常累加');

console.log('--- 舒适描述: 气氛与信赖一起凑 (spec §7.3) ---');
等于(S.舒适描述(0, 0), S.舒适描述(0, 0), '同一个输入同一个输出');
断言(S.舒适描述(0, 0).includes('不自在'), '气氛 0 / 信赖 0 → 最低档 (与改动前逐字相同)');
断言(S.舒适描述(0, 100).includes('还算安稳'), '光靠信赖最多 52 分, 够不到「舒服地靠着」');
断言(S.舒适描述(70, 100).includes('敞开'), '满装修 + 满信赖 → 最高档');
断言(S.舒适描述(170, 0).includes('敞开'), '光靠装修也够得着最高档');
断言(S.舒适描述(60, 0) !== S.舒适描述(0, 0), '气氛变了描述要变 (家具就是靠这个生效的)');
断言(S.舒适描述(3, 100).includes('还算安稳'), '气氛 低 + 信赖拉满 → 只到「还算安稳」(旧公式会到「敞开」, 这条专门钉住公式换了)');

console.log('--- 精神力上限由等级给 (spec §9) ---');
const L = await import(new URL('../../等级.ts', import.meta.url).href);
等于(L.算精神力上限('D'), 100, 'D 级 100 —— 与改动前的初值一致');
等于(L.算精神力上限('S'), 180, 'S 级 180');
等于(L.升一档('D'), 'C', 'D 升一档是 C');
等于(L.升一档('S'), 'S', 'S 不会再往上升');

console.log('--- 床位: 只数「在诊」的 ---');
等于(S.在诊人数({}), 0, '一个都没有 → 0');
等于(S.在诊人数({ 甲: { 状态: '在诊' }, 乙: { 状态: '已出院' }, 丙: { 状态: '已收编' } }), 1, '出院和收编都不占床');
等于(S.在诊人数({ 甲: { 状态: '在诊' }, 乙: { 状态: '在诊' } }), 2, '两个在诊 → 2');

console.log('--- 床位闸门 (spec §5.2) ---');
const 哨兵 = { 甲: { 状态: '在诊' }, 乙: { 状态: '在诊' } };
等于(S.能接诊吗(哨兵, 2, '丙'), false, '两张床都占着 → 丙 接不了');
等于(S.能接诊吗(哨兵, 3, '丙'), true, '开到三张床 → 接得了');
等于(S.能接诊吗(哨兵, 2, '甲'), true, '甲 本人已经在诊 —— 那是复诊, 不占新床');
等于(S.能接诊吗({}, 1, '任何人'), true, '空诊所永远接得了');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
