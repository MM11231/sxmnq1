interface 原始块 {
  标签: string | null;
  内容: string;
  未闭合: boolean;
}

/** 去掉标签和空白之后的纯文本。 */
const 纯文本 = (s: string): string => (s ?? '').replace(/<[^>]*>/g, '').replace(/\s/g, '');

/** 汉字个数。 */
const 汉字数 = (s: string): number => (纯文本(s).match(/[一-鿿]/g) || []).length;

/**
 * 散文分 = 汉字数 × 汉字占比。
 *
 * 为什么是乘两下而不是看其中一个:
 *   只看汉字数 —— 一段很长的英文思维链会靠长度赢;
 *   只看占比   —— 一小段中文问答 (author_note 那种) 会靠纯度赢。
 * 乘起来 = 又长又像中文散文, 那正是剧情的样子。
 */
function 散文分(s: string): number {
  const 纯 = 纯文本(s);
  if (!纯.length) return 0;
  const 字 = 汉字数(s);
  return 字 * (字 / 纯.length);
}

/**
 * 把文本按**最外层**标签切成块。没被标签包住的散字归到 标签=null 的一块。
 *
 * 未闭合的标签要单独收尾: 被截断的消息里 `<content>` 常常开了没闭,
 * 只认闭合标签的话这一段内容会凭空消失 —— 而截断在酒馆里是常态, 不是脏数据。
 */
function 切顶层块(s: string): 原始块[] {
  const 块们: 原始块[] = [];
  const 栈: { 标签: string; 尾?: number }[] = [];
  // 标签名放宽到「任何不含空白和尖括号的字符」, 首字符仍要求是字母/下划线/汉字。
  //
  // 为什么必须放宽: 真见过 `<think_nya~>` —— 名字里有 `~`。收窄的字符集会让整个标签
  // 不被识别, 于是它连带裹着的思维链一起变成普通文字, 后面所有判据都跟着错位。
  // 首字符那条限制留着是为了不把 `a < b` 这种当成标签。
  const 式 = /<(\/?)([A-Za-z_一-鿿][^\s<>/]*)([^>]*?)(\/?)>/g;
  let 位 = 0;
  let m: RegExpExecArray | null;

  while ((m = 式.exec(s))) {
    const 斜 = m[1];
    const 名 = m[2];
    const 自闭 = m[4];

    if (栈.length === 0 && m.index > 位) {
      const 散 = s.slice(位, m.index);
      if (散.trim()) 块们.push({ 标签: null, 内容: 散, 未闭合: false });
    }

    if (斜) {
      const 开 = 栈.pop();
      if (开 && 栈.length === 0) {
        块们.push({ 标签: 开.标签, 内容: s.slice(开.尾!, m.index), 未闭合: false });
      }
    } else if (!自闭) {
      栈.push(栈.length === 0 ? { 标签: 名, 尾: 式.lastIndex } : { 标签: 名 });
    } else if (栈.length === 0) {
      块们.push({ 标签: 名, 内容: '', 未闭合: false });
    }

    位 = 式.lastIndex;
  }

  if (栈.length) {
    // 最外层那个没关上 —— 剩下的全是它的内容。
    const 开 = 栈[0];
    块们.push({ 标签: 开.标签, 内容: s.slice(开.尾!), 未闭合: true });
  } else if (位 < s.length) {
    const 散 = s.slice(位);
    if (散.trim()) 块们.push({ 标签: null, 内容: 散, 未闭合: false });
  }

  return 块们;
}

/** 是自家控制块吗 —— 全等, 不放宽。 */
const 是控制块 = (名: string): boolean => 自家控制块.has(名.toLowerCase());

/** 命中正文容器吗 —— 全等。容器是玩家显式写出来的, 得准。 */
const 是容器 = (名: string | null, 容器表: Set<string>): boolean =>
  !!名 && 容器表.has(名.toLowerCase());

/** 命中噪声表吗 —— **子串**, 见 默认噪声标签 上面那段。 */
const 是噪声 = (名: string | null, 噪声表: string[]): boolean => {
  if (!名) return false;
  const 低 = 名.toLowerCase();
  return 噪声表.some(n => n && 低.includes(n.toLowerCase()));
};

/** 给折叠块取个好看的标题。内层 `<summary>` 的文字最优先 —— 那本来就是标题。 */
function 取标题(块: { 标签: string | null; 内容: string }): string {
  const 内 = 块.内容.match(/<summary>([\s\S]*?)<\/summary>/i);
  if (内) {
    const 文 = 内[1].replace(/<[^>]*>/g, '').trim();
    if (文) return 文;
  }
  if (块.标签) {
    for (const [式, 名] of 名字表) if (式.test(块.标签)) return 名;
    // 认不出来就把标签名原样显示 —— 玩家一眼就知道该往适配表里加什么。
    return 块.标签;
  }
  return '零散文字';
}

// ---------------------------------------------------------------- 行级外语
//
// 双语镜像预设 (2026-10-05 实测, `story_scene` 里逐行交替):
//
//   ☆‹錆びついたシャッターが上がりきると、外の冷たい空気が…›
//   生锈的卷帘门彻底升起，外面的冷空气与消毒液的味道混合在一起，流进了候诊室。
//
// 块级判据管不到这一层 —— 上面挑块挑得完全正确, 两轨却一起渲染了出来。

/**
 * 中文里**不会出现的字符**。判「这一行是不是外语轨」只能靠它。
 *
 * ★ 不能靠「汉字少」: 日文行里汉字一大把 (`錆びついたシャッターが…` 十几个),
 *   用汉字数判会得出「这全是中文」。2026-10-05 那版探针就是这么写的, 拿真实记录跑,
 *   报回来「外语行 0 行」—— 一个永远返回 0 的坏探针, 差点当成「已经没问题了」。
 *
 * 覆盖: 平假名/片假名、谚文、西里尔、希伯来、阿拉伯、泰文、天城文。
 */
const 非中文外文 =
  /[぀-ゟ゠-ヿ가-힯ᄀ-ᇿЀ-ӿ֐-׿؀-ۿ฀-๿ऀ-ॿ]/g;

/** 拉丁字母。中文里夹英文是常态, 所以它单独一条判据, 阈值要高。 */
const 拉丁 = /[A-Za-z]/g;

/**
 * 这一行是不是外语。
 *
 * 三条判据取或。前两条针对「中文里根本不会出现那些字」的语言, 第三条针对英文 ——
 * 英文的难点不在于认出来, 而在于**别把 `B 级`、`OK` 这种正常夹用的也认进去**。
 */
function 是外语行(行: string): boolean {
  const 外 = (行.match(非中文外文) || []).length;
  // ① 有两个外文字就够了 —— 中文句子里不会无缘无故冒出假名/谚文/西里尔。
  if (外 >= 2) return true;

  const 汉 = 汉字数(行);
  // ② 只有一个外文字, 但一个汉字都没有 —— `‹カ›` 这种被装饰符包着的短行。
  if (外 >= 1 && 汉 === 0) return true;

  // ③ 英文: 一个汉字都没有, 而且拉丁字母得够多。
  //    阈值 8 是放 `B 级`、`OK`、`HP+10` 这类中文里正常夹的英文过去。
  return 汉 === 0 && (行.match(拉丁) || []).length >= 8;
}

/**
 * 从外语行里**学出预设自己那套装饰**, 用来兜住判据一、二都够不着的标点行。
 *
 * 真实那楼里就漏了一对 (唯一漏的一行, 占 54 行的 1/54):
 *
 *   ☆‹「……」›      ← 装饰符包着, 可里面一个假名、一个字母、一个汉字都没有
 *   "……"            ← 它的译文
 *
 * 为什么是「学」而不是写死 `☆‹`: 每份预设的包装都不一样, 写死等于只伺候这一份,
 * 换份预设照样漏。这里从同一块里已有的外语行取**最长公共前后缀** ——
 * 26 行日文共同的 `☆‹` 和 `›` 就是这么来的。
 *
 * 只认**不含字母和数字**的头尾: 那是「装饰符」的定义。少了这条,
 * 一堆首字母相同的英文行会让公共前缀变成 `The`, 然后去误伤别的行。
 */
function 学装饰(外语行们: string[]): { 头: string; 尾: string } | null {
  if (外语行们.length < 2) return null;

  let 头 = 外语行们[0];
  let 尾 = 外语行们[0];
  for (const 行 of 外语行们.slice(1)) {
    let i = 0;
    while (i < 头.length && i < 行.length && 头[i] === 行[i]) i++;
    头 = 头.slice(0, i);

    let j = 0;
    while (j < 尾.length && j < 行.length && 尾[尾.length - 1 - j] === 行[行.length - 1 - j]) j++;
    尾 = 尾.slice(尾.length - j);
  }

  // 头尾不能重叠到把整行吃掉, 也不能太短 —— 一两个字很容易误伤普通标点行。
  const 样本 = 外语行们[0];
  if (!头.length && !尾.length) return null;
  if (头.length + 尾.length >= 样本.length) return null;
  if (/[\p{L}\p{N}]/u.test(头 + 尾)) return null;

  // 注意这里交出去的尾**可能是 `。›` 而不是 `›`**: 26 行日文句句以 `。›` 收尾,
  // 公共后缀就学到了句号。句号不是装饰, 是句读 —— 是 是装饰行() 里退到「最外层一个字」
  // 的理由, 见那边的注释。别在这儿削, 削不干净: 句号落在被剥掉的尾巴里, 够不着。
  return { 头, 尾 };
}

/** 这一行带着那套学来的装饰吗。只对「没有汉字的短标点行」放行, 不碰真正的散文。 */
function 是装饰行(行: string, 装: { 头: string; 尾: string } | null): boolean {
  if (!装) return false;
  // 这一行的汉字和拉丁都必须是 0, 所以底下宽松不宽松都误伤不到中文译文。
  if (汉字数(行) > 0 || (行.match(拉丁) || []).length >= 8) return false;

  // 退到**最外层那一个字符**去认, 沾上任意一头就算。
  //
  // 为什么不用整段头尾、也不用两头都中 —— 都是被 `☆‹「……」›` 逼出来的:
  //   ① 学出来的尾是 `。›` 不是 `›`(句号被公共后缀捎上了, 见 学装饰), 整段比就失配;
  //      头这边同理, 外语行要是都以 `☆‹「` 开头, 头也会把开引号吞进去。
  //   ② 两头都要中就更严了。可 `☆` `›` 才是预设写死在纸面上的包装,
  //      真正该问的是「这行是不是被那套装帧包着」, 而不是「两头是不是都齐」。
  // 这一行的汉字和拉丁已经确认是 0, 宽松到这一步没有误伤空间。
  const 首 = 装.头[0];
  const 末 = 装.尾[装.尾.length - 1];
  if (首 !== undefined && 行.length > 1 && 行.startsWith(首)) return true;
  if (末 !== undefined && 行.length > 1 && 行.endsWith(末)) return true;
  return false;
}

/** 给折叠条取个「原文（日文）」用的名字。认不出就只说「原文」。 */
function 语言名(行们: string[]): string {
  const 全 = 行们.join('');
  if (/[぀-ゟ゠-ヿ]/.test(全)) return '日文';
  if (/[가-힯ᄀ-ᇿ]/.test(全)) return '韩文';
  if (/[Ѐ-ӿ]/.test(全)) return '俄文';
  if (/[֐-׿]/.test(全)) return '希伯来文';
  if (/[؀-ۿ]/.test(全)) return '阿拉伯文';
  if (/[A-Za-z]/.test(全)) return '英文';
  return '原文';
}

/**
 * 中文轨至少要占整块的这么多, 才敢折外语。
 *
 * ★ 这是**安全闸**, 不是调优参数: 少了它, 一份纯英文预设 (或者英文玩家) 打开界面会
 *   发现整篇正文被折了起来 —— 比不折糟得多, 而且一句错都不报。
 *   判据落在「中文轨的字符数」上而不是行数上: 中文行可能又多又短。
 */
const 中文轨下限 = 0.25;

// ---------------------------------------------------------------- 主流程

/**
 * 把一条原始消息切成要显示的几块。**不丢内容** —— 除了 HTML 注释和本卡自己的控制块,
 * 其余每一个字都会出现在某一块里。
 *
 * 判据的顺序 (为什么容器排在噪声前面): 容器是玩家显式写出来的, 比黑名单可靠 ——
 * 万一某份预设的正文容器名恰好长得像噪声表里某一条的子串, 显式声明应该赢。
 */
/**
 * 把摊开那块的正文切成片段。**不丢字** —— 外语行只是被挪进 `原文` 片段, 不在原地消失。
 *
 * 配对规则 (源顺序是「原文在前」还是「译文在前」都归到这里):
 *   把连续的同轨行攒成一段, 中文轨先落地, 外语轨紧随其后。
 *   于是玩家读到的永远是「译文, 下面挂一条原文」, 不管预设怎么排。
 *
 * 段落这一层**必须保留**: 全中文的故事靠空行分段, 直接按行跑会把所有段落并成一大坨。
 * (主界面 App.vue 原来的 `分段()` 就是按空行切的, 这里接手了它。)
 */
export function 切片段(内容: string, 折外语: boolean = true): 片段[] {
  const 段们 = (内容 ?? '')
    .split(/\n\s*\n/)
    .map(段 => 段.trim())
    .filter(Boolean);
  if (!段们.length) return [];

  const 行组 = 段们.map(段 =>
    段
      .split('\n')
      .map(行 => 行.trim())
      .filter(Boolean),
  );

  // 分两遍: 先用判据一、二把「明显是外语」的行认出来, 再从它们身上学出预设的装饰,
  // 回头兜住那些一个假名一个字母都没有的标点行 (见 学装饰 上面那一对真实例子)。
  const 全行 = 行组.flat();
  const 装饰 = 学装饰(全行.filter(是外语行));
  const 归外语 = (行: string) => 是外语行(行) || 是装饰行(行, 装饰);

  // 安全闸: 中文轨太薄就整块不折。见 中文轨下限 上面。
  const 总字 = 全行.join('').length;
  const 中文字 = 全行.filter(行 => !归外语(行)).join('').length;
  const 可折 = !!折外语 && 总字 > 0 && 中文字 >= 总字 * 中文轨下限;

  const 出: 片段[] = [];
  for (const 行们 of 行组) {
    const 文: string[] = [];
    const 外: string[] = [];
    const 吐 = () => {
      if (文.length) {
        出.push({ 类: '文', 文: 文.join('\n') });
        文.length = 0;
      }
      if (外.length) {
        出.push({ 类: '原文', 文: 外.join('\n'), 语言: 语言名(外) });
        外.length = 0;
      }
    };

    for (const 行 of 行们) {
      if (可折 && 归外语(行)) {
        // 中文轨先落地, 外语紧随其后。这一句就是「逐句折在译文旁」的全部实现。
        if (文.length) 吐();
        外.push(行);
      } else {
        文.push(行);
      }
    }
    吐();
  }
  return 出;
}

export function 切块(原文: string, 适配: 适配表类型 = 默认适配): 显示块[] {
  const 文 = (原文 ?? '').replace(注释, '');

  // 自家控制块整块丢掉, 连没闭合的也算 —— 变量块开了头没收尾在流式生成里很常见,
  // 而它一定在正文之后, 丢掉它不会碰到剧情。
  const 生的 = 切顶层块(文).filter(b => !(b.标签 && 是控制块(b.标签)));
  if (!生的.length) return [];

  const 容器表 = new Set(适配.正文容器.map(名 => 名.toLowerCase()));

  // 谁默认展开。三档, 依次退让。
  let 展开的: 原始块 | null = 生的.find(b => 是容器(b.标签, 容器表)) ?? null;

  if (!展开的) {
    // 没有显式容器。在**没被认成噪声**的块里按散文分挑, 而且要领先够多才敢挑。
    const 候选 = 生的.filter(b => !是噪声(b.标签, 适配.噪声标签));
    if (候选.length) {
      const 排 = [...候选].sort((a, b) => 散文分(b.内容) - 散文分(a.内容));
      const 一 = 散文分(排[0].内容);
      const 二 = 排[1] ? 散文分(排[1].内容) : 0;
      if (一 > 最低分 && 一 >= 二 * 领先倍数) 展开的 = 排[0];
    }
  }

  // 还是没挑出来 —— 尽量别让界面一个字都不摊开。挑最长的那块, 哪怕它是噪声。
  if (!展开的) {
    展开的 = [...生的].sort((a, b) => 纯文本(b.内容).length - 纯文本(a.内容).length)[0];
  }

  return 生的.map(b => {
    const 内容 = b.内容.trim();
    const 正文 = b === 展开的;
    return {
      标签: b.标签,
      标题: 取标题(b),
      内容,
      正文,
      字数: 纯文本(b.内容).length,
      // 折起来的块不细切: 它本来就要点开才看, 切了也只是多一层嵌套。
      片段: 正文 ? 切片段(内容, 适配.折外语) : [{ 类: '文', 文: 内容 } as 片段],
    };
  });
}

/**
 * 只要正文那一段的纯文本。给「历史」抽屉这类**需要紧凑**的地方用 ——
 * 那里一行一条, 摊开折叠块没有意义。
 *
 * 取的是 `文` 片段而不是 `内容`: 历史抽屉更窄, 把外语轨也塞进去只会让它变成一团。
 */
export function 取正文(原文: string, 适配: 适配表类型 = 默认适配): string {
  const 块 = 切块(原文, 适配).find(b => b.正文);
  if (!块) return '';
  return 块.片段
    .filter(f => f.类 === '文')
    .map(f => f.文)
    .join('\n\n');
}
