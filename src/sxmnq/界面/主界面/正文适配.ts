// 预设适配层 —— 「正文长什么样」是**预设**决定的, 而预设是玩家自带的, 我们控制不了。
//
// 这一层只干一件事: 把一整条 AI 消息切成**要显示的几块**, 并指出哪一块是正文。
// `正文.ts` 负责从楼层取原文、把玩家的配置读进来; `App.vue` 负责渲染。
//
// ---------------------------------------------------------------- 为什么是「切块」不是「抠正文」
//
// 早先这里是「从消息里抠出正文那一段, 其余全丢」。那个模型有个致命的不对称:
// **判据一旦失手, 要么漏标签、要么把剧情整段丢掉, 而且都不报错。**
//
// 真实翻车记录 (2026-10-05, 一份喵系预设): 它把思维链包在 `<think_nya~>` 里、正文包在
// `<game>` 里。`~` 当时不在标签名字符集里, 整段思维链没被认成标签, 变成一块「无标签散字」;
// 而它是**中文的、还比正文长** (1050 字 vs 980 字) —— 散文分判据分不出高下, 于是落到
// 「全显示」兜底, 2518 字连着标签一起糊到界面上。
//
// 关键教训: **中文思维链 + 散文分判据 = 结构性失效**, 不是阈值调调就能好的。所以改成:
//   每块都留着, 只是**默认展开一块、其余折起来**。
// 判据错了的最坏后果从「丢剧情」降成「折错了一块」—— 玩家看得见, 点开就有。
//
// 另外这里每一条判据都是**量出来的**: 拿真实聊天记录跑过 15 条消息, 含一次被截断的生成
// (标签开了没闭) 和一次白名单外的容器名。动阈值之前先重跑 正文适配.test.mjs。
//
// ---------------------------------------------------------------- 三个层级
//
// 一条消息的脏法有三层, 分别归三处管, 少一层都会漏:
//   ① 标签级 —— `<thinking>` 这种整块不是剧情。归 默认噪声标签 / 默认正文容器。
//   ② 块级   —— 挑哪一块摊开。归 切块()。
//   ③ 行级   —— 双语镜像预设把原文和译文写在同一块里, 逐行交替。归 切片段()。
// ③ 是 2026-10-05 加的: 那时 ①② 都判对了, 界面照样把整条日文轨糊了出来。

