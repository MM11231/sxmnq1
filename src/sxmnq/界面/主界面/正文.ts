// 正文从哪来。
//
// 正则把整条消息换成了界面, 所以玩家在聊天区看不见剧情 —— 剧情得由界面自己从
// **原始消息文本**里读出来重新渲染。`getChatMessages` 给的是原始文本, 变量更新标签、
// 占位符、预设的思维链这些都还在里面, 所以要先切开、再决定摊开哪一块。
//
// 「怎么切」全在 正文适配.ts: 那一层只管认预设, 这一层只管取原文和读配置。

import { 默认适配, 适配表, 切块 as 按适配切块, 取正文 as 按适配取正文, type 适配表类型, type 显示块 } from './正文适配';

/**
 * 适配表在全局变量里的键名。
 *
 * 为什么放全局变量而不是写死在代码里: 这张卡是要发给别人用的, 而**预设是玩家自带的**,
 * 我们见不到他们的标签长什么样。真遇到认不出的预设时, 玩家在酒馆助手的变量面板里往
 * 这个键加一行就行, 不用等我们改代码重新发版。
 */
const 配置键 = '正文适配';

/** 读玩家的适配表。读不到、读坏了都退回默认 —— 界面不能因为一行配置写错就整个白屏。 */
export function 读适配(): 适配表类型 {
  try {
    const 配 = getVariables({ type: 'global' })?.[配置键];
    if (!配) return 默认适配;
    return 适配表.parse(配);
  } catch (错) {
    console.warn('[正文适配] 全局变量 `正文适配` 读不动, 这回用默认的:', 错);
    return 默认适配;
  }
}

/**
 * 把一条消息切成要显示的几块 —— 主界面正文区用这个。
 *
 * 不传适配表就现读一次配置。正文跟着流式生成每 500ms 切一遍, 所以界面那边是
 * **开在 setup 里读一次**再把结果传进来的 (每次重切都去读一遍全局变量纯属浪费)。
 */
export function 切块(原文: string, 适配: 适配表类型 = 读适配()): 显示块[] {
  return 按适配切块(原文, 适配);
}

/**
 * 只要正文那一段的纯文本。历史抽屉那种一行一条的地方用 —— 那里摊开折叠块没有意义。
 */
export function 取正文(原文: string, 适配: 适配表类型 = 读适配()): string {
  return 按适配取正文(原文, 适配);
}

/** 读最新一楼的原始文本。`-1` 就是「最新」, 界面挂在哪一楼都不影响。 */
export function 读最新原文(): string {
  try {
    const 消 = getChatMessages(-1);
    return 消?.[0]?.message ?? '';
  } catch {
    return '';
  }
}
