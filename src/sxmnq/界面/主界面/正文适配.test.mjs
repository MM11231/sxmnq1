let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 扁 = s => (s ?? '').replace(/\s+/g, ' ').trim();
const 等于 = (实得, 期望, 说明) => {
  const a = 扁(实得);
  const b = 扁(期望);
  断言(a === b, a === b ? 说明 : `${说明}\n         期望 ${JSON.stringify(b.slice(0, 90))}\n         实得 ${JSON.stringify(a.slice(0, 90))}`);
};
const 含 = (实得, 片段, 说明) => 断言(扁(实得).includes(扁(片段)), 说明);
const 不含 = (实得, 片段, 说明) => 断言(!扁(实得).includes(扁(片段)), 说明);

// ---------------------------------------------------------------- 漏检器 + 自检
/** 数数还剩多少标签/注释。 */
const 漏多少 = s =>
  (s.match(/<\/?[A-Za-z_一-鿿][\w:.\-一-鿿]*/g) || []).length + (s.match(/<!--/g) || []).length;

console.log('\n=== 仪表自检: 漏检器真的会报红吗 ===');
// 「摊开的那块是干净的」是**阴性断言**, 一个永远返回 0 的坏探针能骗过所有用例。
断言(漏多少('<b>x</b><!-- y -->') === 3, '漏检器能数出残留 (这个数不对, 下面所有 ✓ 都不作数)');
断言(漏多少('干净的一句话') === 0, '漏检器在真的干净时不乱报');

/** 所有块拼起来 —— 用来验「一个字都没丢」 */
const 拼 = 块们 => 块们.map(b => b.内容).join('\n');
const 展开的 = 块们 => 块们.find(b => b.正文);
const 标题们 = 块们 => 块们.map(b => b.标题);

