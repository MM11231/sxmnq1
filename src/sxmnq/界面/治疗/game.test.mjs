// ---- 生成丝线 ----
console.log('--- 生成丝线 ---');
const 宽 = 390, 高 = 700;
for (const 条数 of [3, 7, 12, 25]) {
  const 线们 = G.生成丝线(条数, 宽, 高, 20260928);
  断言(线们.length === 条数, `${条数} 条 → 生成 ${线们.length} 条`);
  断言(
    线们.every(l => [l.x1, l.y1, l.x2, l.y2].every(v => v >= 0 && v <= 1)),
    `${条数} 条 → 坐标全部落在 0~1 内`,
  );
  const 最短 = Math.min(...线们.map(l => Math.hypot((l.x2 - l.x1) * 宽, (l.y2 - l.y1) * 高)));
  断言(最短 >= Math.hypot(宽, 高) * 0.25 - 1e-6, `${条数} 条 → 没有过短的线 (最短 ${最短.toFixed(0)}px)`);

  // 交叠: 数一数有多少对线真的相交
  const 交 = (a, b) => {
    const d = (p, q, r) => (q.x - p.x) * (r.y - p.y) - (q.y - p.y) * (r.x - p.x);
    const p1 = { x: a.x1 * 宽, y: a.y1 * 高 }, p2 = { x: a.x2 * 宽, y: a.y2 * 高 };
    const p3 = { x: b.x1 * 宽, y: b.y1 * 高 }, p4 = { x: b.x2 * 宽, y: b.y2 * 高 };
    const d1 = d(p3, p4, p1), d2 = d(p3, p4, p2), d3 = d(p1, p2, p3), d4 = d(p1, p2, p4);
    return ((d1 > 0) !== (d2 > 0)) && ((d3 > 0) !== (d4 > 0));
  };
  let 对数 = 0;
  for (let i = 0; i < 线们.length; i++)
    for (let j = i + 1; j < 线们.length; j++) if (交(线们[i], 线们[j])) 对数++;
  断言(对数 > 0, `${条数} 条 → 彼此交叠 (${对数} 对相交)`);
}
等于(G.生成丝线(8, 宽, 高, 42), G.生成丝线(8, 宽, 高, 42), '同种子 → 同一局, 可复现');

