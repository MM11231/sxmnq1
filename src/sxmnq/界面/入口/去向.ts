// 每条路线开局落在**哪一屏**。
//
// 为什么不直接在 入口/App.vue 里写 if/else: 以后再加一条路线而忘了加分支, 最后的
// `v-else` 会把它**静默地**接到诊所线那一屏上 —— 不报错、构建照过, 玩家只是看见
// 一屏跟他选的路线毫无关系的东西。写成一张表 + 一条测试盯住「路线取值里的每一条
// 这儿都有」, 这类漏就无从发生。
//
// 值只放**字符串**, 不直接放组件: 这个文件要能在 node 里 import (测试跑的就是它),
// 而 .vue 在 node 里 import 不了。字符串到组件的对应写在 入口/App.vue 的模板里,
// 两边靠这张表的键对齐。
import { 路线取值, type 路线键 } from '../../路线';

/** 界面这一层能去的那两屏。加一屏就往这儿加一个名字, 再去 入口/App.vue 接上。 */
export type 屏名 = '诊所' | '白塔';

export const 去向: Record<路线键, 屏名> = {
  诊所线: '诊所',
  白塔向导路线: '白塔',
};

/**
 * 路线取值的全集, 导出一份给测试用。
 *
 * 测试要断言「每一条路线都有去向」, 而 `路线取值` 是 `as const` 的元组 —— 直接从它
 * 推导就行, 不用在这儿再抄一份名单(抄一份就又多一处会忘记改的地方)。
 */
export const 全部路线 = 路线取值;
