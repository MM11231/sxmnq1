// 直接跑: node src/sxmnq/界面/入口/去向.test.mjs
//
// 这个文件盯的是**两张表跟路线名单对不对得上**:
//
//   1. `去向` —— 每条路线落在哪一屏。缺一条, 入口那个 `v-else` 会把它静默接到诊所线
//      那一屏上: 构建照过、不报错, 玩家选了白塔线却看见诊所的界面。
//   2. `路线表` —— 创建页那几张卡片。缺一条, 那条路在创建页上**根本没有卡片**,
//      玩家永远选不到它, 而代码里那条路是齐的。
//
// 两件都是「少了一个东西」的错 —— 少掉的东西不在 diff 里, 逐行审代码看不出来,
// 只有拿名单去对才看得见。
import './../../测试钩子.mjs';

const { 路线取值, 路线表 } = await import(new URL('../../路线.ts', import.meta.url).href);
const { 去向, 全部路线 } = await import(new URL('./去向.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};

console.log('--- ★ 每条路线都有去处 (缺的那条会被 v-else 静默接到诊所线) ---');
路线取值.forEach(键 => {
  const 值 = 去向[键];
  断言(typeof 值 === 'string' && 值.length > 0, `路线「${键}」有去向 (实得 ${JSON.stringify(值)})`);
});

console.log('--- 去向表里不许有没人认领的键 (死数据: 写了但没有路线会走到) ---');
Object.keys(去向).forEach(键 => {
  断言(路线取值.includes(键), `去向表里的「${键}」是一条真路线`);
});

console.log('--- 全部路线 跟 路线取值 是同一份名单 ---');
断言(全部路线.length === 路线取值.length, `条数一样 (路线取值 ${路线取值.length} / 全部路线 ${全部路线.length})`);
路线取值.forEach(键 => 断言(全部路线.includes(键), `全部路线 里有「${键}」`));

console.log('--- ★ 每条路线在创建页上都有一张卡 (缺一张 = 那条路玩家选不到) ---');
路线取值.forEach(键 => {
  断言(路线表.some(项 => 项.键 === 键), `路线「${键}」在 路线表 里有卡片`);
});
路线表.forEach(项 => {
  断言(路线取值.includes(项.键), `卡片「${项.名}」的键「${项.键}」在 路线取值 里 (写错了 schema 枚举就收不下)`);
});
断言(new Set(路线表.map(项 => 项.键)).size === 路线表.length, '没有两张卡写着同一个键 (同键的话上面那张点不到)');

console.log('--- 卡片本身的字段齐不齐 ---');
路线表.forEach(项 => {
  断言(typeof 项.名 === 'string' && 项.名.length > 0, `「${项.键}」有名字`);
  断言(typeof 项.介 === 'string' && 项.介.length > 0, `「${项.键}」有介绍 (空着卡片上就少一块)`);
  断言(typeof 项.开 === 'boolean', `「${项.键}」的 开 是布尔 (写成字符串的话创建页判不出灰不灰)`);
  断言(typeof 项.要命名 === 'boolean', `「${项.键}」的 要命名 是布尔`);
});

console.log('--- ★ 两条分支都得有人走 (没人走的那条就是死代码) ---');
// 创建页按 `要命名` 分成「进第三步」和「直接落盘」两条路。要是所有路线都要命名,
// 或者所有路线都不要, 另一条分支就永远执行不到 —— 而它照样在源码里躺着, 看起来
// 一切正常。所以这儿各要一条。
断言(路线表.some(项 => 项.要命名), '至少有一条路线走第三步 (要命名 为真)');
断言(路线表.some(项 => !项.要命名), '至少有一条路线不走第三步 (要命名 为假, 否则那个分支是死的)');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
