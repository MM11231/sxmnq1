// 直接跑: node src/sxmnq/生成/闸门.test.mjs
import '../测试钩子.mjs';

const G = await import(new URL('./闸门.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};
const 线性同余 = (种子) => {
  let s = 种子 >>> 0;
  return () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 4294967296);
};

console.log('--- 可来等级: D 起, 到诊所等级 +1 止 (spec §4.1) ---');
等于(G.可来等级('D'), ['D', 'C'], 'D 级诊所只来 D 和 C');
等于(G.可来等级('C'), ['D', 'C', 'B'], 'C 级 → 解一档 B');
等于(G.可来等级('B'), ['D', 'C', 'B', 'A'], 'B 级 → 解一档 A');
等于(G.可来等级('A'), ['D', 'C', 'B', 'A', 'S'], 'A 级 → 解锁到顶');
等于(G.可来等级('S'), ['D', 'C', 'B', 'A', 'S'], 'S 级不会溢出到第六档');

console.log('--- 闸门权重: 逐格对照 spec §4.2 的表 (25 格全测) ---');
// 行 = 诊所等级, 列 = 目标等级。**整张 5×5 都要有值** ——
// 池子之外的格子 (比如 D 级诊所 ← S 级病人) 掷等级 走不到, 但 闸门权重 是导出的纯函数,
// 「诊所比病人低时权重恒为 1」是设计事实, 不该只靠一个负号分支的巧合成立:
// 万一有人把 if (差 < 0) 那句删了, 差 = -2 会算成 5 —— 比同级还高, 池子一下子就反了。
const 期望表 = {
  D: { D: 3, C: 1, B: 1, A: 1, S: 1 },
  C: { D: 2, C: 3, B: 1, A: 1, S: 1 },
  B: { D: 1, C: 2, B: 3, A: 1, S: 1 },
  A: { D: 1, C: 1, B: 2, A: 3, S: 1 },
  S: { D: 1, C: 1, B: 1, A: 2, S: 3 },
};
const 全档 = ['D', 'C', 'B', 'A', 'S'];
for (const [诊所, 行] of Object.entries(期望表)) {
  for (const 目标 of 全档) {
    等于(G.闸门权重(诊所, 目标), 行[目标], `${诊所} 级诊所 ← ${目标} 级: 权重 ${行[目标]}`);
  }
}
断言(
  全档.every(诊所 => 全档.every(目标 => typeof 期望表[诊所][目标] === 'number')),
  '期望表本身盖满了 25 格 (漏一格这条会红, 而不是悄悄少测)',
);
断言(G.可来等级('D').every(t => t !== 'B' && t !== 'A' && t !== 'S'), 'D 级诊所的池子里没有 B 以上');

console.log('--- 掷等级: 高一级是稀客, 同级是多数 ---');
// 用同一个种子跑 4000 次, 看分布。不是精确值, 是「方向对不对」
const 计数 = { D: 0, C: 0, B: 0 };
const 随 = 线性同余(20260928);
for (let i = 0; i < 4000; i++) 计数[G.掷等级('C', 随)]++;
断言(计数.C > 计数.D && 计数.D > 计数.B, `C 级诊所: 同级(${计数.C}) > 低一档(${计数.D}) > 高一档(${计数.B})`);
断言(计数.B > 0, 'B 级客人抽得到 (不是被闸门挡死)');
断言(计数.C / 4000 > 0.45 && 计数.C / 4000 < 0.55, `同级占比 ≈ 50% (实得 ${(计数.C / 4000 * 100).toFixed(1)}%)`);

console.log('--- 掷等级 不会越过闸门 ---');
for (const 诊所 of ['D', 'C', 'B', 'A', 'S']) {
  const 允许 = new Set(G.可来等级(诊所));
  const 随2 = 线性同余(7);
  const 越界 = Array.from({ length: 2000 }, () => G.掷等级(诊所, 随2)).filter(t => !允许.has(t));
  等于(越界, [], `${诊所} 级诊所 2000 次里没有越界客人`);
}

console.log('--- 污染度区间: 逐档对照 spec §4.2 的表 ---');
等于(G.污染度区间, {
  D: [20, 45], C: [35, 65], B: [55, 85], A: [70, 95], S: [85, 100],
}, '五档区间与 spec 一致');

console.log('--- 掷污染度: 闭区间, 两端都取得到 ---');
const 序列 = (...值们) => { let i = 0; return () => 值们[i++ % 值们.length]; };
等于(G.掷污染度('D', 序列(0)), 20, 'D 级下限 20');
等于(G.掷污染度('D', 序列(0.999999)), 45, 'D 级上限 45');
等于(G.掷污染度('S', 序列(0)), 85, 'S 级下限 85');
等于(G.掷污染度('S', 序列(0.999999)), 100, 'S 级上限 100');
for (const 档 of ['D', 'C', 'B', 'A', 'S']) {
  const [低, 高] = G.污染度区间[档];
  const 越界 = Array.from({ length: 500 }, (_, i) => G.掷污染度(档, 线性同余(i + 1))).filter(v => v < 低 || v > 高);
  等于(越界, [], `${档} 档 500 次都落在 [${低}, ${高}]`);
}

console.log('--- 基础诊金: spec §4.3 的三个例子 ---');
等于(G.算基础诊金('D', 30), 100, 'D 级 · 污染 30 → 100');
等于(G.算基础诊金('C', 50), 180, 'C 级 · 污染 50 → 180');
等于(G.算基础诊金('S', 90), 380, 'S 级 · 污染 90 → 380');

console.log('--- 实际诊金: 评级系数只在这里乘 ---');
等于(G.算实际诊金(100, 1.2), 120, '基础 100 × S 档 1.2 = 120');
等于(G.算实际诊金(100, 1.0), 100, 'A 档 1.0 不变化');
等于(G.算实际诊金(101, 0.8), 81, 'B 档 0.8 且四舍五入');
等于(G.算实际诊金(101, 0.5), 51, 'C 档 0.5');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
