// 直接跑: node src/sxmnq/生成/姓名.test.mjs
//
// 名字从前端出的理由见 spec 2026-10-06-名单直出 §5.3, 以及 姓名.ts 的开头。
// 这个文件守两件不能出错的事:
//
//   ① 新姓名保持两到四字，兼容旧调用中的四字要求（归一到四字西式）。
//   ② **不重名。** 申请列表 以姓名为键, 重名是静默覆盖, 不是「多一个人」。
import '../测试钩子.mjs';

const X = await import(new URL('./姓名.ts', import.meta.url).href);
const P = await import(new URL('./池子.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};
const 线性同余 = (种子) => {
  let s = 种子 >>> 0;
  return () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 4294967296);
};

console.log('--- 池子的大小与纯净度 ---');
断言(P.姓氏池.length >= 60, `姓氏池至少 60 条 (实得 ${P.姓氏池.length})`);
断言(P.名用字池.length >= 40, `日常用字至少 40 条 (实得 ${P.名用字池.length})`);
断言(P.中式双字名池.length >= 80, '双字名经过完整筛选');
// 重字会让某个字被抽中的概率翻倍 —— 看不出来, 但它是一种静默的权重错。
断言(new Set(P.姓氏池).size === P.姓氏池.length, '姓氏池 无重复字');
断言(new Set(P.名用字池).size === P.名用字池.length, '名用字池 无重复字');
for (const 池 of [P.中式双字名池, ...Object.values(P.西式姓名池)]) 断言(new Set(池).size === 池.length, '完整名字池无重复');
断言(P.姓氏池.every(字 => 字.length === 1), '姓氏池 全是单字姓');
断言(P.战损任务池.length >= 8 && P.战损地点池.length >= 8 && P.战损后果池.length >= 6,
  `战损三池各有货 (${P.战损任务池.length}/${P.战损地点池.length}/${P.战损后果池.length})`);

console.log('--- ★ 六种 (字数, 中式) 组合都拼得出名字, 且满足原卡字数 ---');
// 同时验证新规则和旧四字调用的兼容行为。
for (const [长度, 池] of Object.entries(P.西式姓名池)) 断言(池.every(名 => 名.length === Number(长度)), '西式池字数正确');
断言(![...P.西式姓名池[2], ...P.西式姓名池[3], ...P.西式姓名池[4]].some(名 => /皮特|亚当|维克托|维克多|亚历山大|安德烈亚斯/.test(名)), '排除原卡禁止示例及同名变体');
断言(!P.名用字池.some(字 => /轩宸墨曦汐梓瑶璃嫣毅骏锋/.test(字)), '中式不堆古风或力量寓意');
const 组合们 = [
  { 字数: 2, 中式: true }, { 字数: 3, 中式: true }, { 字数: 4, 中式: true },
  { 字数: 2, 中式: false }, { 字数: 3, 中式: false }, { 字数: 4, 中式: false },
];
for (const 要求 of 组合们) {
  let 好 = true;
  for (let 种子 = 1; 种子 <= 200; 种子++) {
    const 名 = X.起一个名(要求, new Set(), 线性同余(种子));
    if (!名 || 名.length !== 要求.字数) {
      断言(false, `${要求.字数} 字${要求.中式 ? '中式' : '西式'}: 种子 ${种子} 拼出「${名}」(${名.length} 字)`);
      好 = false;
      break;
    }
  }
  断言(好, `${要求.字数} 字${要求.中式 ? '中式' : '西式'}: 200 个种子全部非空，输出 ${要求.字数} 字`);
}

console.log('--- ★ 避开集合里的名字一个都不能出现 ---');
// 这三个名字用**生成器自己**抽出来 (空避开集 + 种子 1), 所以「抽得到」是构造保证的。
// 别改回「拿池子下标 0/1 硬拼」: 拼一个 是先抽 名用字池/西式音节池 的,
// 而种子 1..300 的首抽下标只落在 9~14, 永远够不到 0/1 —— 那样拼出来的名字
// 在实现彻底无视 避开 时也撞不上, 断言就成了空转 (2026-10-06 实测灵敏度 0)。
// 种子取 1: 下面扫描的第一个种子就是 1, 实现一坏, 第一次抽就必然撞上 (实测灵敏度 9)。
const 已有 = new Set([
  X.起一个名({ 字数: 2, 中式: true }, new Set(), 线性同余(1)),
  X.起一个名({ 字数: 3, 中式: true }, new Set(), 线性同余(1)),
  X.起一个名({ 字数: 2, 中式: false }, new Set(), 线性同余(1)),
]);
等于(已有.size, 3, '三个样本名字互不相同 (否则避开集比看上去小)');
let 撞了 = 0;
for (const 要求 of 组合们) {
  for (let 种子 = 1; 种子 <= 300; 种子++) {
    if (已有.has(X.起一个名(要求, 已有, 线性同余(种子)))) 撞了++;
  }
}
等于(撞了, 0, '1800 次抽名里, 一次都没撞上避开集合 (撞了就是静默覆盖)');

console.log('--- 避开集合是只读的: 起名不该改它 ---');
{
  const 集 = new Set(['沈岩']);
  const 前 = [...集];
  X.起一个名({ 字数: 2, 中式: true }, 集, 线性同余(3));
  等于([...集], 前, '起名不动调用方的集合 (调用方自己 add)');
}

console.log('--- 连续撞名必须找到空闲姓名，所有候选耗尽也不能覆盖旧档案 ---');
{
  const 要求 = { 字数: 3, 中式: true };
  const 已占 = new Set([X.兜底名(要求)]);
  const 名 = X.起一个名(要求, 已占, () => 0);
  断言(!已占.has(名), '随机源始终抽中占用姓名时仍可去重');
  let 抛错 = false;
  try { X.起一个名(要求, { has: () => true }, () => 0); } catch { 抛错 = true; }
  断言(抛错, '全部用尽时明确报错，不覆盖已有姓名');
  const 西式用尽 = new Set(P.西式姓名池[2]);
  断言(!西式用尽.has(X.起一个名({ 字数: 2, 中式: false }, 西式用尽, () => 0)), '西式池用尽可借用中式姓名');
  const 累计 = new Set();
  const 随机 = 线性同余(20261017);
  const D = await import('./掷骰.ts');
  for (let i = 0; i < 4000; i++) {
    const 姓名 = X.起一个名(D.掷命名要求(随机), 累计, 随机);
    if (累计.has(姓名) || !/^[\p{Script=Han}]{2,4}$/u.test(姓名)) throw new Error(姓名);
    累计.add(姓名);
  }
  断言(累计.size === 4000, '连续生成 4000 个姓名无重复、无数字后缀，均为两到四字');
  console.log('实际抽样：' + [...累计].slice(0, 30).join('、'));
}

console.log('--- 战损来源: 三段拼, 非空, 两个种子给得出不同结果 ---');
{
  let 好 = true;
  const 见过 = new Set();
  for (let 种子 = 1; 种子 <= 200; 种子++) {
    const 损 = X.起一个战损(线性同余(种子));
    if (!损 || 损.length < 6) { 断言(false, `种子 ${种子}: 战损来源「${损}」太短`); 好 = false; break; }
    见过.add(损);
  }
  断言(好, '200 个种子的战损来源都非空且有实质内容');
  断言(见过.size > 20, `战损来源不是复读机 (200 次里有 ${见过.size} 种)`);
  断言(X.起一个战损(线性同余(7)) === X.起一个战损(线性同余(7)), '战损来源可复现');
}

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
