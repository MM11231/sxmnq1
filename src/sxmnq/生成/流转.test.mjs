// 直接跑: node src/sxmnq/生成/流转.test.mjs
import '../测试钩子.mjs';
const L = await import(new URL('./流转.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};
const 线性同余 = (种子) => {
  let s = 种子 >>> 0;
  return () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 4294967296);
};

/** 造一条掷完的档案。只填测试关心的字段, 其余给个能看出来的假值 */
const 造条 = (姓名) => ({
  等级: 'D', 污染度: 30, 诊金: 100,
  年龄: 25, 地域: '极北凛冬(军备重工): 骨架宽厚具压迫感。',
  精神体: { 纲: '哺乳纲', 方向: '食肉目', 栖息: '陆行', 体型: '中型(与人齐平)', 危险: '力量型' },
  特征: ['泪痣'], A面: '高冷', B面: '独占本能',
  姓名, 战损来源: 姓名 ? '清剿三号污染区时被精神体撕开防线' : '',
  字数: 3, 中式: true,
});
const 造今日 = (已生成于 = '', 待登记 = [], 申请列表 = {}) => ({ 已生成于, 待登记, 申请列表 });

console.log('--- 该掷了吗: 只看日期戳 ---');
等于(L.该掷了吗('', '霜降月第一日'), true, '开局戳是空的 → 该掷');
等于(L.该掷了吗('霜降月第一日', '霜降月第一日'), false, '戳等于今天 → 不掷');
等于(L.该掷了吗('霜降月第一日', '霜降月第二日'), true, '日期变了 → 该掷');
等于(L.该掷了吗('霜降月第一日', ''), false, '世界.日期 还没写 (AI 还没开张) → 不掷, 别抢先');

console.log('--- 晋级: 有名字的进申请列表, 没名字的留下 ---');
const 今日 = 造今日('霜降月第一日', [造条('沈砚'), 造条(''), 造条('白露')]);
等于(L.晋级已命名的(今日), ['沈砚', '白露'], '两个有名字的被晋级');
等于(Object.keys(今日.申请列表), ['沈砚', '白露'], '申请列表 里正好是这两个');
等于(今日.待登记.length, 1, '没名字的那个留在待登记');
等于(今日.待登记[0].姓名, '', '留下来的确实是没名字的那个');

console.log('--- 晋级的条目: 字段照搬, 状态写「待接」, 字数/中式 丢掉 ---');
const 沈 = 今日.申请列表.沈砚;
等于(沈.等级, 'D', '等级 照搬');
等于(沈.污染度, 30, '污染度 照搬');
等于(沈.诊金, 100, '诊金 照搬');
等于(沈.战损来源, '清剿三号污染区时被精神体撕开防线', '战损来源 照搬');
等于(沈.状态, '待接', '状态 是「待接」');
等于(沈.精神体.纲, '哺乳纲', '精神体 整个带过来了');
断言(!('字数' in 沈) && !('中式' in 沈), '字数/中式 不进申请列表 (那是给 AI 下指令用的)');
断言(!('姓名' in 沈), '姓名 不进申请列表 (它就是 key)');

console.log('--- 晋级 是幂等的: 再跑一次不会有变化 ---');
const 第二次 = L.晋级已命名的(今日);
等于(第二次, [], '第二次没有可晋级的');
等于(Object.keys(今日.申请列表).length, 2, '申请列表 没重样');
等于(今日.待登记.length, 1, '待登记 没被再摘一次');

console.log('--- 跑一次 日期没变: 只晋级, 不掷 ---');
const 今2 = 造今日('霜降月第一日', [造条('陆时')], { 沈砚: { 状态: '已接' } });
const 果2 = L.跑一次(今2, '霜降月第一日', 'C', 线性同余(1));
等于(果2.掷了, false, '日期没变 → 没掷');
等于(果2.晋级, ['陆时'], '陆时 晋级了');
等于(Object.keys(今2.申请列表).sort(), ['沈砚', '陆时'].sort(), '旧的申请没被冲掉, 新的加进来');

console.log('--- 跑一次 日期变了: 清空申请列表, 重掷一批 ---');
const 今3 = 造今日('霜降月第一日', [造条('沈砚')], { 沈砚: { 状态: '待接' }, 白露: { 状态: '已接' } });
const 果3 = L.跑一次(今3, '霜降月第二日', 'C', 线性同余(2));
等于(果3.掷了, true, '日期变了 → 掷了');
等于(果3.新掷 >= 3 && 果3.新掷 <= 6, true, `掷了 ${果3.新掷} 个人 (3~6)`);
等于(今3.已生成于, '霜降月第二日', '日期戳更新了');
等于(今3.申请列表, {}, '申请列表 清空了 (连同昨天没接的白露)');
等于(今3.待登记.length, 果3.新掷, '待登记 就是新掷的那一批');
断言(今3.待登记.every(人 => 人.姓名 === ''), '新掷的人全都没有名字');

console.log('--- ★ 幂等是这一层的命门: 连跑 20 次, 仍然只有一批 ---');
const 今4 = 造今日('', [], {});
let 掷了几次 = 0;
for (let i = 0; i < 20; i++) {
  if (L.跑一次(今4, '霜降月第一日', 'B', 线性同余(9)).掷了) 掷了几次++;
}
等于(掷了几次, 1, '20 次调用里只有第一次真的掷了 (iframe 重建 20 次也不会多来病人)');
等于(今4.已生成于, '霜降月第一日', '戳停在今天');

console.log('--- 幂等 也扛得住交替的日期 (剧情来回改日期) ---');
const 今5 = 造今日('', [], {});
L.跑一次(今5, '霜降月第一日', 'B', 线性同余(11));
const 一批 = JSON.stringify(今5.待登记);
L.跑一次(今5, '霜降月第一日', 'B', 线性同余(12));
等于(JSON.stringify(今5.待登记), 一批, '同一天再跑, 批次逐字不变 (没被重新掷)');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
