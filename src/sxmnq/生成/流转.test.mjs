// 直接跑: node src/sxmnq/生成/流转.test.mjs
//
// 2026-10-06「名单直出」之后这个文件只剩一件事要守: **幂等**。
// 状态栏 iframe 每次渲染消息都会重建, 跑一次() 会被调用很多次,
// 唯一挡住重复掷骰的是 今日.已生成于 那个日期戳。
//
// 「谁进名单」不再测了 —— 名单是 掷一批 直接产出的, 归 生成.test.mjs。
import '../测试钩子.mjs';
const L = await import(new URL('./流转.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};
const 线性同余 = (种子) => {
  let s = 种子 >>> 0;
  return () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 4294967296);
};
const 造今日 = (已生成于 = '', 申请列表 = {}) => ({ 已生成于, 申请列表 });

console.log('--- 该掷了吗: 只看日期戳 ---');
等于(L.该掷了吗('', '霜降月第一日'), true, '开局戳是空的 → 该掷');
等于(L.该掷了吗('霜降月第一日', '霜降月第一日'), false, '戳等于今天 → 不掷');
等于(L.该掷了吗('霜降月第一日', '霜降月第二日'), true, '日期变了 → 该掷');
等于(L.该掷了吗('霜降月第一日', ''), false, '世界.日期 还没写 (AI 还没开张) → 不掷, 别抢先');

console.log('--- 日期变了: 清空昨天的名单, 掷一批新的 ---');
{
  const 今 = 造今日('霜降月第一日', { 沈砚: { 状态: '待接' }, 白露: { 状态: '已接' } });
  const 果 = L.跑一次(今, '霜降月第二日', 'C', {}, 线性同余(2));
  等于(果.掷了, true, '日期变了 → 掷了');
  等于(果.新掷, 3, '★ C 档来 3 个人 (2 + 等级值[C]=1)');
  等于(Object.keys(今.申请列表).length, 3, '申请列表 就是新掷出来的三个人');
  // ★ 探针用「白露」而不是「沈砚」。白 不在 姓氏池 里, 所以「白露」**不可能**
  //   被 起一个名 拼出来 —— 名单里出现它只可能是昨天那份没清干净。
  //   拿「沈砚」当探针是坏的: 沈 与 砚 都在池子里, 今天真可能又掷出一个沈砚,
  //   那条断言会随种子假红 (memory: grep 判据先自检仪表 —— 探针先得探得到)。
  断言(!('白露' in 今.申请列表), '★ 昨天那份名单整个作废了 (白露拼不出来, 只能是昨天的残留)');
  等于(今.已生成于, '霜降月第二日', '日期戳更新了');
}

console.log('--- ★ 同一天再跑: 一个字节都不动 ---');
{
  const 今 = 造今日('', {});
  const 果甲 = L.跑一次(今, '霜降月第一日', 'B', {}, 线性同余(4));
  const 快照 = JSON.stringify(今.申请列表);
  等于(果甲.掷了, true, '第一次掷了');
  const 果乙 = L.跑一次(今, '霜降月第一日', 'B', {}, 线性同余(5));
  等于(果乙.掷了, false, '第二次没掷');
  等于(果乙.新掷, 0, '第二次新掷 0');
  等于(JSON.stringify(今.申请列表), 快照, '★ 名单逐字不变 (换了个种子也没用 —— 根本没重掷)');
  等于(今.已生成于, '霜降月第一日', '戳停在今天');
}

console.log('--- ★ 幂等是这一层的命门: 连跑 20 次, 仍然只有一批 ---');
{
  const 今 = 造今日('', {});
  let 掷了几次 = 0;
  for (let i = 0; i < 20; i++) {
    if (L.跑一次(今, '霜降月第一日', 'B', {}, 线性同余(9 + i)).掷了) 掷了几次++;
  }
  等于(掷了几次, 1, '20 次调用里只有第一次真的掷了 (iframe 重建 20 次也不会多来病人)');
  等于(Object.keys(今.申请列表).length, 4, 'B 档 4 个人 (2 + 等级值[B]=2)');
}

console.log('--- ★ 哨兵: 只有 已出院 的会回到名单上 ---');
{
  const 哨兵 = {
    白露: { 状态: '已出院' },   // 唯一该回来的
    陆时: { 状态: '在诊' },     // 占着床, 不该再申请一次
    柯云舟: { 状态: '已收编' }, // 已经留在诊所了
  };
  // 白/陆/柯 都不在 姓氏池 里 —— 所以这三个名字**不可能**被 起一个名 拼出来,
  // 名单里出现它们只可能是 回头客池 那条路 (见 memory: grep 判据先自检仪表)。
  let 白露出现 = 0;
  let 别的出现 = 0;
  for (let 种子 = 1; 种子 <= 400; 种子++) {
    const 今 = 造今日('', {});
    L.跑一次(今, '霜降月第一日', 'S', 哨兵, 线性同余(种子));
    const 键 = Object.keys(今.申请列表);
    if (键.includes('白露')) 白露出现++;
    if (键.includes('陆时') || 键.includes('柯云舟')) 别的出现++;
  }
  断言(白露出现 > 0, `已出院的白露回来过 (实得 ${白露出现}/400)`);
  等于(别的出现, 0, '★ 在诊的与已收编的一次都没出现');
}

console.log('--- 哨兵表空着也照样跑得动 ---');
{
  const 今 = 造今日('', {});
  const 果 = L.跑一次(今, '霜降月第一日', 'D', {}, 线性同余(7));
  等于(果.新掷, 2, 'D 档开局来 2 个人');
  等于(Object.keys(今.申请列表).length, 2, '名单里正好 2 个');
}

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
