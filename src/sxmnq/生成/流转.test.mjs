import '../测试钩子.mjs';
const L = await import(new URL('./流转.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};
const 线性同余 = (种子) => {
  let s = 种子 >>> 0;
  return () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 4294967296);
};

/** 造一条掷完的档案。只填测试关心的字段, 其余给个能看出来的假值 */
const 造条 = (姓名) => ({
  等级: 'D', 污染度: 30, 诊金: 100,
  年龄: 25, 地域: '极北凛冬(军备重工): 骨架宽厚具压迫感。',
  精神体: { 纲: '哺乳纲', 方向: '食肉目', 栖息: '陆行', 体型: '中型(与人齐平)', 危险: '力量型' },
  特征: ['泪痣'], A面: '高冷', B面: '独占本能',
  姓名, 战损来源: 姓名 ? '清剿三号污染区时被精神体撕开防线' : '',
  字数: 3, 中式: true,
});
const 造今日 = (已生成于 = '', 待登记 = [], 申请列表 = {}, 登场 = []) =>
  ({ 已生成于, 待登记, 申请列表, 登场 });
/** AI 报到的一条 */
const 造报 = (姓名, 战损来源 = '', 自创 = false) => ({ 姓名, 战损来源, 自创 });
/** 造一张掷好的申请单。`记` 写进 污染度 与 地域, 用来断言「吃掉的是第几张」。
 *  姓名 必须是空串 (空串才会留在 待登记 里等 AI), 但 **战损来源要留着** ——
 *  生产里的 掷一个() 把它留空, 而这里要验的是「AI 没写时回落到单子上的值」,
 *  底的战损来源也是空串的话, 那条断言两边都是 '' , 验不出任何东西。 */
const 造单 = (记) => ({ ...造条('占位'), 姓名: '', 污染度: 记, 地域: `抽查地-${记}` });

console.log('--- 该掷了吗: 只看日期戳 ---');
等于(L.该掷了吗('', '霜降月第一日'), true, '开局戳是空的 → 该掷');
等于(L.该掷了吗('霜降月第一日', '霜降月第一日'), false, '戳等于今天 → 不掷');
等于(L.该掷了吗('霜降月第一日', '霜降月第二日'), true, '日期变了 → 该掷');
等于(L.该掷了吗('霜降月第一日', ''), false, '世界.日期 还没写 (AI 还没开张) → 不掷, 别抢先');

console.log('--- 晋级: 有名字的进申请列表, 没名字的留下 ---');
const 今日 = 造今日('霜降月第一日', [造条('沈砚'), 造条(''), 造条('白露')]);
等于(L.晋级已命名的(今日), ['沈砚', '白露'], '两个有名字的被晋级');
等于(Object.keys(今日.申请列表), ['沈砚', '白露'], '申请列表 里正好是这两个');
等于(今日.待登记.length, 1, '没名字的那个留在待登记');
等于(今日.待登记[0].姓名, '', '留下来的确实是没名字的那个');

console.log('--- 晋级的条目: 字段照搬, 状态写「待接」, 字数/中式 丢掉 ---');
const 沈 = 今日.申请列表.沈砚;
等于(沈.等级, 'D', '等级 照搬');
等于(沈.污染度, 30, '污染度 照搬');
等于(沈.诊金, 100, '诊金 照搬');
等于(沈.战损来源, '清剿三号污染区时被精神体撕开防线', '战损来源 照搬');
等于(沈.状态, '待接', '状态 是「待接」');
等于(沈.精神体.纲, '哺乳纲', '精神体 整个带过来了');
断言(!('字数' in 沈) && !('中式' in 沈), '字数/中式 不进申请列表 (那是给 AI 下指令用的)');
断言(!('姓名' in 沈), '姓名 不进申请列表 (它就是 key)');

console.log('--- 晋级 是幂等的: 再跑一次不会有变化 ---');
const 第二次 = L.晋级已命名的(今日);
等于(第二次, [], '第二次没有可晋级的');
等于(Object.keys(今日.申请列表).length, 2, '申请列表 没重样');
等于(今日.待登记.length, 1, '待登记 没被再摘一次');

console.log('--- 跑一次 日期没变: 只晋级, 不掷 ---');
const 今2 = 造今日('霜降月第一日', [造条('陆时')], { 沈砚: { 状态: '已接' } });
const 果2 = L.跑一次(今2, '霜降月第一日', 'C', 线性同余(1));
等于(果2.掷了, false, '日期没变 → 没掷');
等于(果2.晋级, ['陆时'], '陆时 晋级了');
等于(Object.keys(今2.申请列表).sort(), ['沈砚', '陆时'].sort(), '旧的申请没被冲掉, 新的加进来');

console.log('--- 跑一次 日期变了: 清空申请列表, 重掷一批 ---');
const 今3 = 造今日('霜降月第一日', [造条('沈砚')], { 沈砚: { 状态: '待接' }, 白露: { 状态: '已接' } });
const 果3 = L.跑一次(今3, '霜降月第二日', 'C', 线性同余(2));
等于(果3.掷了, true, '日期变了 → 掷了');
等于(果3.新掷 >= 3 && 果3.新掷 <= 6, true, `掷了 ${果3.新掷} 个人 (3~6)`);
等于(今3.已生成于, '霜降月第二日', '日期戳更新了');
等于(今3.申请列表, {}, '申请列表 清空了 (连同昨天没接的白露)');
等于(今3.待登记.length, 果3.新掷, '待登记 就是新掷的那一批');
断言(今3.待登记.every(人 => 人.姓名 === ''), '新掷的人全都没有名字');

console.log('--- ★ 幂等是这一层的命门: 连跑 20 次, 仍然只有一批 ---');
const 今4 = 造今日('', [], {});
let 掷了几次 = 0;
for (let i = 0; i < 20; i++) {
  if (L.跑一次(今4, '霜降月第一日', 'B', 线性同余(9)).掷了) 掷了几次++;
}
等于(掷了几次, 1, '20 次调用里只有第一次真的掷了 (iframe 重建 20 次也不会多来病人)');
等于(今4.已生成于, '霜降月第一日', '戳停在今天');

console.log('--- 幂等 也扛得住交替的日期 (剧情来回改日期) ---');
const 今5 = 造今日('', [], {});
L.跑一次(今5, '霜降月第一日', 'B', 线性同余(11));
const 一批 = JSON.stringify(今5.待登记);
L.跑一次(今5, '霜降月第一日', 'B', 线性同余(12));
等于(JSON.stringify(今5.待登记), 一批, '同一天再跑, 批次逐字不变 (没被重新掷)');

console.log('--- ★ 处理登场: FIFO 配对, 用最上面那张单子 ---');
const 今6 = 造今日('霜降月第一日', [造单(1), 造单(2), 造单(3)], {}, [造报('甲'), 造报('乙')]);
等于(L.处理登场(今6, 'C', 线性同余(1)), ['甲', '乙'], '两个人都收了, 按报到顺序');
等于(Object.values(今6.申请列表).map(人 => 人.污染度), [1, 2], '吃的是最上面两张 (污染度 1 和 2)');
等于(今6.待登记.map(单 => 单.污染度), [3], '第三张原样留着');
等于(今6.申请列表.甲.地域, '抽查地-1', '掷定值逐字段搬过来了');
等于(今6.申请列表.甲.状态, '待接', '状态是「待接」');
断言(!('字数' in 今6.申请列表.甲) && !('中式' in 今6.申请列表.甲), '字数/中式 不进申请列表');
等于(今6.登场, [], '处理完 登场 清空');

console.log('--- 处理登场: AI 写的战损来源优先, 空的话用单子里的 ---');
const 今7 = 造今日('霜降月第一日', [造单(1), 造单(2)], {},
  [造报('甲', '清剿三号污染区时被精神体撕开防线'), 造报('乙', '   ')]);
L.处理登场(今7, 'C', 线性同余(2));
等于(今7.申请列表.甲.战损来源, '清剿三号污染区时被精神体撕开防线', 'AI 写了就用 AI 的');
等于(今7.申请列表.乙.战损来源, '清剿三号污染区时被精神体撕开防线', '★ 纯空格算没写, 回落单子里的 (它是 truthy, 先 trim 再判空)');

console.log('--- 处理登场: 单子用完了就现掷, 等级仍走诊所等级的闸门 ---');
const 今8 = 造今日('霜降月第一日', [], {}, [造报('丙'), 造报('丁')]);
L.处理登场(今8, 'C', 线性同余(7));
断言(!!今8.申请列表.丙 && !!今8.申请列表.丁, '★ 报到比单子多时, 后面的人照样收得下, 不抛异常');
// C 级诊所的可来等级是 ['D','C','B'] —— 见 闸门.ts 的 可来等级
断言(['D', 'C', 'B'].includes(今8.申请列表.丙.等级), `现掷的等级在 C 级诊所的池子里 (实得 ${今8.申请列表.丙.等级})`);
断言(今8.申请列表.丙.污染度 > 0 && !!今8.申请列表.丙.地域 && !!今8.申请列表.丙.精神体.纲,
  '现掷的是一条完整档案, 不是空壳');
// 比对象身份, 不比数值 —— 数值撞车是可能的, 对象身份不会。
// 这一条抓的是「现掷写成了循环外算一次」: 那样丙丁会是同一个对象, 改一个动两个。
断言(今8.申请列表.丙 !== 今8.申请列表.丁, '★ 两个人各自现掷了一次, 不是同一个对象抄了两遍');

console.log('--- 处理登场: 自创 不吃单子 ---');
const 今9 = 造今日('霜降月第一日', [造单(1), 造单(2)], {}, [造报('路人', '', true)]);
等于(L.处理登场(今9, 'C', 线性同余(3)), ['路人'], '自创的人也收');
等于(今9.待登记.length, 2, '★ 自创不消耗单子, 两张都还在');
断言(今9.申请列表.路人.污染度 !== 1 && 今9.申请列表.路人.污染度 !== 2, '自创的人用的是现掷的数值, 不是单子上的');

console.log('--- 处理登场: 空姓名跳过, 重名不覆盖也不消耗单子 ---');
const 今10 = 造今日('霜降月第一日', [造单(1), 造单(2)], { 甲: { 状态: '待接', 污染度: 99 } },
  [造报(''), 造报('  '), 造报('甲'), 造报('乙')]);
等于(L.处理登场(今10, 'C', 线性同余(4)), ['乙'], '★ 空姓名跳过; 甲 已存在 → 跳过');
等于(今10.申请列表.甲.污染度, 99, '★ 已有的档案没被覆盖 (甲 还是 99, 不是单子上的 1 或 2)');
等于(今10.申请列表.乙.污染度, 1, '★ 甲 没消耗单子 —— 乙 拿到的是第一张 (1), 不是第二张 (2)');
等于(今10.待登记.length, 1, '乙 吃掉一张, 剩一张');

console.log('--- 处理登场: 姓名前后空格被 trim 掉 ---');
const 今11 = 造今日('霜降月第一日', [造单(1)], {}, [造报('  沈砚  ')]);
等于(L.处理登场(今11, 'C', 线性同余(5)), ['沈砚'], '★ key 是 trim 过的');
等于(Object.keys(今11.申请列表), ['沈砚'], '★ 申请列表里只有 「沈砚」一个键, 没有 「  沈砚  」');

console.log('--- 处理登场: 只写 今日, 不碰 哨兵 ---');
const 今12 = 造今日('霜降月第一日', [造单(1)], {}, [造报('甲')]);
今12.哨兵 = { 甲: { 状态: '在诊', 污染度: 88 } };
L.处理登场(今12, 'C', 线性同余(6));
等于(今12.哨兵.甲.污染度, 88, '★ 哨兵 档案一动不动 —— 在诊 之后的事归子项目乙');

console.log('--- 自创 字段整个缺失时当 false (不写等于用最上面那张) ---');
const 今13 = 造今日('霜降月第一日', [造单(1)], {}, [{ 姓名: '甲' }]);
等于(L.处理登场(今13, 'C', 线性同余(8)), ['甲'], '缺 自创 的人也收得下');
等于(今13.待登记.length, 0, '★ 缺 自创 当作 false → 照常占用单子');
等于(今13.申请列表.甲.污染度, 1, '用的是单子上的数值');

console.log('--- 跑一次 同一天: 兼容回路与新路一起走 ---');
const 今14 = 造今日('霜降月第一日', [造条('陆时'), 造单(1)], {}, [造报('甲')]);
const 果14 = L.跑一次(今14, '霜降月第一日', 'C', 线性同余(9));
等于(果14.掷了, false, '日期没变 → 没掷');
等于(果14.晋级, ['陆时'], '老路: AI 回填姓名的那个被晋级了');
等于(果14.登场, ['甲'], '新路: 报到的那个被收了');
等于(Object.keys(今14.申请列表).sort(), ['甲', '陆时'].sort(), '两条路的结果都在申请列表里');
等于(今14.申请列表.甲.污染度, 1, '新路吃的是剩下的那张单子 (老路已经把有名字的那张摘走了)');

console.log('--- 跑一次 跨天: 登场 一并清空 ---');
const 今15 = 造今日('霜降月第一日', [造单(1)], {}, [造报('甲')]);
const 果15 = L.跑一次(今15, '霜降月第二日', 'C', 线性同余(10));
等于(果15.掷了, true, '日期变了 → 重掷');
等于(果15.登场, [], '新的一天没有 登场');
等于(今15.登场, [], '★ 昨天残留的报到被清掉了, 不算在今天头上');
等于(Object.keys(今15.申请列表), [], '申请列表 也清空了');

console.log('--- 跑一次 幂等: 连跑 20 次, 登场 不会被重复处理 ---');
const 今16 = 造今日('霜降月第一日', [造单(1), 造单(2), 造单(3)], {}, [造报('甲'), 造报('乙')]);
for (let i = 0; i < 20; i++) L.跑一次(今16, '霜降月第一日', 'C', 线性同余(20 + i));
等于(Object.keys(今16.申请列表).sort(), ['甲', '乙'].sort(), '★ 20 次之后申请列表里还是只有这两个人');
等于(今16.待登记.length, 1, '★ 只吃掉两张单子, 没有被反复消耗');
等于(今16.登场, [], '登场 停在空数组上');

console.log('--- 兼容回路 撞名: 丢掉那张单子, 不是留回去 ---');
const 今17 = 造今日('霜降月第一日', [造条('沈砚'), 造条('')], { 沈砚: { 状态: '已接', 污染度: 77 } });
等于(L.晋级已命名的(今17), [], '★ 同名的不再晋级');
等于(今17.申请列表.沈砚.污染度, 77, '已有的档案没被覆盖');
等于(今17.待登记.length, 1, '★ 同名的那张单子被丢掉了 —— 留回去的话 待登记 永远不会归零, 界面上「还有 N 个人没露面」会一直挂着');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
