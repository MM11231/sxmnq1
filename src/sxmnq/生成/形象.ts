export function 人物随机(种子: string): () => number {
  let n = 2166136261;
  for (const c of 种子) n = Math.imul(n ^ c.charCodeAt(0), 16777619);
  return () => { n += 0x6D2B79F5; let t = n; t = Math.imul(t ^ t >>> 15, t | 1); t ^= t + Math.imul(t ^ t >>> 7, t | 61); return ((t ^ t >>> 14) >>> 0) / 4294967296; };
}

export function 地域名称(地域: string) { return 地域.split(/[(:：（]/)[0].trim(); }

export function 创建形象(姓名: string, 人: { 地域: string; 特征: string[] }, 新人物 = false): 人物形象 {
  const 随机 = 人物随机(姓名 + '|' + 地域名称(人.地域) + '|' + 人.特征.join('|'));
  const 抽 = <T,>(池: readonly T[]): T => 池[Math.floor(随机() * 池.length)];
  const 偏好 = 地域偏好[地域名称(人.地域)];
  const 肤色 = 抽(偏好 && 随机() < .7 ? 偏好.肤色 : 外貌池.肤色);
  const 发色 = 抽(偏好 && 随机() < .7 ? 偏好.发色 : 外貌池.发色);
  const 发型 = 抽(外貌池.发型), 基础瞳色 = 抽(外貌池.瞳色), 体态 = 抽(外貌池.体态);
  const 瞳色 = 人.特征.includes('异色瞳') ? `左眼${基础瞳色}、右眼${抽(外貌池.瞳色.filter(c => c !== 基础瞳色))}` : 基础瞳色;
  // 旧角色只有已记录亚人特征才展开亚种，避免升级后突然改变族型。
  const 亚种概率 = /极北|极西/.test(人.地域) ? .4 : .25;
  const 有亚种 = 人.特征.some(t => /亚人|兽耳|兽尾/.test(t)) || (新人物 && 随机() < 亚种概率);
  const 亚种 = 有亚种 ? 抽(亚种池) : undefined;
  const 辨识特征 = 人.特征.filter(t => !/亚人|兽耳|兽尾|机油|硝烟/.test(t)).map(t => {
    if (t === '眼镜(金丝/黑框/半框/圆框)') return 抽(['金丝眼镜', '黑框眼镜', '半框眼镜', '圆框眼镜']);
    if (t.includes('/')) return 抽(t.replace(/[()（）]/g, '').split('/'));
    return t;
  });
  const 自带气息 = 辨识特征.some(t => /香|味/.test(t));
  return { 版本: 1, 肤色, 发色, 发型, 瞳色, 体态, 亚种: 亚种?.名称 ?? '人类', 亚种特征: 亚种 ? 抽(亚种.特征) : '', 辨识特征,
    气息: !自带气息 && 随机() < .3 ? 抽(外貌池.气息) : '', 相处细节: 抽(亚种 ? 亚种日常[亚种.名称] : 日常池) };
}

export function 外貌描述(形象: 人物形象): string {
  const 眼睛 = 形象.辨识特征.includes('异色瞳') ? 形象.瞳色 : `瞳色${形象.瞳色}`;
  return `${形象.体态}，肤色${形象.肤色}。${形象.发色}色${形象.发型}，${眼睛}。${形象.亚种特征 ? 形象.亚种特征 + '。' : ''}${形象.气息 ? '身上有' + 形象.气息 + '。' : ''}`;
}

export function 读取形象(姓名: string, 人: { 地域: string; 特征: string[]; 形象?: 人物形象 }) {
  return 人.形象 ?? 创建形象(姓名, 人);
}
