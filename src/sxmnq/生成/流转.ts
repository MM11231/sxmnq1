/**
 * 流转 —— 掷完的人怎么变成正式的申请者。
 *
 *   待登记[i]   ← 前端掷 (生成.ts)。有数值, 没名字, 界面上显示「未登记 · 01」
 *       │
 *       │  AI 写 姓名 + 战损来源  (spec §8.2: 名字归 AI, 因为它有审美)
 *       ▼
 *   申请列表[姓名]  ← 玩家点接诊
 *       │
 *       ▼
 *   哨兵[姓名]      ← 在诊(占床) → 已出院 / 已收编
 *
 * **这个文件里最要紧的一个词是「幂等」。**
 * 状态栏 iframe 每次渲染消息都会重建, 跑一次() 会被调用很多次。
 * 唯一挡住重复掷骰的是 今日.已生成于 这个日期戳 —— 见 spec §8.4。
 *
 * 与 spec §8.5 的一处偏离 (AI 只写两个字段, 晋级由前端干) 记在实施计划里。
 */
import type { 等级 } from '../等级';
import { 掷一批, type 待登记条目, type 精神体掷定值 } from './生成';
import type { 随机源 } from './掷骰';

/** 进了申请列表的哨兵。少了 字数/中式 (那是给 AI 下命名指令用的), 多了 状态 */
export interface 申请条目 {
  等级: 等级;
  污染度: number;
  诊金: number;
  年龄: number;
  地域: string;
  精神体: 精神体掷定值;
  特征: string[];
  A面: string;
  B面: string;
  战损来源: string;
  状态: string;
}

export interface 今日数据 {
  已生成于: string;
  待登记: 待登记条目[];
  申请列表: Record<string, 申请条目>;
}

export interface 流转结果 {
  掷了: boolean;
  新掷: number;
  晋级: string[];
}

/**
 * 今天掷过没有。**`当前日期` 为空时一律返回 false。**
 *
 * 那个空判断是必须的: 存档刚开、AI 还没写第一句话的时候 世界.日期 是空串,
 * 而 已生成于 的初始值也是空串 —— 不挡住的话, 开局第一帧就会掷一批,
 * 抢在 AI 写日期之前。等到 AI 真写了日期, 戳对不上, 又掷一批。
 * 玩家会在还没开张的诊所里看到两批病人。
 */
export function 该掷了吗(已生成于: string, 当前日期: string): boolean {
  return 当前日期 !== '' && 已生成于 !== 当前日期;
}

/**
 * 把已经有名字的从 待登记 摘进 申请列表。**就地改 今日。**
 *
 * 没有名字的原地留下 —— 不需要逐个匹配, AI 写在哪个槽里就是哪个 (spec §8.5)。
 */
export function 晋级已命名的(今日: 今日数据): string[] {
  const 晋级: string[] = [];
  const 留下: 待登记条目[] = [];

  for (const 条 of 今日.待登记) {
    const 名 = (条.姓名 ?? '').trim();
    if (!名) {
      留下.push(条);
      continue;
    }
    // 逐字段搬, 不用展开语法 —— 这样 字数/中式 与 姓名 自然就被挡在外面,
    // 且以后 待登记条目 加字段时这里会**编译不过**, 而不是静默漏掉。
    今日.申请列表[名] = {
      等级: 条.等级,
      污染度: 条.污染度,
      诊金: 条.诊金,
      年龄: 条.年龄,
      地域: 条.地域,
      精神体: 条.精神体,
      特征: 条.特征,
      A面: 条.A面,
      B面: 条.B面,
      战损来源: 条.战损来源,
      状态: '待接',
    };
    晋级.push(名);
  }

  今日.待登记 = 留下;
  return 晋级;
}

/**
 * 状态栏挂载时、以及 世界.日期 一变时调这个。**就地改 今日。**
 *
 * 顺序很要紧: **先看日期戳, 再谈晋级。**
 * 反过来的话, 昨天掷的、AI 忘了命名的那些人会被晋级进今天的申请列表 ——
 * 而今天的名单已经换了一批人了。
 */
export function 跑一次(
  今日: 今日数据,
  当前日期: string,
  诊所等级: 等级,
  随机: 随机源 = Math.random,
): 流转结果 {
  if (该掷了吗(今日.已生成于, 当前日期)) {
    const 新 = 掷一批(诊所等级, 随机);
    今日.待登记 = 新;
    // 昨天的申请单一并作废: 新的一天, 新的病人 (spec §9 从 AI 手上收回来的那件事)
    今日.申请列表 = {};
    今日.已生成于 = 当前日期;
    return { 掷了: true, 新掷: 新.length, 晋级: [] };
  }

  return { 掷了: false, 新掷: 0, 晋级: 晋级已命名的(今日) };
}
