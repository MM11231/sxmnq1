/**
 * 流转 —— 掷完的人怎么变成正式的申请者。
 *
 * 有**两条路**通向 申请列表, 现在同时活着:
 *
 *   ① 新路 (主路) —— AI 报到
 *        待登记[i]   ← 前端掷 (生成.ts)。有数值, 没名字, 界面上显示「未到 · 01」
 *            │
 *            │  AI 让某人推门进来, 往 今日.登场 **追加**一条 { 姓名, 战损来源 }
 *            ▼
 *        处理登场() 按 FIFO 取最上面那张单子配给他
 *            │
 *            ▼
 *        申请列表[姓名]
 *
 *   ② 老路 (兼容回路) —— AI 回填 待登记[i].姓名
 *        晋级已命名的() 把有名字的摘出来。
 *        **为什么不删**: 世界书是分发出去、各自一份的。玩家更新世界书之前,
 *        AI 仍然会照老规矩回填姓名 —— 留着这条路, 那些安装照样能出病人。
 *
 * 为什么要换动作类型: 回填数组索引是**簿记**, 追加一条记录是**叙事**。
 * 实测 AI 同一份 <UpdateVariable> 里正确 append 了 世界.近期事件, 却一条都没碰
 * 待登记 —— 它做叙事, 不做簿记。详见 spec 2026-10-06-病人入口 §1.3。
 *
 *   申请列表[姓名]  ← 玩家点接诊
 *       │
 *       ▼
 *   哨兵[姓名]      ← 在诊(占床) → 已出院 / 已收编
 *
 * **这个文件里最要紧的一个词是「幂等」。**
 * 状态栏 iframe 每次渲染消息都会重建, 跑一次() 会被调用很多次。
 * 唯一挡住重复掷骰的是 今日.已生成于 这个日期戳 —— 见 spec §8.4。
 * 登场 靠「处理完就清空」达到同样的幂等 —— 见本篇的测试。
 *
 * 与 spec §8.5 的一处偏离 (AI 只写两个字段, 晋级由前端干) 记在实施计划里。
 */
import type { 等级 } from '../等级';
import { 掷一个, 掷一批, type 待登记条目, type 精神体掷定值 } from './生成';
import type { 随机源 } from './掷骰';

/** 进了申请列表的哨兵。少了 字数/中式 (那是给 AI 下命名指令用的), 多了 状态 */
export interface 申请条目 {
  等级: 等级;
  污染度: number;
  诊金: number;
  年龄: number;
  地域: string;
  精神体: 精神体掷定值;
  特征: string[];
  A面: string;
  B面: string;
  战损来源: string;
  状态: string;
}

export interface 登场条目 {
  姓名: string;
  战损来源: string;
  /** 罕见: 这一楼的人明确不是申请单上的。缺省 false = 占用最上面那张单子 */
  自创: boolean;
}

export interface 今日数据 {
  已生成于: string;
  待登记: 待登记条目[];
  登场: 登场条目[];
  申请列表: Record<string, 申请条目>;
}

export interface 流转结果 {
  掷了: boolean;
  新掷: number;
  /** 兼容回路收的 (§6.2) */
  晋级: string[];
  /** 新路收的 */
  登场: string[];
}

/**
 * 今天掷过没有。**`当前日期` 为空时一律返回 false。**
 *
 * 那个空判断是必须的: 存档刚开、AI 还没写第一句话的时候 世界.日期 是空串,
 * 而 已生成于 的初始值也是空串 —— 不挡住的话, 开局第一帧就会掷一批,
 * 抢在 AI 写日期之前。等到 AI 真写了日期, 戳对不上, 又掷一批。
 * 玩家会在还没开张的诊所里看到两批病人。
 */
export function 该掷了吗(已生成于: string, 当前日期: string): boolean {
  return 当前日期 !== '' && 已生成于 !== 当前日期;
}

/**
 * 把已经有名字的从 待登记 摘进 申请列表。**就地改 今日。**
 *
 * 没有名字的原地留下 —— 不需要逐个匹配, AI 写在哪个槽里就是哪个 (spec §8.5)。
 */
/**
 * 待登记条目 → 申请条目。
 *
 * **逐字段搬, 不用展开语法** —— 这样 字数/中式/姓名 自然被挡在外面,
 * 且以后 待登记条目 加字段时这里会**编译不过**, 而不是静默漏掉。
 */
function 转申请(条: 待登记条目, 战损来源: string): 申请条目 {
  return {
    等级: 条.等级,
    污染度: 条.污染度,
    诊金: 条.诊金,
    年龄: 条.年龄,
    地域: 条.地域,
    精神体: 条.精神体,
    特征: 条.特征,
    A面: 条.A面,
    B面: 条.B面,
    战损来源,
    状态: '待接',
  };
}

export function 晋级已命名的(今日: 今日数据): string[] {
  const 晋级: string[] = [];
  const 留下: 待登记条目[] = [];

  for (const 条 of 今日.待登记) {
    const 名 = (条.姓名 ?? '').trim();
    if (!名) {
      留下.push(条);
      continue;
    }
    // 同名已经在申请列表里 → **丢掉**这张单子, 而不是留回去。
    // 同名说明 AI 把一个人写了两遍, 没有第二个人在等它;
    // 留回去的话 待登记 永远不会归零, 界面上「还有 N 个人没露面」会一直挂着。
    //
    // ⚠ 这与 处理登场 的重名处理**故意相反** —— 那边撞名要**留着**单子,
    //   因为在那条路上单子是一张还没人用的卡。别把两处抄成一样。
    if (今日.申请列表[名]) {
      console.warn(`[流转] 待登记 里的「${名}」已在申请列表里, 丢掉这张单子`);
      continue;
    }
    今日.申请列表[名] = 转申请(条, 条.战损来源);
    晋级.push(名);
  }

  今日.待登记 = 留下;
  return 晋级;
}

/**
 * 把 AI 报到的人配进 申请列表。**就地改 今日**, 返回收了谁。
 *
 * 配对是 **FIFO**（spec §4.1）: 取 待登记 最上面那张, 用它的掷定值。
 * 单子用完了、或者这条标了 自创, 就现掷一个 —— 等级仍然走诊所等级的闸门,
 * 不会凭空冒出高级哨兵。
 *
 * **重名一律跳过, 而且不动 待登记** —— 那张单子是一张还没人用的卡,
 * 该留给下一个真进来的人。与 晋级已命名的 的处理**故意相反** (见那边的注释)。
 *
 * 幂等靠「处理完清空 登场」, 不靠日期戳。
 */
export function 处理登场(
  今日: 今日数据,
  诊所等级: 等级,
  随机: 随机源 = Math.random,
): string[] {
  const 收了: string[] = [];

  for (const 报 of 今日.登场) {
    const 名 = (报.姓名 ?? '').trim();
    if (!名) continue; // AI 写半截是常态, 不当成错误

    if (今日.申请列表[名]) {
      console.warn(`[流转] 登场 里的「${名}」已在申请列表里, 跳过 (不消耗申请单)`);
      continue;
    }

    // 自创 (或单子用完了) → 现掷
    const 单 = 报.自创 === true ? undefined : 今日.待登记.shift();
    const 底 = 单 ?? 掷一个(诊所等级, 随机);
    // AI 写的战损来源优先, 但**先 trim 再判空** —— 纯空格是 truthy,
    // 不 trim 的话 `||` 兜底会失效, 病人的战损来源会变成一个空格。
    const 战损 = (报.战损来源 ?? '').trim() || 底.战损来源;

    今日.申请列表[名] = 转申请(底, 战损);
    收了.push(名);
  }

  今日.登场 = [];
  return 收了;
}

/**
 * 状态栏挂载时、以及 世界.日期 一变时调这个。**就地改 今日。**
 *
 * 顺序很要紧: **先看日期戳, 再谈晋级。**
 * 反过来的话, 昨天掷的、AI 忘了命名的那些人会被晋级进今天的申请列表 ——
 * 而今天的名单已经换了一批人了。
 */
export function 跑一次(
  今日: 今日数据,
  当前日期: string,
  诊所等级: 等级,
  随机: 随机源 = Math.random,
): 流转结果 {
  if (该掷了吗(今日.已生成于, 当前日期)) {
    const 新 = 掷一批(诊所等级, 随机);
    今日.待登记 = 新;
    // 昨天的申请单一并作废: 新的一天, 新的病人 (spec §9 从 AI 手上收回来的那件事)
    今日.申请列表 = {};
    // 昨天残留的报到同样不算数 —— 不挡的话, 新的一天会用今天的单子
    // 去配昨天那个人, 而今天的名单已经换了一批。
    今日.登场 = [];
    今日.已生成于 = 当前日期;
    return { 掷了: true, 新掷: 新.length, 晋级: [], 登场: [] };
  }

  // **顺序要紧: 先兼容回路, 后新路。**
  // 先老后新时, 处理登场 看到的 待登记 已经是 晋级已命名的 清理过的残表,
  // shift() 拿到的必然还没被用过 —— 顺手省掉一类重叠 bug。
  // 反过来也不错, 但过渡期 AI 两套都写时, 新路的 FIFO 可能撞上老路刚摘走的那张。
  const 晋级 = 晋级已命名的(今日);
  const 登场 = 处理登场(今日, 诊所等级, 随机);
  return { 掷了: false, 新掷: 0, 晋级, 登场 };
}
