/** 名单显示前由程序起名；姓名是档案键，绝不通过重名兜底覆盖已有角色。 */
import { 名用字池, 中式双字名池, 西式姓名池, 姓氏池, 战损任务池, 战损地点池, 战损后果池 } from './池子';
import { 均匀抽, type 命名要求, type 随机源 } from './掷骰';

export const 重掷上限 = 20;

/** 原白塔：2～4 字，四字强制西式；已有档案姓名不经过生成器。 */
const 字数归一 = (字数: number): number => 字数 <= 2 ? 2 : 字数 >= 4 ? 4 : 3;
// 原文强调姓名连起来不能成为熟悉物件词；同时排除明显的日常指令或句子。
const 熟词 = new Set('铁砂 铸铁 马网 白纸 白布 白沙 白石 白陶 石桥 石板 石桌 石凳 石灰 石岩 石砂 石棉 石门 田园 田地 林木 林园 周末 关门 开门 房门 房屋 房间 车门 车灯 车轮 车行 车桥 车帆 米饭 米粉 米粒 米线 米纸 米果 布衣 布帆 木舟 不可 不行 不走 不来 不去 不留 不住 不等 不看 不听 不问 不说 不读 不写 不收 不放 不开 不关 不过 不如 不也 不亦 不以 不且 不又 不于 不之 如何 易于 易如 易以 易可 甘于 安可 何去 孔洞 包纸 包布 包饭 包住 包收 包退 方可 方尺 方桌 方舟 方石 方岩 方桥 应当 应可 应如 应于 应以 时常 时过 时至 章回 文具 文章 文册 叶片 余页 余册 常来 常去 常住 常看 常听 常说 常读 常写 常开 常关 常行 古今 古桥 古舟 古册 古陶 古屋 古纸 古杉 温和 温补 成果 成册 成行 成岩 连纸 连页 连读 左岸 左页 左行 左回 夏至 夏日 童话 陶泥 陶杯 陶碗 陶盘 陶灯 汤碗 汤杯 井水 井口 井泥 池水 池泥 路灯 路桥 路过 路口 井田'.split(' '));
const 中式候选 = (字数: number): string[] => 姓氏池.flatMap(姓 =>
  (字数 === 2 ? 名用字池 : 中式双字名池)
    .filter(名 => !名.includes(姓) && !熟词.has(姓 + 名) && !(姓 === '不' && 字数 === 3))
    .map(名 => 姓 + 名),
);
const 中文池: Readonly<Record<number, readonly string[]>> = { 2: 中式候选(2), 3: 中式候选(3) };
function 候选池(要求: 命名要求): readonly string[] {
  return (要求.中式 && 要求.字数 < 4 ? 中文池 : 西式姓名池)[字数归一(要求.字数)];
}

/** 第一候选，仅用于展示/测试；正式起名必须查重。 */
export function 兜底名(要求: 命名要求): string {
  return 候选池(要求)[0];
}

export function 起一个名(要求: 命名要求, 避开: ReadonlySet<string>, 随机: 随机源 = Math.random): string {
  const 池 = 候选池(要求);
  for (let i = 0; i < 重掷上限; i++) {
    const 名 = 均匀抽(池, 随机);
    if (!避开.has(名)) return 名;
  }
  // 连续撞名后依次查找空闲姓名。某个短名池用完，借用其他池，仍然保持原卡允许的两到四字。
  for (const 备用 of [池, 中文池[2], 中文池[3], 西式姓名池[2], 西式姓名池[3], 西式姓名池[4]]) {
    const 名 = 备用.find(候选 => !避开.has(候选));
    if (名) return 名;
  }
  throw new Error('姓名池已用尽，未创建新哨兵；已有档案保持不变。');
}

/**
 * 战损来源。三段拼: 任务 + 地点 + 后果。
 *
 * 它比姓名弱一档 —— 战损来源本来就是叙事描写, 模板拼出来的会比 AI 写的板。
 * 同样是明确接受的代价: 宁可板, 也不要一个需要 AI 配合才成立的入口。
 * 以后想加花, 改 池子.ts 里的字就行。
 */
export function 起一个战损(随机: 随机源 = Math.random): string {
  return 均匀抽(战损任务池, 随机) + 均匀抽(战损地点池, 随机) + 均匀抽(战损后果池, 随机);
}
