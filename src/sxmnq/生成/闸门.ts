/**
 * 闸门 —— 谁会来这家诊所。
 *
 * **闸门管的是概率分布, 不是准入名单**（spec §4 开头那句）。
 * D 级诊所不是「不让 B 级病人进门」, 是「B 级病人压根不会听说你」。
 *
 * 与 掷骰.ts 的分界: 掷骰掷的是「这个人长什么样」, 跟玩家无关;
 * 这里掷的每一项都取决于**玩家诊所的等级**。所以掷骰不认识等级, 这里认识。
 */
import { 等级序, 等级值, type 等级 } from '../等级';
import { 加权抽, 掷区间, type 随机源 } from './掷骰';

/** 能收到的哨兵等级: 从 D 起, 到诊所等级 +1 止。低等级永远能来, 每升一档解锁高它一档的客人 */
export function 可来等级(诊所等级: 等级): 等级[] {
  return 等级序.slice(0, Math.min(等级值[诊所等级] + 2, 等级序.length));
}

/**
 * 权重: 本档 3, 每低一档 −1, 下限 1; 高一档恒为 1。
 *
 * 读法 —— **多数是同级的, 其次是低一级的, 高一级的是稀客。**
 * 低档从 3 递减到 1 就停住 (不再继续降), 否则 S 级诊所的池子里
 * D 级客人的权重会变成 −1, 加权抽直接崩。
 */
export function 闸门权重(诊所等级: 等级, 目标: 等级): number {
  const 差 = 等级值[诊所等级] - 等级值[目标];
  if (差 < 0) return 1; // 高一级的稀客
  return Math.max(1, 3 - 差);
}

export function 掷等级(诊所等级: 等级, 随机: 随机源 = Math.random): 等级 {
  const 池: Record<string, number> = {};
  for (const 目标 of 可来等级(诊所等级)) 池[目标] = 闸门权重(诊所等级, 目标);
  return 加权抽(池, 随机) as 等级;
}

/**
 * 污染度区间 —— **难度差异的真正来源**。
 *
 * spec §3.4 把等级差锁死在 [−1, +1] 之后, 等级本身已经带不来多少难度变化了;
 * 同一个 D 级病人可以污染 20 也可以是 45, 那才是这一单要跑几趟的原因。
 */
export const 污染度区间: Record<等级, [number, number]> = {
  D: [20, 45],
  C: [35, 65],
  B: [55, 85],
  A: [70, 95],
  S: [85, 100],
};

export function 掷污染度(等级: 等级, 随机: 随机源 = Math.random): number {
  const [低, 高] = 污染度区间[等级];
  return 掷区间(低, 高, 随机);
}

/** 基础诊金 —— 病人卡上显示的就是它。结算时才乘评级系数 */
export function 算基础诊金(等级: 等级, 污染度: number): number {
  return (等级值[等级] + 1) * 40 + 污染度 * 2;
}

/**
 * 实际诊金 = 基础 × 评级系数。
 *
 * 单独一个函数而不是写在结算里, 是为了让「系数不该出现在 申请列表 上」
 * 这件事有个明确的位置可指 —— 定价发生在接诊之前, 系数在接诊之后才知道。
 */
export function 算实际诊金(基础诊金: number, 评级系数: number): number {
  return Math.round(基础诊金 * 评级系数);
}
