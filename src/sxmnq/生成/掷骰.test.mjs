// 直接跑: node src/sxmnq/生成/掷骰.test.mjs
import '../测试钩子.mjs';

const D = await import(new URL('./掷骰.ts', import.meta.url).href);
const P = await import(new URL('./池子.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};
const 近似 = (实得, 期望, 说明) => 断言(Math.abs(实得 - 期望) < 1e-9, `${说明} (${实得} ≈ ${期望})`);

/** 按顺序吐出给定的数, 用完循环 —— 让「掷骰」变成可复现的查表 */
const 序列 = (...值们) => {
  let i = 0;
  return () => 值们[i++ % 值们.length];
};
/** 测试属性用的确定性伪随机, 免得依赖 Math.random 导致偶发红 */
const 线性同余 = (种子) => {
  let s = 种子 >>> 0;
  return () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 4294967296);
};

console.log('--- 加权抽: 落在哪一段由 r 决定 ---');
// 池 {A:3, B:1} 总权重 4。r = 随机() * 4
等于(D.加权抽({ A: 3, B: 1 }, 序列(0)), 'A', 'r=0 → 第一档');
等于(D.加权抽({ A: 3, B: 1 }, 序列(0.5)), 'A', 'r=2 → 还在 A 段 (0~3)');
等于(D.加权抽({ A: 3, B: 1 }, 序列(0.8)), 'B', 'r=3.2 → 落到 B 段 (3~4)');
等于(D.加权抽({ A: 3, B: 1 }, 序列(0.999999)), 'B', 'r 逼近 4 → 仍是 B');
等于(D.加权抽({ 只有: 1 }, 序列(0.5)), '只有', '只有一个键时永远返回它');

console.log('--- 均匀抽: 等概率取表里一个 ---');
const 三件 = ['甲', '乙', '丙'];
等于(D.均匀抽(三件, 序列(0)), '甲', 'r=0 → 第一个');
等于(D.均匀抽(三件, 序列(0.5)), '乙', 'r=0.5 → 第二个');
等于(D.均匀抽(三件, 序列(0.99)), '丙', 'r=0.99 → 第三个');

console.log('--- 掷区间: 闭区间, 两端都取得到 ---');
等于(D.掷区间(20, 45, 序列(0)), 20, '下限取得到');
等于(D.掷区间(20, 45, 序列(0.999999)), 45, '上限取得到');
断言(
  Array.from({ length: 200 }, (_, i) => D.掷区间(20, 45, 线性同余(i + 1))).every(v => v >= 20 && v <= 45),
  '200 次都在 [20, 45] 里',
);

console.log('--- 算纲池: 地域系数是乘上去的 ---');
// 极西狂沙: 鱼类及水生生物 0.08, 两栖纲 0.15, 爬行纲 1.4
const 沙 = D.算纲池(P.地域池[3]);
近似(沙.爬行纲, 14 * 1.4, '极西狂沙 爬行纲 = 14 × 1.4');
近似(沙.鱼类及水生生物, 12 * 0.08, '极西狂沙 鱼类 = 12 × 0.08');
近似(沙.哺乳纲, 30, '没被地域改写的纲原样保留');
const 北 = D.算纲池(P.地域池[0]);
近似(北.哺乳纲, 30 * 1.3, '极北凛冬 哺乳纲 = 30 × 1.3');
近似(北.鱼类及水生生物, 12 * 0.15, '极北凛冬 鱼类 = 12 × 0.15');

console.log('--- 掷精神体: 四属性必须跟着纲走 ---');
// 随机恒为 0 → 每次都取该权重表的第一个键
const 精 = D.掷精神体(P.地域池[0], 序列(0));
等于(精.纲, '哺乳纲', 'r=0 时取纲池第一个键');
等于(精.方向, P.纲方向.哺乳纲, '方向 取自 纲方向[纲]');
等于(精.栖息, '陆行', '栖息 取自 栖息权重[纲] 的第一项');
等于(精.体型, '微小(可栖肩头)', '体型 取自 体型权重[纲] 的第一项');
等于(精.危险, '毒性', '危险 取自 危险权重[纲] 的第一项');

// 换个地域、换个数, 抽到的纲与四属性必须仍然自洽
for (const [地, r] of [[P.地域池[3], 0.55], [P.地域池[1], 0.3], [P.地域池[2], 0.75]]) {
  const 精2 = D.掷精神体(地, 序列(r, 0.4));
  断言(
    !!P.纲方向[精2.纲] && 精2.方向 === P.纲方向[精2.纲],
    `${地.slice(0, 4)} r=${r} → ${精2.纲}, 方向对得上`,
  );
  断言(
    !!P.栖息权重[精2.纲][精2.栖息] &&
      !!P.体型权重[精2.纲][精2.体型] &&
      !!P.危险权重[精2.纲][精2.危险],
    `${精2.纲} → 栖息/体型/危险 都是该纲那一行的键 (${精2.栖息} / ${精2.体型} / ${精2.危险})`,
  );
}

console.log('--- 掷个人特征: 1~2 个, 且来自不同的池 ---');
for (let 种子 = 1; 种子 <= 300; 种子++) {
  const 特征 = D.掷个人特征(线性同余(种子));
  if (特征.length < 1 || 特征.length > 2) {
    断言(false, `种子 ${种子}: 特征个数 ${特征.length} 不在 1~2`);
    break;
  }
  const 所属池 = 特征.map(t =>
    Object.entries(P.个人特征池).filter(([, 池]) => 池.includes(t)).map(([名]) => 名),
  );
  if (所属池.some(池们 => 池们.length !== 1)) {
    断言(false, `种子 ${种子}: 特征 ${JSON.stringify(特征)} 不是恰好属于一个池`);
    break;
  }
  if (所属池.length === 2 && 所属池[0][0] === 所属池[1][0]) {
    断言(false, `种子 ${种子}: 两个特征都来自「${所属池[0][0]}」池`);
    break;
  }
}
断言(true, '300 个种子: 个数 1~2、每个特征唯一归属、两个特征不同池');

console.log('--- 掷性格: A/B 面各一个, 都在表里 ---');
const 性 = D.掷性格(线性同余(7));
断言(P.性格A面.includes(性.A面), `A面「${性.A面}」在表里`);
断言(P.性格B面.includes(性.B面), `B面「${性.B面}」在表里`);
const 性2 = D.掷性格(线性同余(8));
断言(
  P.性格A面.includes(性2.A面) && P.性格B面.includes(性2.B面),
  '换个种子同样成立',
);

console.log('--- 掷年龄: 18~35 闭区间 ---');
等于(D.掷年龄(序列(0)), 18, '下限 18');
等于(D.掷年龄(序列(0.999999)), 35, '上限 35');
断言(
  Array.from({ length: 300 }, (_, i) => D.掷年龄(线性同余(i + 1))).every(
    a => a >= P.年龄下限 && a <= P.年龄上限 && Number.isInteger(a),
  ),
  '300 次都是 [18, 35] 里的整数',
);

console.log('--- 掷命名要求: 2~4 字; 4 字必西式, 2~3 字才掷中外 ---');
等于(D.掷命名要求(序列(0)), { 字数: 2, 中式: true }, 'r=0 → 2 字, 下一个 r=0 → 中式');
等于(D.掷命名要求(序列(0.5, 0.9)), { 字数: 3, 中式: false }, 'r=0.5 → 3 字, 0.9 → 西式');
等于(D.掷命名要求(序列(0.99)), { 字数: 4, 中式: false }, 'r=0.99 → 4 字, 强制西式');
for (let 种子 = 1; 种子 <= 300; 种子++) {
  const 命 = D.掷命名要求(线性同余(种子));
  if (命.字数 < 2 || 命.字数 > 4) {
    断言(false, `种子 ${种子}: 字数 ${命.字数} 不在 2~4`);
    break;
  }
  if (命.字数 === 4 && 命.中式) {
    断言(false, `种子 ${种子}: 4 字却掷成了中式 —— 白塔原文是强制西式`);
    break;
  }
}
断言(true, '300 个种子: 字数 2~4, 且 4 字从不中式');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
