/**
 * 组装 —— 把 掷骰.ts 掷出来的零件拼成一个「人」。
 *
 * 一个 待登记条目 是**已经掷完、但还没有名字**的哨兵 (spec §8.5 的中间态)。
 * 姓名与战损来源留空, 那是 AI 的活 (§8.2): 名字掷出「大壮」玩家会觉得
 * 角色没有魅力, 而 AI 按命名法则取的名字有审美。
 *
 * **字段顺序刻意与 schema 的 档案形状 一一对应** —— 这里每加一个字段,
 * schema.ts 的 档案形状 也要加, 否则它会被 zod 静默丢掉。
 */
import type { 等级 } from '../等级';
import { 算基础诊金, 掷等级, 掷污染度 } from './闸门';
import {
  掷个人特征, 掷命名要求, 掷地域, 掷年龄, 掷性格, 掷精神体, 掷区间,
  type 随机源,
} from './掷骰';

export interface 精神体掷定值 {
  纲: string;
  方向: string;
  栖息: string;
  体型: string;
  危险: string;
}

export interface 待登记条目 {
  // —— 从 闸门 来, 取决于玩家诊所的等级 ——
  等级: 等级;
  污染度: number;
  诊金: number;
  // —— 从 掷骰 来, 与玩家无关 ——
  年龄: number;
  地域: string;
  精神体: 精神体掷定值;
  特征: string[];
  A面: string;
  B面: string;
  // —— 留给 AI 的两项 ——
  姓名: string;
  战损来源: string;
  // —— 命名要求, 只在这一步有用, 晋级的丢掉 ——
  字数: number;
  中式: boolean;
}

/** 掷一个完整的档案。姓名与战损来源留空, 等 AI 填 */
export function 掷一个(诊所等级: 等级, 随机: 随机源 = Math.random): 待登记条目 {
  const 哨兵等级 = 掷等级(诊所等级, 随机);
  const 污染度 = 掷污染度(哨兵等级, 随机);
  const 地域 = 掷地域(随机);
  const 性格 = 掷性格(随机);
  const 命名 = 掷命名要求(随机);

  return {
    等级: 哨兵等级,
    污染度,
    诊金: 算基础诊金(哨兵等级, 污染度),
    年龄: 掷年龄(随机),
    地域,
    精神体: 掷精神体(地域, 随机),
    特征: 掷个人特征(随机),
    A面: 性格.A面,
    B面: 性格.B面,
    姓名: '',
    战损来源: '',
    字数: 命名.字数,
    中式: 命名.中式,
  };
}

/** 一天来几个人。白塔原文是 3~6 */
export const 每日人数下限 = 3;
export const 每日人数上限 = 6;

export function 掷一批(诊所等级: 等级, 随机: 随机源 = Math.random): 待登记条目[] {
  const 个数 = 掷区间(每日人数下限, 每日人数上限, 随机);
  return Array.from({ length: 个数 }, () => 掷一个(诊所等级, 随机));
}
