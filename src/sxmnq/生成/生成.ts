import { 具体精神体 } from './精神体';
import { 创建形象, type 人物形象 } from './形象';
/**
 * 组装 —— 把 掷骰.ts 掷出来的零件拼成一个人, 并给他起好名字。
 *
 * ★ 2026-10-06「名单直出」: **掷一批() 直接产出最终要写进变量的那个 record。**
 *
 * 改之前这里产的是「掷完、但还没有名字」的中间态 (待登记), 名字等 AI 填。
 * 中间态没有了 —— 因为名字必须在你**看见它的那一刻**就存在, 而 AI 填格子是
 * 实测失败过的动作 (见 姓名.ts 开头)。名字就是 申请列表 的键, 所以
 * 「掷一个人」和「把他放进名单」本来就是一件事; 分两步才需要那个中间态。
 *
 * **字段顺序刻意与 schema 的 档案形状 一一对应** —— 这里每加一个字段,
 * schema.ts 的 档案形状 也要加, 否则它会被 zod 静默丢掉。
 */
import { 等级值, type 等级 } from '../等级';
import { 算基础诊金, 掷等级, 掷污染度 } from './闸门';
import { 起一个名, 起一个战损 } from './姓名';
import {
  掷个人特征, 掷命名要求, 掷地域, 掷年龄, 掷性格, 掷精神体,
  type 随机源,
} from './掷骰';

export interface 精神体掷定值 {
  名称: string;
  纲: string;
  方向: string;
  栖息: string;
  体型: string;
  危险: string;
}

/** 一个申请人。**字段与 schema.ts 的 档案形状 逐字对应。** */
export interface 申请条目 {
  等级: 等级;
  污染度: number;
  诊金: number;
  年龄: number;
  地域: string;
  精神体: 精神体掷定值;
  特征: string[];
  形象?: 人物形象;
  A面: string;
  B面: string;
  战损来源: string;
  状态: string;
}

/**
 * 掷一个人的数值 + 名字。名字会躲开 `避开` 里的每一个。
 *
 * 返回的是 `{ 姓名, 条目 }` 而不是一整条 —— 姓名是 申请列表 的**键**,
 * 不是条目里的字段 (schema 的 档案形状 里也没有它)。
 */
export function 掷一个(
  诊所等级: 等级,
  避开: ReadonlySet<string>,
  随机: 随机源 = Math.random,
): { 姓名: string; 条目: Omit<申请条目, '状态'> } {
  const 哨兵等级 = 掷等级(诊所等级, 随机);
  const 污染度 = 掷污染度(哨兵等级, 随机);
  const 地域 = 掷地域(随机);
  const 性格 = 掷性格(随机);

  const 姓名 = 起一个名(掷命名要求(随机), 避开, 随机);
  const 精神体 = 掷精神体(地域, 随机);
  const 特征 = 掷个人特征(随机);
  return {
    姓名,
    条目: {
      等级: 哨兵等级,
      污染度,
      诊金: 算基础诊金(哨兵等级, 污染度),
      年龄: 掷年龄(随机),
      地域,
      精神体: { ...精神体, 名称: 具体精神体(精神体, 姓名) },
      特征,
      形象: 创建形象(姓名, { 地域, 特征 }, true),
      A面: 性格.A面,
      B面: 性格.B面,
      战损来源: 起一个战损(随机),
    },
  };
}

/**
 * 一天来几个人。**按诊所等级给, 不掷。**
 *
 * 白塔原文是 3~6, 但那份随机数在这里没有意义: 玩家做不了任何事去影响它,
 * 它只让「今天能看几个病人」变得不可预期。改成等级的函数之后**只涨不跌**,
 * 而且跟 算精神力上限 用的是同一张 等级值 表, 两处口径一致。
 *
 * **下限是 2, 不是 0。** 玩家的要求。按 `1 + 等级值` 算, D 档开局一天只来一个人,
 * 玩家点一下就没事干了 —— 而 D 档正是每个存档的第一天。
 *
 * **不用 `诊所.名声` 判**: 名声是**本档之内的进度条** (加名声 攒满 100 就进位
 * 并清零), 拿它判会出现「升档那天人数从 5 掉回 2」—— 玩家刚治好一波病人、
 * 升了档, 门口反而冷清了。
 */
export function 每日人数(等级: 等级): number {
  return 2 + 等级值[等级];
}

/** 每个名额成为「回头客」的概率。见 掷一批。 */
export const 回头客概率 = 0.25;

export interface 掷一批的输入 {
  诊所等级: 等级;
  /** 已在册的哨兵姓名。抽名时避开 —— 顺带用来挑回头客。 */
  已有姓名: readonly string[];
  /** `状态 === '已出院'` 的哨兵姓名。空的就一个回头客都没有。 */
  回头客池: readonly string[];
}

/**
 * 掷今天这一批, **直接产出 申请列表 该有的那个 record**。
 *
 * 姓名就是键, 所以这里同时管两件事: 起名, 以及**不去重名**。
 * 重名不是「多一个人」, 是**静默覆盖**掉名单里已有的那个人。
 *
 * **回头客** (spec §10): 掷完人数之后摇一次 25% 的骰, 中了就把随机**一个名额**
 * 换成已出院的老熟人 —— 名字复用, 数值全部重掷 (他来的是新的一趟)。
 *
 * 为什么要加它: **界面那边早就等着它了。** `界面/申请/App.vue:128-129` 的注释
 * 原文就写着「回头客重新出现在申请列表时, 只有申请列表是他此刻最新的状态」,
 * 而那个「信赖 N」角标 (`申请__熟`) 与 算预计线数 读的 `哨兵[姓名]?.信赖`,
 * 前提都是「申请人可能是老熟人」。前端起名之后这条前提**默认永远不成立**
 * (掷出来的名字不可能撞上已有的哨兵), 角标就永远亮不起来 ——
 * 一段死代码, 外加一条**写了却没人兑现的注释**。
 *
 * 诚实说明: 查过世界书, 它**从来没有**指示过 AI 带回老病人 ——
 * 所以这不是「保留一个现有行为」, 是把一个界面在等、却从来没被做出来的
 * 可能性真的做出来。想砍随时可砍, 砍掉的后果只是那个角标继续不亮。
 */
export function 掷一批(
  输入: 掷一批的输入,
  随机: 随机源 = Math.random,
): Record<string, 申请条目> {
  const { 诊所等级, 已有姓名, 回头客池 } = 输入;
  const 避开 = new Set(已有姓名);
  const 名单: Record<string, 申请条目> = {};
  const 人数 = 每日人数(诊所等级);

  // 回头客掷两下: 先判中不中, 再选是哪一位; 第三下决定他占第几个名额。
  // 占名额而不是额外插一个 —— 人数是等级定的, 老熟人回来也不该把门口挤爆。
  const 回头客 =
    回头客池.length > 0 && 随机() < 回头客概率
      ? 回头客池[Math.floor(随机() * 回头客池.length)]
      : '';
  // 没回头客时是 -1, 而 i 从 0 起 —— 那个分支永远不会进。
  const 回头位 = 回头客 ? Math.floor(随机() * 人数) : -1;

  for (let i = 0; i < 人数; i++) {
    const 名 = i === 回头位 ? 回头客 : '';
    if (名) {
      名单[名] = { ...掷一个(诊所等级, 避开, 随机).条目, 状态: '待接' };
      避开.add(名);
      continue;
    }
    const 掷出来的 = 掷一个(诊所等级, 避开, 随机);
    名单[掷出来的.姓名] = { ...掷出来的.条目, 状态: '待接' };
    避开.add(掷出来的.姓名);
  }
  return 名单;
}
