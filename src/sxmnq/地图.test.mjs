// 直接跑: node src/sxmnq/地图.test.mjs
//
// 这张图的失败**全部是静默的** —— 摆错一格、关键词抄错一个字, 地图照画、不报错,
// 症状只是「高亮时灵时不灵」或者「点这个房间没有反应」。那种症状最容易被当成
// 「界面抽风」而不是「数据错了」, 所以这里拿断言把几条不变量钉死。
//
// 数据是生成出来的(见 地图/数据.ts 顶上那段), 所以这些断言同时也是**生成结果的
// 体检**: 哪天重新生成把 `写` 弄丢了, 这里会红。
import './测试钩子.mjs';

const 数 = await import(new URL('./地图/数据.ts', import.meta.url).href);
const { 是不是这格 } = await import(new URL('./地图/认出.ts', import.meta.url).href);
const { 世界地图, 白塔地图, 房间明细 } = 数;

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};

const 九格 = [世界地图, 白塔地图];
const 都格 = 九格.flatMap(层 => 层.格.filter(Boolean));

console.log('--- 形状: 两层都是 3×3 ---');
九格.forEach(层 => {
  断言(层.格.length === 9, `「${层.名}」是 9 格 (实得 ${层.格.length})`);
});

console.log('--- ★ 摆位照世界书, 别让人随手挪 ---');
// 世界书「世界 - 白塔」: 「位于大陆中央，由四大特区联手打造」。
断言(世界地图.格[4]?.id === 'tower', '世界地图正中是白塔 (世界书: 位于大陆中央)');
// 四个特区在世界书的方位: 北端/南端/东侧/西端。
断言(世界地图.格[1]?.id === 'north', '极北在正上');
断言(世界地图.格[3]?.id === 'west', '极西在正左');
断言(世界地图.格[5]?.id === 'east', '极东在正右');
断言(世界地图.格[7]?.id === 'south', '极南在正下');
// 世界书「地点 - 深渊地块」: 「四大区交界处的地下裂隙网络」—— 交界处就是四格中间那圈。
断言(世界地图.格[8]?.id === 'abyss', '深渊在四区交界那角');
// 世界书「地点 - 任务大厅」: 「白塔核心区·一层中庭」。
断言(白塔地图.格[4]?.id === 'mission', '白塔地图正中是任务大厅 (世界书: 核心区一层中庭)');
// 世界书: 治疗中心=北翼 / 维护站=治疗中心东侧 / 训练场=西翼 / 宿舍区=东翼 / 商业区=南翼。
断言(白塔地图.格[1]?.id === 'medical', '治疗中心在正上 (世界书: 北翼)');
断言(白塔地图.格[2]?.id === 'inhibitor', '维护站在右上 (世界书: 治疗中心东侧)');
断言(白塔地图.格[3]?.id === 'training', '训练场在正左 (世界书: 西翼)');
断言(白塔地图.格[5]?.id === 'dorm', '宿舍区在正右 (世界书: 东翼)');
断言(白塔地图.格[7]?.id === 'commercial', '商业区在正下 (世界书: 南翼)');

console.log('--- id 不重样 (重了就是同一格画两遍) ---');
const 号们 = 都格.map(格 => 格.id);
断言(new Set(号们).size === 号们.length, `id 全不重样 (共 ${号们.length} 格)`);

console.log('--- ★ 移步写进去的那个串, 必须能让自己再亮起来 ---');
// 这是这张图最容易静默坏掉的地方: 高亮拿存档去 `includes` 每一格的 `键`,
// 而移步写的是 `写 ?? 名`。写进去的串一旦不含 `键`, 移过去当场亮、下次刷新就灭,
// 而且不报错 —— 看起来只是「高亮时灵时不灵」。
都格.forEach(格 => {
  const 写 = 格.写 ?? 格.名;
  断言(
    写.includes(格.键),
    `「${格.名}」移步写「${写}」, 含关键词「${格.键}」`,
  );
});

console.log('--- 生成出来的两条容易踩空的: 全名 != 格子上的大字 ---');
const 维护站 = 都格.find(格 => 格.id === 'inhibitor');
断言(维护站?.写 === '抑制器维护站', '维护站写全名「抑制器维护站」, 不写「维护站」');
const 宿舍区 = 都格.find(格 => 格.id === 'dorm');
断言(宿舍区?.写 === '觉醒者宿舍区', '宿舍区写全名「觉醒者宿舍区」');

console.log('--- 认出在哪格 ---');
const 任务大厅 = 白塔地图.格[4];
断言(是不是这格(任务大厅, '白塔·任务大厅'), '存档「白塔·任务大厅」认得出任务大厅');
断言(是不是这格(任务大厅, '任务大厅'), '存档就写「任务大厅」也认得出');
断言(是不是这格(任务大厅, '任务大厅的前台受理区'), '存档写得更细也认得出 (比的是包含)');
断言(!是不是这格(任务大厅, '白塔·治疗中心'), '人不在任务大厅时不亮');
断言(!是不是这格(任务大厅, ''), '存档里地点是空串时不亮任何一格');
断言(!是不是这格(任务大厅, undefined), '存档里地点缺失时不亮 (不能崩)');
// 移步写进去的串, 自己这格得亮。
断言(是不是这格(维护站, 维护站.写), '移步到维护站之后, 维护站这格自己亮');
断言(是不是这格(宿舍区, 宿舍区.写), '移步到宿舍区之后, 宿舍区这格自己亮');
// AI 按 `名` 写的那条路。
断言(是不是这格(维护站, '你在维护站'), 'AI 正文里写「维护站」, 这格也亮 (名也认)');

console.log('--- 可钻的格子都有下层, 下层都有格子认领 (不许有死数据) ---');
const 可钻的 = 都格.filter(格 => 格.可钻).map(格 => 格.id);
const 有明细的 = Object.keys(房间明细);
// 两种「可钻」, 去处不一样, 别混成一锅:
//   - `tower` 钻进**另一层九格**(白塔地图), 它不该有房间明细。
//   - `south` 这轮没做数据(极南 DLC 还没开), 点下去只弹说明。它可钻是照老卡留的
//     位子 —— 等极南做的时候, 这里应该有一份明细。留个名字在这儿免得忘。
const 钻下一层的 = ['tower'];
const 这轮没做的 = ['south'];
const 该有明细的 = 可钻的.filter(id => !钻下一层的.includes(id) && !这轮没做的.includes(id));
该有明细的.forEach(id => {
 断言(有明细的.includes(id), `可钻的「${id}」有房间明细`);
});
有明细的.forEach(id => {
  断言(可钻的.includes(id), `有房间明细的「${id}」在图上是个可钻的格子 (没人在用的明细就是死代码)`);
});
// `tower` 的下一层就是白塔地图本身 —— 组件里是写死的那一条分支, 数据里没有对应
// 关系可查, 所以在这儿把它的去处说清楚, 免得日后有人把白塔地图从组件里摘掉。
断言(白塔地图.名 === '白塔', '「白塔」那格钻进的是白塔地图 (组件靠 id === \'tower\' 认它)');

console.log('--- 房间明细本身 ---');
有明细的.forEach(id => {
  const 行 = 房间明细[id];
  断言(行.length > 0, `「${id}」的明细不是空的`);
  行.forEach(间 => {
    断言(!!间.说?.trim(), `「${间.名}」有一句说明 (点开不能是空白)`);
  });
});

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
