// 主角开局可以走的几条职业路线。**这里是唯一的真值源** ——
// `schema.ts` 拿 `路线取值` 拼枚举, 创建页拿 `路线表` 渲染卡片, 两边都从这儿读。
//
// 为什么不各写一份、再加个测试去比对: 这两处一旦对不上, 后果是**静默**的。
// 创建页写进变量的那个值必须和 schema 的枚举一个字都不差 —— 差一个字, MVU 的
// safeParse 就整份失败、直接 `return`, 玩家看到的是「所有数值变回默认值」, 而不是
// 一条报错(见 创建/App.vue 顶部同一处注释)。靠「改的时候记得两边都改」不可靠,
// 靠一条正则做守卫也只是事后报警; 让它**只有一处可改**, 这类错就无从发生。
//
// 加第三条线: `路线取值` 和 `路线表` 各加一行, 别处不用动。

/** 会被写进变量、必须与 schema 枚举逐字相同的那些值。 */
export const 路线取值 = ['诊所线', '白塔向导路线'] as const;

export type 路线键 = (typeof 路线取值)[number];

/**
 * 创建页那一屏的卡片各要什么。
 *
 * `键` 是写进变量的值 —— 必须在上面的 `路线取值` 里。
 * `名` / `介` 只给玩家看, 改文案不影响任何逻辑。
 * `开` 是这条路**现在能不能选进游戏**。和 `身份表` 里的哨兵同一个套路:
 *   枚举收着这个值(所以老存档、手写存档都读得进来), 但创建页把它灰掉。
 * `要命名` 是这条路**走不走第三步**。诊所线第三步问诊所名; 白塔向导路线不问 ——
 *   向导不经营诊所, 拿「给诊所起个名」去问他是错的。创建页照这个标记决定选完
 *   是去第三步还是直接落盘进游戏, 不认路线的名字。
 */
export const 路线表: ReadonlyArray<{
  键: 路线键;
  名: string;
  介: string;
  开: boolean;
  要命名: boolean;
}> = [
  // 保留旧路线定义与源码，但新开局不展示。
  { 键: '诊所线', 名: '诊所线', 介: '从无名诊所开始。接单、疏导、攒名声。', 开: false, 要命名: true },
  { 键: '白塔向导路线', 名: '白塔向导路线', 介: '白塔体制内的向导。', 开: true, 要命名: false },
];
