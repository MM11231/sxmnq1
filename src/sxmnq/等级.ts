/**
 * 五档等级。**这是全工程唯一一处定义「等级是什么」的地方。**
 *
 * 原来它住在 界面/治疗/game.ts 里，但 生成/ 那一层（谁会被诊所吸引来）
 * 比界面层更底，让它反过来 import 界面层是依赖倒挂 —— 所以提到这里。
 * game.ts 仍然再导出一次，界面那几处既有 import 不用动。
 */
export type 等级 = 'D' | 'C' | 'B' | 'A' | 'S';

/** 由低到高。概率池、闸门、称号都按这个序推 */
export const 等级序: readonly 等级[] = ['D', 'C', 'B', 'A', 'S'];

export const 等级值: Record<等级, number> = { D: 0, C: 1, B: 2, A: 3, S: 4 };

/** 升一档。已经是 S 就还是 S —— 名声在满级时会一直顶在 100, 不该继续进位 */
export function 升一档(等级: 等级): 等级 {
  return 等级序[Math.min(等级值[等级] + 1, 等级序.length - 1)];
}

/**
 * 精神力上限由等级给: D 100 / C 120 / B 140 / A 160 / S 180。
 *
 * spec §9 把 `精神力上限` 从 AI 手上收回来时写的是「前端按等级给」,
 * 但**全篇没有给公式** —— 而它原来是挂在 `主角.执业等级` 上的
 * (「只在执业等级提升时同步增加」), 那个字段这一步已经删了,
 * 那条规则就成了悬空引用。
 *
 * 这里取的 `100 + 等级值 × 20` 是实施计划**自己定的数** (已报给用户):
 * 基准 100 与改动前的初值一致, 每档 +20 让升级除了「清得更快」之外
 * 还多一点「接得更多」的手感。**要改就改这一个函数。**
 */
export function 算精神力上限(等级: 等级): number {
  return 100 + 等级值[等级] * 20;
}
