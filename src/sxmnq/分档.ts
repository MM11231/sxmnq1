/**
 * 把数值翻译成行为描述。
 *
 * 这是整套机制的核心 (设计文档 §8): AI 看「信赖 45」只会写出泛泛的反应,
 * 看「对{{user}}的能力比较认同，认为{{user}}的精神疏导效果不错」才会写准。
 *
 * schema.ts 用它生成 $ 派生字段 (每回合都跟着变量列表进提示词),
 * 结算.ts 用它兜底 (哨兵刚出现、还没进变量时)。
 * 两边必须一致, 所以只在这里写一份。
 */

export function 信赖分档(信赖: number): string {
  if (信赖 >= 80) return '完全信赖{{user}}的能力，只愿意让{{user}}为自己进行精神疏导';
  if (信赖 >= 60) return '比较信赖{{user}}的能力，认为{{user}}很可靠';
  if (信赖 >= 40) return '对{{user}}的能力比较认同，认为{{user}}的精神疏导效果不错';
  if (信赖 >= 20) return '对{{user}}的能力有一点信任，认为{{user}}是个正经向导';
  return '不清楚{{user}}的能力，不知道能不能信赖';
}

export function 好感分档(好感: number): string {
  if (好感 >= 12) return '渴望和{{user}}组建家庭相伴一生，将{{user}}视为一生的伴侣，会频繁试图求婚和求爱';
  if (好感 >= 9) return '渴望成为{{user}}的恋人，会非常明显地表达出追求，非常容易吃醋';
  if (好感 >= 6) return '会隐晦地试着追求{{user}}，会在对话里试探自己对{{user}}是否特殊';
  if (好感 >= 3) return '将{{user}}视为有点在意的人，会时不时下意识地靠近{{user}}';
  return '认识的向导，会用公事公办的态度对待';
}

/**
 * 等级 → 称号。**五档一一对应，不做数学换算** —— 以前是拿 1~5 的星级去查表，
 * 现在直接按等级查，少一层「数字对不对得上」的心智负担。
 */
const 称号表: Record<string, string> = {
  D: '无名诊所',
  C: '略有耳闻',
  B: '小有名气',
  A: '声名远播',
  S: '声名鹊起',
};

export function 等级称号(等级: string): string {
  return 称号表[等级] ?? 称号表.D;
}
