export function 查事件(id:string):探索事件|undefined {
  if(!id.startsWith('festival:'))return 日常事件.find(e=>e.id===id);
  const 节=节庆表.find(e=>e.id===id.slice(9));
  return 节 ? {id,标题:节.名称,正文:节.场景,选项:节庆选项[节.id],地点:节.地点} : undefined;
}
