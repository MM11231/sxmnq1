type Data={日程:{天数:number;时段:number;历法偏移:number;考核目标:string;活动记录:string[];偶遇:string};向导:Record<属性,number>;主角:{金钱:number;精神力:number;精神力上限:number};世界:{日期:string;天气:string;生活:{探索:探索状态;遭遇记录:{日期:string;地点:string;标题:string;正文:string;结果:string}[]}}};
export function 安排探索事件(data:Data,地点:{id:string;name:string;district:string},时段:number) {
  const 状=data.世界.生活.探索,日=data.日程.天数,历=年历位置(日,data.日程.历法偏移);
  if(日%2===1||data.日程.考核目标||状.待处理||状.触发日===日)return null;
  const 节=今日节庆(历),节庆键=节?`${历.年}:${节.id}`:'';
  let 事件:探索事件|undefined;
  if(节?.地点.includes(地点.id)&&!(节.id==='stars'&&时段<2)&&!状.节庆足迹.includes(节庆键))事件=查事件('festival:'+节.id);
  else {
    const 种=`${日}/${时段}/${地点.id}/探索`;
    if(固定数(种+'/出现')>=.35)return null;
    const 池=日常事件.filter(e=>(!e.地点||e.地点.includes(地点.id))&&(!e.区||e.区===地点.district)&&(!e.季||e.季===历.季)&&(!e.天气||e.天气.test(data.世界.天气))&&!状.最近.some(r=>r.id===e.id&&日-r.天数<8));
    if(池.length)事件=池[Math.floor(固定数(种+'/选择')*池.length)];
  }
  if(!事件)return null;
  状.触发日=日;
  状.待处理={id:事件.id,天数:日,地点:地点.name,地点id:地点.id,前置行动:data.日程.活动记录.at(-1)??'',节庆键:事件.id.startsWith('festival:')?节庆键:''};
  return 状.待处理;
}
export function 处理探索事件(data:Data,选择:string) {
  const 状=data.世界.生活.探索,待=状.待处理;
  if(!待)throw Error('这件事已经处理过了。');
  const 件=查事件(待.id),选项=件?.选项.find(o=>o.id===选择);
  if(选择!=='skip'&&!选项)throw Error('请选择有效的回应。');
  if(待.天数!==data.日程.天数){状.待处理=null;return '这件事已经过去，未重复结算。';}
  const 结果:string[]=[];
  if(选项?.属性){const 原=data.向导[选项.属性];data.向导[选项.属性]=Math.min(100,原+1);结果.push(`${选项.属性} +${data.向导[选项.属性]-原}`);}
  if(选项?.金钱){data.主角.金钱+=选项.金钱;结果.push(`金钱 +${选项.金钱}`);}
  if(选项?.恢复){const 原=data.主角.精神力;data.主角.精神力=Math.min(data.主角.精神力上限,原+选项.恢复);结果.push(`精力 +${data.主角.精神力-原}`);}
  const 正文=选项?.结果 ?? '你继续自己的安排，没有参与这件事。',结果文=结果.join('，')||'无数值变化';
  const 记录=`${件?.标题??'途中见闻'}：${正文}（${结果文}，不额外占用时段）`;
  状.最近.push({id:待.id,天数:待.天数});状.最近=状.最近.slice(-30);
  if(待.节庆键)状.节庆足迹.push(待.节庆键);状.节庆足迹=状.节庆足迹.slice(-24);
  data.世界.生活.遭遇记录.push({日期:data.世界.日期,地点:待.地点,标题:件?.标题??'途中见闻',正文,结果:结果文});
  data.世界.生活.遭遇记录=data.世界.生活.遭遇记录.slice(-8);
  data.日程.活动记录.push(记录);data.日程.偶遇+=(data.日程.偶遇?'\n':'')+记录;
  状.待处理=null;
  return `${待.地点} · ${待.前置行动}\n${记录}`;
}
