import assert from 'node:assert/strict';
import { 是值班日, 执行活动, 登记治疗, 结束一天, 开始考核, 结算考核, 日历日期 } from './规则.ts';
const 日 = { 天数: 1, 时段: 0, 起始日期: '2026年12月31日', 已接诊: 0, 本日经验: 0, 活动记录: [], 上日结算: '', 考核目标: '', 考核阶段: 0, 偶遇: '' };
const 成长 = { 等级: 'D', 经验: 0, 力量: 10, 精神: 10, 学识: 10, 魅力: 10, 已通关: false };
const 主角 = { 精神力: 100, 精神力上限: 100 };
const 活 = { 名称: '学习', 属性: '学识', 收益: 3, 消耗: 10 };
assert(是值班日(日));
assert.throws(() => 执行活动(日, 成长, 主角, 活));
登记治疗(日, 成长, 'A'); assert.equal(成长.经验, 16);
结束一天(日, 主角); assert(!是值班日(日)); assert.equal(主角.精神力, 100);
assert.throws(() => 登记治疗(日, 成长, 'S'));
执行活动(日, 成长, 主角, 活); assert.equal(成长.学识, 13); assert.equal(日.时段, 1);
const 存档 = structuredClone({ 日, 成长, 主角 }); assert(!是值班日(存档.日)); assert.equal(存档.日.时段, 1);
执行活动(日, 成长, 主角, 活); 执行活动(日, 成长, 主角, 活);
assert.throws(() => 执行活动(日, 成长, 主角, 活)); assert.equal(成长.学识, 19);
assert.equal(日历日期('2026年12月31日', 2), '2027年01月01日');
结束一天(日, 主角); assert(是值班日(日)); 结束一天(日, 主角);
assert.throws(() => 开始考核(日, 成长));
Object.assign(成长, { 经验: 100, 力量: 20, 精神: 20, 学识: 20, 魅力: 20 });
开始考核(日, 成长); assert.throws(() => 结束一天(日, 主角));
结算考核(日, 成长, 'B'); assert.equal(成长.等级, 'D'); assert.equal(成长.经验, 100);
结束一天(日, 主角); 结束一天(日, 主角); 开始考核(日, 成长); 结算考核(日, 成长, 'A');
assert.equal(成长.等级, 'C'); assert.equal(成长.经验, 0); assert.equal(成长.学识, 20);
assert.throws(() => 结算考核(日, 成长, 'S'));
结束一天(日, 主角); 结束一天(日, 主角);
Object.assign(成长, { 等级: 'A', 经验: 100, 力量: 85, 精神: 85, 学识: 85, 魅力: 85 });
开始考核(日, 成长); 结算考核(日, 成长, 'A'); assert.equal(日.考核阶段, 1); assert.equal(成长.等级, 'A');
结算考核(日, 成长, 'A'); assert.equal(成长.等级, 'S'); assert(成长.已通关);
console.info('日程、持久化、跨年、活动限制、考核重试和S级通关测试通过。');
