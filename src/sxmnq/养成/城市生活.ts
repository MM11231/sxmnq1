import { 年历位置, 今日节庆, 下一节庆, 旧日期位置 } from './年历';
export interface 城市生活 { 更新日:number; 节日:string; 城内消息:string; 遭遇记录:{日期:string;地点:string;标题:string;正文:string;结果:string}[] }
export function 更新城市(世界:{天气:string;温度:string;季节:string;星期:string;生活:城市生活},起始:string,天数:number,偏移?:number) {
 if(世界.生活.更新日===天数)return false;
 const 历=年历位置(天数,偏移??旧日期位置(起始)),季=历.季;
 const 天气池={春:['薄雾','晴朗','细雨','多云','阵雨'],夏:['晴朗','多云','雷阵雨','晴热','阴天'],秋:['晴朗','多云','凉雨','薄雾','晴朗'],冬:['阴天','小雪','晴冷','多云','大雪']};
 世界.天气=天气池[季][((历.总日*17+历.年*3)>>>0)%5];世界.季节=季;
 世界.温度=({春:'12—20℃',夏:'24—32℃',秋:'10—18℃',冬:'−3—6℃'})[季];
 世界.星期='星期'+['日','一','二','三','四','五','六'][历.总日%7];
 const 节=今日节庆(历),下一=下一节庆(历);
 世界.生活.节日=节?.名称??'';
 const 日常=['档案馆新开放了一批脱敏任务记录。','训练区张贴了新的公开课程。','商业区有几家店铺更换了当日菜单。','公共厨房里飘着热汤的香气。','中庭挂出了补给分拣志愿者招募。','接驳站更新了本周的外勤时刻表。'];
 世界.生活.城内消息=节?节.名称+' · '+季+节.起+'—'+节.止+'日。'+节.简介+(历.日===节.止?'今天是最后一天。':''):日常[历.总日%日常.length]+(下一.还有<=2?'再过'+下一.还有+'天是'+下一.节.名称+'。':'');
 世界.生活.更新日=天数;return true;
}
