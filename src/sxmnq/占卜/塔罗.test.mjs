// 直接跑: node src/sxmnq/占卜/塔罗.test.mjs
//
// 占卜这个模块最值钱的一条性质是**纯派生**: 同一天同一张牌, 且解读只跟
// 牌义与当日局势有关。它靠不住的话, 玩家刷新一下牌就换了 —— 那这一卦
// 就什么都不值了, 而且这种坏法哪里都不报错。
import '../测试钩子.mjs';
const T = await import(new URL('./塔罗.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};

const 造势 = (改 = {}) => ({ 精神力: 80, 精神力上限: 100, 名声: 50, 等级: 'C', 在诊: 1, 床位: 2, ...改 });

console.log('--- 牌堆本身 ---');
等于(T.大阿卡纳.length, 22, '22 张大阿卡纳');
等于(new Set(T.大阿卡纳.map(牌 => 牌.名)).size, 22, '22 个牌名没有重复');
等于(new Set(T.大阿卡纳.map(牌 => 牌.号)).size, 22, '22 个编号没有重复');
断言(T.大阿卡纳.every(牌 => 牌.正.trim().length > 0), '每张都有正位牌义');
断言(T.大阿卡纳.every(牌 => 牌.逆.trim().length > 0), '每张都有逆位牌义');
断言(T.大阿卡纳.every(牌 => 牌.正 !== 牌.逆), '正逆位不是同一句话 (那样逆位就白翻了)');
断言(T.大阿卡纳.every(牌 => 牌.号 && 牌.名), '每张都有号与名');
等于(T.大阿卡纳[0].名, '愚者', '第 0 张是愚者');
等于(T.大阿卡纳[21].名, '世界', '第 21 张是世界');
断言(T.牌面(T.大阿卡纳[11]) === 'XI · 正义', `牌面印成「号 · 名」(实得 ${T.牌面(T.大阿卡纳[11])})`);
等于(T.找牌('塔')?.号, 'XVI', '按名字找得到牌');
等于(T.找牌('格陵兰'), undefined, '找不到的牌名给 undefined, 不是抛错');

console.log('--- 定种: 同一天同一张, 跨天才换 ---');
const 甲 = T.抽牌('三月十四');
const 乙 = T.抽牌('三月十四');
等于(甲.牌.名, 乙.牌.名, '同一天抽两次是同一张牌');
等于(甲.逆位, 乙.逆位, '同一天正逆位也一样');
等于(T.抽牌('三月十四').牌.名, 甲.牌.名, '再抽一次还是它 (分布式的纯函数, 没有内部状态)');

// 跨天要真的会换。只比一天不够 —— 万一 散列 退化成常数, 比一天也会「不同」。
const 一旬 = ['三月十四', '三月十五', '三月十六', '三月十七', '三月十八', '三月十九', '三月二十']
  .map(d => T.抽牌(d).牌.名);
断言(new Set(一旬).size >= 4, `十天里至少出 4 张不同的牌 (实得 ${new Set(一旬).size} 张: ${一旬.join(' ')})`);

// 「三月十四 → 三月十五」抽到相邻的牌, 就是 FNV-1a 低位不动的那种退化。
// 这是 摇号机 存在的全部理由, 所以专门钉一条。
const 邻 = [];
for (let i = 1; i <= 12; i++) 邻.push(T.大阿卡纳.findIndex(牌 => 牌.名 === T.抽牌(`四月第${i}日`).牌.名));
const 递增数 = 邻.slice(1).filter((v, i) => v === 邻[i] + 1).length;
断言(递增数 <= 3, `相邻日期不会一路抽到相邻的牌 (12 天里只有 ${递增数} 次递增)`);

// 覆盖: 一整年下来 22 张都得露面, 不然有些牌玩家永远见不到。
const 见 = new Set();
for (let m = 1; m <= 12; m++) for (let d = 1; d <= 28; d++) 见.add(T.抽牌(`某月${m}月第${d}日`).牌.名);
等于(见.size, 22, `336 天里 22 张牌全都出现过 (实得 ${见.size} 张)`);

// 逆位不能一边倒。全正或全逆都说明那个 < 0.35 写错了。
let 逆数 = 0;
const 总 = 500;
for (let i = 0; i < 总; i++) if (T.抽牌(`抽第${i}日`).逆位) 逆数++;
const 逆比 = 逆数 / 总;
断言(逆比 > 0.25 && 逆比 < 0.46, `逆位比例落在 0.25~0.46 之间 (实得 ${逆比.toFixed(3)})`);

console.log('--- 没有日期就不起卦 ---');
等于(T.抽牌(''), null, '空日期不给牌');
等于(T.抽牌('   '), null, '只有空白也不给牌');
等于(T.起一卦('', 造势()), null, '空日期起不了卦 (否则「今天」这个概念不成立)');
断言(!!T.起一卦('三月十四', 造势()), '有日期就起得了');

console.log('--- 起一卦 是纯函数 ---');
const 势 = 造势();
等于(T.起一卦('三月十四', 势), T.起一卦('三月十四', 造势()), '同样的日期与局势 → 逐字相同的卦');
等于(T.起一卦('三月十四', 造势({ 精神力: 3 })), T.起一卦('三月十四', 造势({ 精神力: 3 })), '换了局势也一样是纯的');
断言(T.起一卦('三月十四', 造势()).牌 === T.起一卦('三月十四', 造势({ 精神力: 3 })).牌,
  '★ 局势变了牌不跟着变 —— 牌只认日期。牌跟着精神力换的话, 玩家一治疗卦就变了');

console.log('--- 解读 = 牌义 × 当日局势 (spec §7) ---');
const 卦 = T.起一卦('三月十四', 造势());
const 那张 = T.找牌(卦.牌);
断言(卦.解读.includes(卦.逆位 ? 那张.逆 : 那张.正), '解读里有牌义那一段, 且正逆位取对了');
断言(卦.解读.includes('精神海'), '解读里念了精神海');
断言(卦.解读.includes('名字') || 卦.解读.includes('街'), '解读里念了名声');
// 默认局势是 在诊 1 / 床位 2, 那一段的原话是「里面还躺着人」—— 里面既没有
// 「诊所」也没有「床」。按词表猜措辞是量不准的, 直接钉住那一句。
断言(卦.解读.includes('里面还躺着人'), `解读里念了诊室 (在诊 1/2 时说「里面还躺着人」)`);
等于(卦.已抽于, '三月十四', '卦上记着它是哪天的');
断言(卦.解读.length > 60 && 卦.解读.length < 220,
  `解读长度合适 (实得 ${卦.解读.length} 字 —— 它每一轮都会被注进提示词)`);

// 三个轴各自都要真的改变解读, 否则「× 当日局势」是假的, 只是每段都写了句废话。
const 换 = 改 => T.起一卦('三月十四', 造势(改)).解读;
const 基 = 换({});
// 三个档位要**互相**不同, 不是跟基准比 —— 基准的精神力是 80, 跟 100 落在同一个
// 档里, 拿它当参照量出「一样」是必然的, 而那并不说明有哪一档失效了。
const 三档 = [换({ 精神力: 10 }), 换({ 精神力: 50 }), 换({ 精神力: 100 })];
等于(new Set(三档).size, 3, `精神力的低/中/高三档各说各的 (实得 ${new Set(三档).size} 种)`);
断言(换({ 精神力: 10 }) !== 基, '精神力低 → 解读跟基准不同');
// (不拿 100 跟基准比: 基准的 80 本来就已经在「满」那一档里, 两者相同是对的。)
断言(换({ 名声: 5 }) !== 基, '名声低 → 解读不同');
断言(换({ 名声: 95 }) !== 基, '名声高 → 解读不同');
断言(换({ 在诊: 0 }) !== 基, '没人在诊 → 解读不同');
断言(换({ 在诊: 2, 床位: 2 }) !== 基, '床满了 → 解读不同');
// 边界: 上限是 0 (老存档 / 没填) 时不能除出 NaN 或 Infinity
const 破 = T.起一卦('三月十四', 造势({ 精神力上限: 0, 精神力: 80 }));
断言(!/NaN|Infinity|undefined/.test(破.解读), `上限为 0 时解读里不出现 NaN/Infinity (实得「${破.解读}」)`);

console.log('--- 「今天抽过了吗」 ---');
等于(T.今天抽过了({ 已抽于: '三月十四', 牌: '塔', 逆位: false, 解读: 'x' }, '三月十四'), true, '日期对得上 → 今天抽过了');
等于(T.今天抽过了({ 已抽于: '三月十三', 牌: '塔', 逆位: false, 解读: 'x' }, '三月十四'), false, '昨天抽的 → 今天还能抽');
等于(T.今天抽过了({ 已抽于: '', 牌: '', 逆位: false, 解读: '' }, ''), false,
  '★ 空日期时不许算「抽过了」—— 算的话玩家点了没反应, 而且永远抽不了');
等于(T.今天抽过了({ 已抽于: '三月十四', 牌: '', 逆位: false, 解读: '' }, ''), false, '世界日期空着时也不认旧卦');

console.log('--- 媚u 防线: 牌义不夸玩家 (spec §7 + §6.4) ---');
// 阴性断言 —— 先自检仪表 (仓库既有教训)。喂一句**已知该命中**的话进去,
// 探针必须数得出来; 数不出来就说明这把尺子是坏的, 下面的 0 不算数。
const 脏话 = ['你的诊所一定会名声大噪', '客人慕名而来', '求诊的人排到了街上', '你会成为最强的向导'];
const 脏词 = ['名声大噪', '慕名', '求诊', '排到了街上', '最强'];
const 数脏 = 文本 => 脏词.filter(w => 文本.includes(w)).length;
const 自检 = 脏话.map(数脏);
断言(自检.every(n => n > 0), `探针自检: 四句已知的媚u话都被数出来了 (${自检.join(',')})`);
断言(数脏('今天精神海还算稳。') === 0, '探针自检: 一句干净的话数出来是 0');

const 全牌义 = T.大阿卡纳.flatMap(牌 => [牌.正, 牌.逆]);
const 漏的 = 全牌义.filter(句 => 数脏(句) > 0);
等于(漏的, [], `44 句牌义没有一句夸玩家 (漏了 ${漏的.length} 句)`);

// 解读那一层也要过一遍。逐日、逐局势地扫, 免得某个组合才露出来。
const 脏解读 = [];
for (const 日 of ['三月十四', '三月初一', '霜降月第一日', '腊月廿三', '某月某日']) {
  for (const 精 of [0, 50, 100]) for (const 名 of [0, 50, 100]) for (const 床 of [[0, 2], [1, 2], [2, 2]]) {
    const g = T.起一卦(日, 造势({ 精神力: 精, 名声: 名, 在诊: 床[0], 床位: 床[1] }));
    if (数脏(g.解读) > 0) 脏解读.push(`${日}/${精}/${名}/${床} → ${g.解读}`);
  }
}
等于(脏解读, [], `135 种局势组合的解读都没有媚u (实得 ${脏解读.length} 条)`);

// 第二人称: 牌义是「说给玩家听」的, 出现「你」是**对的** —— 这条不是抓「你」,
// 而是抓「你」后面跟着的那种吹捧句式。上面 4 个脏词才是判据, 这里只钉住
// 牌义里确实有第二人称 (否则上面那条 0 可能是因为整篇都在说第三人称, 而不是干净)。
断言(T.大阿卡纳.some(牌 => 牌.正.includes('你') || 牌.逆.includes('你')), '牌义是第二人称的 —— 上面那个 0 是真干净, 不是因为没有主语');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
