// 占卜。22 张大阿卡纳 + 正逆位, 全部内置在前端 (spec §7)。
//
// 跟报纸一样是**纯派生**: 给定 (日期, 当日局势) 就有唯一一卦。零 token, 不掷骰,
// 不联网。同一天刷新多少次都是同一张牌 —— 换牌会立刻毁掉「这是今天的卦」这件事。
//
// 一份卦抽完要**连解读一起存进变量** (世界.占卜), 所以 起一卦 必须是纯函数:
// 存下去什么, 明天翻出来还是什么, 不能因为中间精神力变了就跟着变。

import { 摇号机, 散列 } from '../定种';

export interface 牌 {
  /** 罗马数字。牌面上要印, 也让玩家能一眼看出这是第几张 */
  号: string;
  名: string;
  /** 正位牌义 */
  正: string;
  /** 逆位牌义 */
  逆: string;
}

