/** 牌面上印的名字, 如「XI · 正义」 */
export function 牌面(牌: 牌): string {
  return `${牌.号} · ${牌.名}`;
}

export function 找牌(名: string): 牌 | undefined {
  return 大阿卡纳.find(牌 => 牌.名 === 名);
}

/** 起卦要看的当日局势。全部来自 stat_data, 一个都不多问。 */
export interface 局势 {
  精神力: number;
  精神力上限: number;
  名声: number;
  等级: string;
  在诊: number;
  床位: number;
}

/** 存进 `世界.占卜` 的那一份。字段与 schema 里的 占卜形状 一一对应。 */
export interface 卦 {
  已抽于: string;
  牌: string;
  逆位: boolean;
  解读: string;
}

export interface 抽出来的 {
  牌: 牌;
  逆位: boolean;
}

/**
 * 今天的牌。**只认日期** —— 局势不进种子, 否则精神力一变牌就跟着换,
 * 而「今天就是这张」正是占卜唯一的份量所在。
 *
 * 种里带上 `占卜|` 前缀: 报纸的种是 `${日期}|${版面}`, 两边用同一个散列,
 * 不带前缀的话「占卜」和某个版面名有可能撞上, 于是报纸和塔罗一起动。
 */
export function 抽牌(日期: string): 抽出来的 | null {
  if (!日期.trim()) return null; // 老存档没有日期。没有哪一天, 也就没有今天的卦。
  const 随 = 摇号机(散列(`占卜|${日期}`));
  const 牌 = 大阿卡纳[Math.floor(随() * 大阿卡纳.length)];
  // 逆位取 0.35 而不是 0.5: 逆位牌义大多更重, 一半一半的话整副牌天天在唱反调,
  // 玩家很快就学会无视它。偏向正位, 逆位才像是一次真正的提醒。
  const 逆位 = 随() < 0.35;
  return { 牌, 逆位 };
}

/** 精神海还剩多少。三段就够 —— 再多玩家也读不出差别。 */
function 说精神海(势: 局势): string {
  const 上限 = 势.精神力上限 > 0 ? 势.精神力上限 : 100;
  const 比 = 势.精神力 / 上限;
  if (比 < 0.3) return '精神海是浅的，今天你能动用的比你以为的少。';
  if (比 < 0.7) return '精神海还算稳，只是没有富余。';
  return '精神海是满的。这样的日子不多。';
}

/**
 * 名声。**说的是它的代价, 不是它的好处** —— 这一段最容易滑成夸玩家,
 * 「名声」在这里是「有多少人在看着你」, 而不是「你多厉害」。
 */
function 说名声(势: 局势): string {
  if (势.名声 < 30) return '白塔里知道你名字的人还不多。';
  if (势.名声 < 70) return '铜铃响过几回了，街面上开始有人认得这张脸。';
  return '你的名字已经走出这条街。这是好事，也是别人开始打量的理由。';
}

/** 诊室里有没有人。这是玩家手上真正压着的东西。 */
function 说诊室(势: 局势): string {
  if (势.在诊 <= 0) return '诊所里没有别人，今天的声音都是外面的。';
  if (势.在诊 < 势.床位) return '里面还躺着人，你手上不止一件事。';
  return '床满了。今天再来一个，你就得做选择。';
}

/**
 * 起一卦。解读 = 牌义 × 当日局势 (spec §7)。
 *
 * **纯函数**: 同样的 (日期, 局势) 永远给同一份解读。存进变量之后就不再重算,
 * 所以玩家今天翻出来的那段话, 晚上再看还是那段话。
 */
export function 起一卦(日期: string, 势: 局势): 卦 | null {
  const 抽 = 抽牌(日期);
  if (!抽) return null;
  return {
    已抽于: 日期,
    牌: 抽.牌.名,
    逆位: 抽.逆位,
    解读: (抽.逆位 ? 抽.牌.逆 : 抽.牌.正) + 说精神海(势) + 说名声(势) + 说诊室(势),
  };
}

/**
 * 存着的那一卦今天还算不算数。
 *
 * `已抽于` 为空时一律算没抽过 —— 空日期进不了 起一卦, 但变量里可能躺着一份
 * 手改过的存档, 那也不该让它冒充「今天已经抽过了」。
 */
export function 今天抽过了(占卜: 卦, 日期: string): boolean {
  return !!日期.trim() && 占卜.已抽于 === 日期;
}
