export function 固定数(种子: string) {
  let hash = 2166136261;
  for (let i = 0; i < 种子.length; i++) hash = Math.imul(hash ^ 种子.charCodeAt(i), 16777619);
  return (hash >>> 0) / 4294967296;
}
