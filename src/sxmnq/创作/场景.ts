const 闲谈地点 = ['cafe', 'bookstore', 'canteen', 'bar', 'market', 'garden'];
export function 地点场景(地点: 地点, 上: 场景上下文): 场景 {
  const 种 = `${上.天数}/${上.时段}/${地点.id}`;
  const 池 = 地点日常[地点.id] ?? 分区日常[地点.district] ?? ['附近有人经过，随后又恢复了平常的安静。'];
  const 光 = ['晨光落在入口附近。', '午后的光线沿着建筑边缘移过来。', '灯陆续亮起来，脚步声比白天稀疏。', '夜深了，附近只剩零星的灯光。'][Math.min(3, Math.max(0, 上.时段))];
  const 雨 = /雨/.test(上.天气 ?? '') ? '来客收起雨伞，鞋底留下一点湿痕。' : /雪/.test(上.天气 ?? '') ? '入口旁有人轻轻掸落肩头的雪。' : '';
  const 描写 = 节庆场景(地点.id, 上.历日, 上.时段) + 光 + 雨 + 池[Math.floor(固定数(种 + '/日常') * 池.length)];
  // 一个游戏日最多一个时段、一个公共地点有作品闲谈。没有浏览奖励或身份揭晓。
  const 快照 = 上.创作.场景日 === 上.天数;
  const 作品们 = 快照 ? 上.创作.场景作品 ?? [] : 上.创作.作品;
  const 名气 = 快照 ? 上.创作.场景名气 ?? 0 : 上.创作.名气;
  const 作池 = 作品们.filter(作 => 作.首刊日 < 上.天数 && 上.天数 - 作.最近刊登日 <= 14 && 作.名气 >= 8);
  if (!作池.length || 上.时段 !== Math.floor(固定数(`${上.天数}/闲谈时段`) * 3)
    || 地点.id !== 闲谈地点[Math.floor(固定数(`${上.天数}/闲谈地点`) * 闲谈地点.length)]) return { 描写, 闲谈: '' };
  const 概率 = Math.min(0.22, 0.03 + 名气 * 0.0019);
  if (固定数(`${上.天数}/作品是否被提到`) >= 概率) return { 描写, 闲谈: '' };
  const 作 = 作池[Math.floor(固定数(`${上.天数}/哪部作品`) * 作池.length)];
  const 普通 = [
    `邻桌有人把报纸折好：“《${作.标题}》那篇，回去再看。”同伴应了一声，接着聊起换班。`,
    `有人折好报纸：“《${作.标题}》那篇我还没看完。”同伴说等回去再看，两人很快换了话题。`,
    `一位来客问同伴有没有看过《${作.标题}》。对方摇摇头，继续看自己的终端。`,
  ];
  const 推荐 = `有人随口问同伴：“你读过《${作.标题}》吗？有空可以试试，报上还留着前几期。”说完便收起报纸。`;
  const 闲谈 = 作.名气 >= 30 && 固定数(种 + '/推荐') < 0.18 ? 推荐 : 普通[Math.floor(固定数(种 + '/闲谈') * 普通.length)];
  return { 描写, 闲谈 };
}
