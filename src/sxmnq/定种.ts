// 定种。**同一个输入给同一串数** —— 报纸和占卜都靠它做到「同一天刷新多少次
// 都是同一份」。
//
// 单独一个文件, 而不是让 占卜/塔罗.ts 去 import 报纸/装配.ts: 那两个模块之间
// 没有任何关系 (报纸是六个版面的池子, 占卜是一副 22 张的牌), 唯一的共同点
// 只是「都要一个小小的确定性随机」。让占卜依赖报纸, 以后改报纸的抽条逻辑就会
// 莫名其妙地影响塔罗。
//
// **不复用 生成/闸门.ts 那套掷骰** (spec §8): 那边是「日期变了重掷一批, 并且要
// 保留已经命名的条目」, 是有状态的; 这边是无状态的派生。两者的幂等要求不同,
// 混用迟早会踩到「重掷把报纸也重掷了」这种难查的联动。

/**
 * FNV-1a。只求「同样的串给同样的数」, 不需要任何密码学性质。
 *
 * `Math.imul` 不能换成 `*`: 后者在 JS 里会先转成双精度浮点, 高位移出去就没了,
 * 哈希会退化到几乎不散 —— 于是「三月十四」和「三月十五」撞到同一张牌。
 */
export function 散列(串: string): number {
  let h = 2166136261;
  for (let i = 0; i < 串.length; i++) {
    h ^= 串.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/**
 * mulberry32。小而够用, 不需要引入任何东西。
 *
 * 直接用 `散列(串) % 22` 抽牌是不行的: FNV-1a 在长得很像的短串上低位几乎不动,
 * 「三月十四」「三月十五」会抽到相邻的牌 —— 玩家连着两天看见「愚者」接「魔术师」,
 * 一眼就看穿是假的。摇一道才有雪崩。
 */
export function 摇号机(种: number): () => number {
  let a = 种 >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
