// 把池子装配成「今天这一期」。
//
// 全部是**纯派生**: 给定 (日期, 季节, 天气, 供稿, 投稿) 就有唯一一期报, 不存变量、不掷骰。
// 所以刷新多少次、重挂几次 iframe, 玩家看到的都是同一份报纸 —— 这是 spec §6.2 要的
// 「同一天刷新多少次都是同一份报」, 也是这个模块能零 token 的原因。
//
// 定种走 定种.ts 那个小 PRNG (占卜也用它), 不碰 生成/闸门.ts 那套掷骰: 那边是
// 「日期变了重掷一批, 并且要保留已经命名的条目」, 是有状态的; 这边是无状态的派生。
// 两者的幂等要求不同, 混用迟早会踩到「重掷把报纸也重掷了」这种难查的联动。(spec §8)

import { 摇号机, 散列 } from '../定种';
import { 按版面, 每版条数, 版面次序, type 版面, type 条目 } from './池子';
import { 落在哪版, type 投稿版面 } from './投稿';

export interface 报条 {
  版面: 版面;
  标题: string;
  正文: string;
  /**
   * 从哪来的。渲染时只有 `投稿` 会带署名和「你投的」标签 ——
   * 玩家花了钱, 得一眼看见自己的稿子印在哪儿。
   */
  来源: '池子' | '供稿' | '投稿';
  /** 玩家投稿才有 */
  署名?: string;
}

export interface 一版 {
  版面: 版面;
  条: 报条[];
}

export interface 一期报 {
  日期: string;
  版: 一版[];
}

/**
 * 世界那边要喂进来的东西。都是字符串, 缺了也不影响出报。
 *
 * 只有 季节 和 天气 是真的在用 (过闸), 日期 用来定种和挑当天的稿。**没有 温度** ——
 * 温度原来是给天气版那条正文做前缀的, 天气版撤掉之后它就没有读者了 (见 出一期)。
 */
export interface 世界快照 {
  日期: string;
  季节: string;
  天气: string;
}

/** `世界.报纸供稿` 里的一条。 */
export interface 供稿条 {
  日期: string;
  标题: string;
  正文: string;
}

/** `世界.报纸投稿` 里的一条。 */
export interface 投稿条 {
  日期: string;
  版面: string;
  标题: string;
  正文: string;
  署名: string;
}

// ── 抽条 ────────────────────────────────────────────────────────────

/**
 * 季节/天气闸。
 *
 * `季` 用**子串**判而不是相等: `世界.季节` 是 AI 写的自由文本, 它写「秋天」「深秋」
 * 都合理。相等判的话这些一样会被判成「不是秋」, 于是**所有带季节的条目一起消失**,
 * 报纸照常出、一版都不空, 只是永远不提破冰节 —— 静默降级, 最难查的那种。
 * 空串则一律不匹配, 老存档 (没有 季节 字段) 就只出全年条目, 也是对的。
 */
export function 过闸(条: 条目, 季: string, 天气: string): boolean {
  if (条.季 && !条.季.some(s => 季.includes(s))) return false;
  if (条.天 && !条.天.some(字 => 天气.includes(字))) return false;
  return true;
}

/**
 * 不重复地抽 n 条。
 *
 * 抽走后从候选里删掉, 而不是抽完再去重 —— 去重会让「抽 2 条」在候选只剩 1 条时
 * 永远凑不满。虽然现在每个版面都够抽, 但池子将来会被改小, 那时候这是静默少一条。
 */
function 抽条(候选: 条目[], n: number, 随: () => number): 条目[] {
  const 剩 = [...候选];
  const 出: 条目[] = [];
  while (出.length < n && 剩.length) {
    出.push(剩.splice(Math.floor(随() * 剩.length), 1)[0]);
  }
  return 出;
}

// ── 装配 ────────────────────────────────────────────────────────────

/**
 * AI 供稿最多占几条。
 *
 * 原来这个数是 `每版条数.要闻` (2), 因为要闻版整个就是给供稿准备的。现在供稿挪到
 * **社会版的第一条**, 而社会版有 3 条 —— 直接复用 `每版条数.社会` 的话, AI 一写
 * 三条就把整个社会版写满了, 池子一条都补不进去, 报纸会变成 AI 的独角戏。
 *
 * 所以这里独立成一个常数, 并且**故意比版面容量小**: 2 条供稿 + 至少 1 条池子。
 * 让 AI 永远是「加进来的头条」而不是「这一版本身」。
 */
const 供稿上限 = 2;

/**
 * 出今天这一期。
 *
 * 顺序是定死的: **供稿 → 池子补齐 → 投稿**。前两者不消耗随机数, 所以池子抽到哪几条
 * 跟有没有人供稿毫无关系 —— 今天 AI 忘了写头条, 报纸不会连着把社会版也换一批。
 * 投稿排在最后, 是为了让它**额外**加一条而不是顶掉一条 (见下面那段注释)。
 */
export function 出一期(世界: 世界快照, 供稿: 供稿条[], 投稿: 投稿条[]): 一期报 {
  const 日期 = 世界.日期 ?? '';
  const 今天的 = (条: { 日期: string }) => 条.日期 === 日期;

  // 只认当天的。AI 忘了清理旧稿完全没关系 —— 日期对不上就不显示, 不需要它记得删。
  //
  // 取后几条 —— 它是用 append 追加的, 新的在后面。
  const 今供 = (供稿 ?? []).filter(今天的).slice(-供稿上限);
  const 今投 = (投稿 ?? []).filter(今天的);

  const 版: 一版[] = 版面次序.map(版面 => {
    // 种里带上版面: 这样往某一个版面加条目, 不会把别的版面也重新洗一遍。
    const 随 = 摇号机(散列(`${日期}|${版面}`));

    const 条: 报条[] = [];

    // AI 的供稿进**社会版**, 而且排在最前面 —— 它写的是玩家身边正在发生的事, 属于
    // 「这个世界在怎么运转」。改版前它占的是头版 (要闻), 要闻撤掉之后就归到这儿。
    if (版面 === '社会') {
      for (const 供 of 今供) 条.push({ 版面, 标题: 供.标题, 正文: 供.正文, 来源: '供稿' });
    }

    // 池子按**版面分量**补满。供稿占的位要扣掉 (头版永远是两条), 但下面的投稿不扣 ——
    // 玩家花了钱买的是一块版面, 不是「顶掉一条本来就会有的免费内容」。挤掉的话
    // 无论投哪一版, 报纸看上去都跟没投一样, 只是换了句话。
    const 候选 = 按版面(版面).filter(条 => 过闸(条, 世界.季节 ?? '', 世界.天气 ?? ''));
    const 要补 = Math.max(0, 每版条数[版面] - 条.length);
    条.push(
      ...抽条(候选, 要补, 随).map(条 => ({
        版面,
        标题: 条.标题,
        正文: 条.正文,
        来源: '池子' as const,
      })),
    );

    for (const 投 of 今投) {
      if (落在哪版[投.版面 as 投稿版面] !== 版面) continue;
      条.push({ 版面, 标题: 投.标题, 正文: 投.正文, 来源: '投稿', 署名: 投.署名 });
    }

    return { 版面, 条 };
  });

  // 这里原来有一段「给天气版第一条正文加 季节·天气·温度 前缀」的逻辑, 随天气版一起
  // 撤掉了。天气现在是**诊所页那个格子**的事 (那里一直在显示 季节·天气·温度), 报纸
  // 再报一遍纯属重复; 而报纸想要的那点天候味道, 靠池子里那些 `天` / `季` 闸的条目
  // 就够了 —— 下雪天自然会登下雪的事, 不必专门留一版说今天下雪。

  return { 日期, 版 };
}

/** 当天的投稿条数。一期只登一则, 界面靠它判断还能不能再投。 */
export function 今天投过(投稿: 投稿条[], 日期: string): boolean {
  return (投稿 ?? []).some(条 => 条.日期 === 日期);
}
