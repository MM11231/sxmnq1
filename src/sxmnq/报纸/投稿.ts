// 投稿 —— 玩家花钱买的版面。
//
// spec §2.3: 「投稿是玩家的动作, 不是游戏的赏赐」。所以这里没有任何一条免费的路,
// 也没有任何一条「因为你来了所以大家都很高兴」的稿子 —— 玩家掏钱, 玩家写字, 报纸登出来。
//
// 这是这个模块唯一花钱的地方, 标定它要跟诊金对上:
//   D 级一次治疗 ≈ 80~130 金 (基础诊金 (0+1)*40 + 污染度*2, 污染度 D 档 [20,45],
//   再乘评级系数 0.8~1.5) —— 拿 100 金当一次治疗的收入。
// 所以 D 级诊所在分类广告上登一则 = 一场半的治疗, 在头版登一则 = 八场。
// 开业第一天金钱是 0, 登不了报 —— 这是设计要的 (spec §2.3), 想打广告先挣到钱。

import type { 版面 } from './池子';

/** 玩家能投的版面。**没有天气版** —— 天气不是人写的。 */
export type 投稿版面 = '宣传' | '要闻' | '社会' | '经济' | '讣告' | '广告';

/** 投稿界面上的排列顺序。宣传放第一个: 它是玩家最常用的那一档。 */
export const 投稿版面次序: 投稿版面[] = ['宣传', '要闻', '社会', '经济', '讣告', '广告'];

export const 版面说明: Record<投稿版面, string> = {
  宣传: '登在分类广告版, 加名声',
  要闻: '头版。最贵, 也最显眼',
  社会: '市井见闻、生活琐事',
  经济: '航线、物价、军备',
  讣告: '悼念与追思',
  广告: '招租、转让、寻人',
};

/**
 * 稿子登在**哪一版**。
 *
 * 「宣传」不是一个真的版面 —— 它是玩家买广告位的那个动作, 印出来落在分类广告版里。
 * 单独列一档而不是让玩家「选广告 + 勾选宣传」, 是因为两件事在玩家心里就是一件事
 * (「我要打广告」), 拆成两步只会让人多问一句「那勾不勾有什么区别」。
 */
export const 落在哪版: Record<投稿版面, 版面> = {
  宣传: '广告',
  要闻: '要闻',
  社会: '社会',
  经济: '经济',
  讣告: '讣告',
  广告: '广告',
};

/** D 级的基准价。 */
const 基准价: Record<投稿版面, number> = {
  广告: 150,
  讣告: 200,
  社会: 300,
  宣传: 500,
  经济: 450,
  要闻: 800,
};

/**
 * 等级系数。
 *
 * 为什么要涨: 钱在这一行是跟着等级走的 —— S 级诊所一次治疗进账是 D 级的五倍上下
 * (基础诊金随等级加价, 评级系数也从 0.8 涨到 1.5)。版面费不涨的话, 到后期
 * 头版就变成了「随手丢两个钢镚」, 玩家不会再为它做任何取舍。
 */
const 系数: Record<string, number> = { D: 1, C: 1.6, B: 2.4, A: 3.5, S: 5 };

/** 一则稿子的价钱。 */
export function 算版面费(版面: 投稿版面, 等级: string): number {
  const k = 系数[等级] ?? 1;
  // 取整到 10 金。报价写成「447 金」很出戏, 报纸不会这么要钱。
  return Math.round((基准价[版面] * k) / 10) * 10;
}

/**
 * 宣传稿加的名声。
 *
 * **小额, 定死。** 名声到 100 就升一级 (见 等级.ts), 而一次治疗给的名声本来就不低 ——
 * 宣传要是给得多, 最优解就变成了「刷钱→登报」, 而不是「看病」。所以它比一次治疗略多,
 * 但不能多到值得为它攒钱。广告没能耐让一个诊所升一级, 这是常识。
 */
export const 宣传名声 = 5;

export interface 投稿输入 {
  版面: 投稿版面;
  标题: string;
  正文: string;
  署名: string;
}

export interface 能不能投的输入 {
  金钱: number;
  /** 今天的报纸是不是已经登过一则了 */
  今天投过: boolean;
  标题: string;
  正文: string;
}

/**
 * 该不该让这则稿子登出去。返回 null = 可以。
 *
 * 拦在这里而不是靠按钮 disabled: 按钮的 disabled 只管住鼠标, 拦不住
 * 「先点开面板、钱花在别处、再回来提交」这条路径。钱是提交那一刻扣的,
 * 判据就得在提交那一刻再看一遍。
 */
export function 拦下(输入: 能不能投的输入, 版面: 投稿版面, 等级: string): string | null {
  if (!输入.标题.trim()) return '稿子还没有标题';
  if (!输入.正文.trim()) return '稿子还没有正文';
  if (输入.今天投过) return '今天的报纸已经印好了, 明天请早';
  const 价 = 算版面费(版面, 等级);
  if (输入.金钱 < 价) return `版面费 ${价} 金, 现在只有 ${输入.金钱} 金`;
  return null;
}
