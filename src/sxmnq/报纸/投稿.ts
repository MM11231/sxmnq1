// 投稿 —— 玩家花钱买的版面。
//
// spec §2.3: 「投稿是玩家的动作, 不是游戏的赏赐」。所以这里没有任何一条免费的路,
// 也没有任何一条「因为你来了所以大家都很高兴」的稿子 —— 玩家掏钱, 玩家写字, 报纸登出来。
//
// 这是这个模块唯一花钱的地方, 标定它要跟诊金对上:
//   D 级一次治疗 ≈ 80~130 金 (基础诊金 (0+1)*40 + 污染度*2, 污染度 D 档 [20,45],
//   再乘评级系数 0.8~1.5) —— 拿 100 金当一次治疗的收入。
// 所以 D 级诊所在分类广告上登一则 = 一场半的治疗, 在社会版登一则 = 三场。
// 开业第一天金钱是 0, 登不了报 —— 这是设计要的 (spec §2.3), 想打广告先挣到钱。
//
// ── 2026-10-05 改版 (玩家: 「广告和宣传是不是重复了」「讣告做的也意义不明」) ──
//
// **「宣传」改叫「宣传诊所」, 并把差别写在明面上。** 原来有两档「宣传」和「广告」,
// 一个 500 金一个 150 金, 印出来却都在分类广告版 —— 玩家看到的是两个近义词的按钮,
// 猜不出凭什么差三倍钱, 只觉得重复。
//
// 但这两档其实不是重复, 是**两件不同的商品**:
//   宣传诊所 = 「我要让人知道这家诊所」→ 加名声
//   广告     = 「我要转让一台恒温箱」→ 不加名声
// 名声本来就只该来自前者。所以留着两档, 改的是**名字和说明**: 把「宣传」这个
// 和「广告」同义的词换掉, 价差和名声差直接印在按钮说明里, 玩家一眼看得出买的是什么。
//
// **讣告从价目表里下架了, 但报纸上还登。** 玩家手里没有可以悼念的人 —— 让他花钱
// 选「悼念与追思」, 他只会问「我该写谁」。讣告是报纸自己该登的东西: 素不相识的人
// 死了, 而世界照常运转, 这恰好是这张卡想说的话。池子里那 16 条留在讣告版, 玩家买不到。

import type { 版面 } from './池子';

/** 玩家能投的版面。**没有天气版, 也没有讣告版** —— 见上面那段。 */
export type 投稿版面 = '宣传诊所' | '社会' | '学术科技' | '趣闻' | '广告';

/** 投稿界面上的排列顺序。宣传诊所放第一个: 它是玩家最常用的那一档。 */
export const 投稿版面次序: 投稿版面[] = ['宣传诊所', '社会', '学术科技', '趣闻', '广告'];

/**
 * 按钮下面那行说明。
 *
 * 这两行是**改版的重点**: 前四档各自说清楚「登在哪一版、给不给名声、给什么内容」,
 * 玩家不用猜。宣传诊所和广告的说明是特意写成对仗的 —— 对比着读才知道贵在哪。
 */
export const 版面说明: Record<投稿版面, string> = {
  宣传诊所: `登在分类广告版, 加 ${5} 点名声`,
  社会: '这个世界在怎么运转。特区、边境、航线、物价',
  学术科技: '白塔在琢磨什么。抑制器、向导素、深渊',
  趣闻: '普通人今天在干什么。不加名声, 但读的人最多',
  广告: '寻物、转让、招租。不加名声',
};

/**
 * 稿子登在**哪一版**。
 *
 * 「宣传诊所」不是一个真的版面 —— 它是玩家替诊所买广告位的那个动作, 印出来落在
 * 分类广告版里。和「广告」落在同一版是**故意的**: 名声来自「这是一则替诊所打的
 * 广告」这件事本身, 换个版面并不会让名声更该给。两档的差别不在位置, 在买的是什么。
 */
export const 落在哪版: Record<投稿版面, 版面> = {
  宣传诊所: '广告',
  社会: '社会',
  学术科技: '学术科技',
  趣闻: '趣闻',
  广告: '广告',
};

/** D 级的基准价。讣告不在这里 —— 玩家买不到。 */
const 基准价: Record<投稿版面, number> = {
  广告: 150,
  趣闻: 260,
  社会: 320,
  学术科技: 420,
  宣传诊所: 500,
};

/**
 * 等级系数。
 *
 * 为什么要涨: 钱在这一行是跟着等级走的 —— S 级诊所一次治疗进账是 D 级的五倍上下
 * (基础诊金随等级加价, 评级系数也从 0.8 涨到 1.5)。版面费不涨的话, 到后期
 * 头版就变成了「随手丢两个钢镚」, 玩家不会再为它做任何取舍。
 */
const 系数: Record<string, number> = { D: 1, C: 1.6, B: 2.4, A: 3.5, S: 5 };

/** 一则稿子的价钱。 */
export function 算版面费(版面: 投稿版面, 等级: string): number {
  const k = 系数[等级] ?? 1;
  // 取整到 10 金。报价写成「447 金」很出戏, 报纸不会这么要钱。
  return Math.round((基准价[版面] * k) / 10) * 10;
}

/**
 * 宣传稿加的名声。
 *
 * **小额, 定死。** 名声到 100 就升一级 (见 等级.ts), 而一次治疗给的名声本来就不低 ——
 * 宣传要是给得多, 最优解就变成了「刷钱→登报」, 而不是「看病」。所以它比一次治疗略多,
 * 但不能多到值得为它攒钱。广告没能耐让一个诊所升一级, 这是常识。
 */
export const 宣传名声 = 5;

export interface 投稿输入 {
  版面: 投稿版面;
  标题: string;
  正文: string;
  署名: string;
}

export interface 能不能投的输入 {
  金钱: number;
  /** 今天的报纸是不是已经登过一则了 */
  今天投过: boolean;
  标题: string;
  正文: string;
}

/**
 * 该不该让这则稿子登出去。返回 null = 可以。
 *
 * 拦在这里而不是靠按钮 disabled: 按钮的 disabled 只管住鼠标, 拦不住
 * 「先点开面板、钱花在别处、再回来提交」这条路径。钱是提交那一刻扣的,
 * 判据就得在提交那一刻再看一遍。
 */
export function 拦下(输入: 能不能投的输入, 版面: 投稿版面, 等级: string): string | null {
  if (!输入.标题.trim()) return '稿子还没有标题';
  if (!输入.正文.trim()) return '稿子还没有正文';
  if (输入.今天投过) return '今天的报纸已经印好了, 明天请早';
  const 价 = 算版面费(版面, 等级);
  if (输入.金钱 < 价) return `版面费 ${价} 金, 现在只有 ${输入.金钱} 金`;
  return null;
}
