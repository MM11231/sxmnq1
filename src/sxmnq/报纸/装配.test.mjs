// 直接跑: node src/sxmnq/报纸/装配.test.mjs
//
// 这个测试盯的是报纸**最容易被静默弄坏**的那几件事:
//
//   · 「同一天同一份报」—— 它靠的是一个纯函数, 一旦有人在里面塞了 Math.random()
//     或者 new Date(), 报纸会每 500ms 跟着正文刷新换一批。不报错, 只是每刷一次
//     头版就换一条, 看起来像见鬼。
//   · 「一版都不空」—— 抽条抽不满时 `条` 就是个空数组, 界面渲染出来是一片空白,
//     比报错难查得多。所以要遍历四季 × 若干天气, 而不是只试今天这一份。
//   · 「世界不围着玩家转」(spec §6.4) —— 池子里混进一句提到诊所的话, 读起来就是
//     开局发的奖状。这条是玩家专门叮嘱的, 得有机器的眼睛盯着。
import '../测试钩子.mjs';

const 池 = await import(new URL('./池子.ts', import.meta.url).href);
const 装 = await import(new URL('./装配.ts', import.meta.url).href);
const 投 = await import(new URL('./投稿.ts', import.meta.url).href);

let fail = 0;
const 断言 = (条件, 说明) => {
  console.log(`${条件 ? '  ok  ' : ' FAIL '} ${说明}`);
  if (!条件) fail++;
};
const 等于 = (实得, 期望, 说明) => {
  const 好 = JSON.stringify(实得) === JSON.stringify(期望);
  断言(好, 好 ? 说明 : `${说明} —— 期望 ${JSON.stringify(期望)}, 实得 ${JSON.stringify(实得)}`);
};

const 世界 = (改 = {}) => ({ 日期: '霜降月第一日', 季节: '秋', 天气: '雾', ...改 });
const 出 = (改 = {}, 供 = [], 投 = []) => 装.出一期(世界(改), 供, 投);
const 各版 = 期 => 期.版.map(v => v.条.length);
const 全条 = 期 => 期.版.flatMap(v => v.条);

console.log('--- 池子够大 (spec §6.2: 目标 ≥120 条, 读完了就开始撞重复) ---');
断言(池.池子.length >= 120, `池子有 ${池.池子.length} 条`);
console.log('  各版条数: ' + 池.版面次序.map(b => `${池.版面名[b]} ${池.按版面(b).length}`).join(' / '));
for (const b of 池.版面次序) {
  断言(池.按版面(b).length >= 池.每版条数[b], `${池.版面名[b]} 的池子 (${池.按版面(b).length}) 撑得住每期抽 ${池.每版条数[b]} 条`);
}
// 同一版里标题重样, 报纸会像印错了。
const 重标题 = 池.池子.map(x => `${x.版面}|${x.标题}`);
const 重 = 重标题.filter((t, i) => 重标题.indexOf(t) !== i);
断言(重.length === 0, `没有重样的条目${重.length ? ': ' + [...new Set(重)].join(', ') : ''}`);

console.log('\n--- 同一天同一份报 ---');
const 甲 = JSON.stringify(出());
const 乙 = JSON.stringify(出());
断言(甲 === 乙, '同一个日期出两次, 逐字相同');

console.log('\n--- 换一天就换一份 ---');
const 丙 = JSON.stringify(出({ 日期: '霜降月第二日' }));
断言(甲 !== 丙, '日期变了, 报纸也跟着变');
// 但只变一部分才是对的: 顺着换种会把整份报洗一遍, 那样「今天是昨天的延续」就没了。
const 同条 = 出().版.flatMap(v => v.条.map(t => t.标题));
const 异条 = 出({ 日期: '霜降月第二日' }).版.flatMap(v => v.条.map(t => t.标题));
const 重合 = 同条.filter(t => 异条.includes(t)).length;
断言(重合 > 0, `两天的报纸有 ${重合}/${同条.length} 条重合 (不是整份重洗)`);

console.log('\n--- 一版都不空: 遍历四季 × 各种天 ---');
// 只试今天这一份是不够的 —— 空版只会在某些季节/天气的组合下发生, 而那正是玩家
// 玩到冬天才会撞上的。所以这里把组合铺开跑。
const 天气们 = ['', '雾', '雨', '雪', '沙尘', '晴', '极光'];
const 空版 = [];
for (const 季 of ['春', '夏', '秋', '冬']) {
  for (const 天 of 天气们) {
    const 期 = 出({ 季节: 季, 天气: 天 });
    for (const v of 期.版) {
      if (v.条.length === 0) 空版.push(`${季}/${天 || '无天'} 的 ${池.版面名[v.版面]}`);
      if (v.条.length > 池.每版条数[v.版面]) 空版.push(`${季}/${天} 的 ${池.版面名[v.版面]} 超量了`);
    }
  }
}
断言(空版.length === 0, `28 种季节/天气组合下每版都有条${空版.length ? ': ' + 空版.slice(0, 5).join('; ') : ''}`);

console.log('\n--- 季节/天气闸: 该出现的出现, 不该出现的不出现 ---');
// ⚠ 这两条是**阴性断言**, 最容易被坏仪表伪造 —— 先自检仪表。
const 冬 = 出({ 季节: '冬', 天气: '晴' });
const 冬条 = 全条(冬).map(t => t.标题 + t.正文).join('\n');
断言(池.池子.some(x => x.季 && x.季.includes('冬')), '(自检) 池子里确实有冬季限定条目');
// 直接把一条夏季限定塞进池子, 确认判据真的会拦住它 —— 不试的话「没出现」可能只是没抽中。
const 夏条 = 池.池子.find(x => x.季 && x.季.length === 1 && x.季[0] === '夏');
断言(!!夏条, '(自检) 池子里确实有夏季限定条目, 且只限夏');
断言(!装.过闸(夏条, '冬', ''), `夏季限定的「${夏条.标题}」在冬天过不了闸`);
断言(装.过闸(夏条, '夏', ''), '同一个条目在夏天过得了闸 (仪表不是恒假)');
断言(装.过闸(夏条, '夏天', ''), '季节写「夏天」**放行** —— 子串判的就是这个: AI 写的是自由文本');
断言(装.过闸(夏条, '夏末', ''), '季节写「夏末」也放行');
断言(!装.过闸(夏条, '春日', ''), '季节写「春日」拦得住 —— 容错不等于谁都放行');

const 雪条 = 池.池子.find(x => x.天 && x.天.includes('雪'));
断言(!!雪条, '(自检) 池子里确实有降雪限定条目');
// 这条同时也是**季与天要同时满足**的回归: 雪条多半还带着 `季: ['冬']`,
// 只喂天气不喂季节的话它过不了闸, 而那是判据对、测试错。
断言(!装.过闸(雪条, 雪条.季?.[0] ?? '', '晴'), `降雪限定的「${雪条.标题}」在晴天过不了闸`);
断言(装.过闸(雪条, 雪条.季?.[0] ?? '', '小雪转晴'), '天气写「小雪转晴」放行 (预报说「转晴」也该登)');

console.log('\n--- 报纸上不再有天气版 (2026-10-05 撤版) ---');
// 天气是**诊所页**的事 (那里一直在显示 季节·天气·温度), 报纸再登一遍是重复。
// 而且原来天气版那唯一一条跟着变量走的前缀逻辑也跟着撤了 —— 它没有读者了。
断言(!池.版面次序.includes('天气'), '版面表里没有天气版');
断言(!出().版.some(v => v.版面 === '天气'), '哪一天出的报里都没有天气版');
// 撤版之后, 报纸想要的那点天候味道全靠下面这些闸门条目 —— 所以上面那圈空版遍历
// 仍然要过。这一条是提醒: 天气版的 `天` 闸条目已经**分流进学术科技/趣闻**了。
断言(池.池子.some(x => x.天), '池子里仍然有跟着天气走的条目 (只是散在别的版里了)');

console.log('\n--- AI 供稿: 进社会版, 只认当天的, 且不动别版 ---');
const 供 = [{ 日期: '霜降月第一日', 标题: '白塔宣布本季任务投放调整', 正文: '任务大厅自本月起…' }];
const 有供 = 出({}, 供);
const 社会版 = 有供.版.find(v => v.版面 === '社会');
断言(社会版.条[0].标题 === '白塔宣布本季任务投放调整', '供稿排在社会版第一条');
断言(社会版.条[0].来源 === '供稿', '它被标成供稿, 不是池子');
等于(社会版.条.length, 池.每版条数.社会, '供稿顶掉一条池子条, 总数不变 —— 版面分量是稳的');

const 过时 = 出({}, [{ 日期: '霜降月第三日', 标题: '旧闻', 正文: 'x' }]);
断言(!全条(过时).some(t => t.标题 === '旧闻'), '日期对不上的供稿不显示 (AI 忘了清理旧稿也没关系)');
assert_noop: {
  // 供稿进了社会版, 别的版不该跟着变 —— 抽条的种子是按版分开的。
  const 无供 = 出({});
  const a = 无供.版.filter(v => v.版面 !== '社会').map(v => v.条.map(t => t.标题));
  const b = 有供.版.filter(v => v.版面 !== '社会').map(v => v.条.map(t => t.标题));
  等于(b, a, '有没有供稿, 其余版面的内容一模一样');
}
// ★ 供稿上限 (装配.ts 的 `供稿上限`) 比社会版的容量小 —— 这是改版时特意定的:
//   直接复用 每版条数.社会 的话, AI 一写三条就把整个社会版写满, 池子一条都补不进,
//   报纸会变成 AI 的独角戏。所以这里同时验两件事: 不漏登, 也不独占。
const 三条 = 出({}, [
  { 日期: '霜降月第一日', 标题: '甲', 正文: 'a' },
  { 日期: '霜降月第一日', 标题: '乙', 正文: 'b' },
  { 日期: '霜降月第一日', 标题: '丙', 正文: 'c' },
]);
const 社2 = 三条.版.find(v => v.版面 === '社会');
const 供数 = 社2.条.filter(t => t.来源 === '供稿').length;
断言(供数 < 池.每版条数.社会, `三条供稿没有把社会版占满 (登了 ${供数} 条, 版面 ${池.每版条数.社会} 条)`);
断言(社2.条.some(t => t.来源 === '池子'), '社会版里仍然有一条池子的内容 —— AI 不是这一版的全部');
断言(社2.条.length <= 池.每版条数.社会, '不管 AI 写几条, 社会版都不超量');

console.log('\n--- 投稿: 花钱买的那一则 ---');
const 稿 = [{ 日期: '霜降月第一日', 版面: '社会', 标题: '听雨诊所今日开张', 正文: '本诊所主治精神污染。', 署名: '林晚' }];
const 有稿 = 出({}, [], 稿);
const 社3 = 有稿.版.find(v => v.版面 === '社会');
const 稿条 = 社3.条.find(t => t.来源 === '投稿');
断言(!!稿条, '投稿出现在它买的那一版里');
断言(稿条.标题 === '听雨诊所今日开张' && 稿条.署名 === '林晚', '标题和署名都是玩家写的');
等于(社3.条.filter(t => t.来源 === '池子').length, 池.每版条数.社会,
  '池子该有的几条照旧 —— 投稿是**额外**买的, 不挤掉本来就会有的免费内容 (钱不能白花)');
等于(社3.条.length, 池.每版条数.社会 + 1, '投了稿之后这一版多出一条');

// ★ 「宣传诊所」和「广告」都落在分类广告版 —— 这是**故意的**(见 投稿.ts)。
//   改版前这两档叫「宣传」和「广告」, 一个 500 金一个 150 金, 印在同一版,
//   玩家看到两个近义词的按钮只会觉得重复。现在它们是两件不同的商品:
//   一个加名声一个不加。所以这里除了落版, 还要盯住「名声由买的那一档决定」。
const 宣 = 出({}, [], [{ 日期: '霜降月第一日', 版面: '宣传诊所', 标题: '听雨诊所', 正文: '…', 署名: '林晚' }]);
断言(!宣.版.some(v => v.版面 === '宣传诊所'), '没有叫「宣传诊所」的版面 (它不是一个版, 是一次购买)');
断言(宣.版.find(v => v.版面 === '广告').条.some(t => t.来源 === '投稿'), '宣传诊所的稿子落在分类广告版');
const 普 = 出({}, [], [{ 日期: '霜降月第一日', 版面: '广告', 标题: '寻物', 正文: '…', 署名: '' }]);
断言(普.版.find(v => v.版面 === '广告').条.some(t => t.来源 === '投稿'), '普通广告也落在分类广告版 (同一版, 两件商品)');
断言(投.算版面费('宣传诊所', 'D') > 投.算版面费('广告', 'D'), '宣传诊所比普通广告贵 —— 贵的就是那点名声');
断言(投.落在哪版['宣传诊所'] === 投.落在哪版['广告'], '两档落在同一版: 名声来自「替诊所打的广告」这件事, 不是来自位置');

// 讣告从价目表下架了 (玩家: 「讣告做的也意义不明」)。报纸上还登, 但玩家买不到 ——
// 他手里没有可以悼念的人, 让他花钱选「悼念与追思」只会让他问「我该写谁」。
断言(!投.投稿版面次序.includes('讣告'), '讣告不在价目表里');
断言(!('讣告' in 投.落在哪版), '讣告没有落版映射 —— 玩家投不出这一版');
assert_noop3: {
  const 讣版 = 出().版.find(v => v.版面 === '讣告');
  断言(!!讣版 && 讣版.条.length > 0, '讣告版照常登 —— 报纸自己会登, 只是玩家买不到');
  断言(讣版.条.every(t => t.来源 === '池子'), '讣告版上的每一条都来自池子');
}

assert_noop2: {
  const 昨 = 出({}, [], [{ 日期: '霜降月第九日', 版面: '社会', 标题: '昨天的', 正文: 'x', 署名: '' }]);
  断言(!全条(昨).some(t => t.标题 === '昨天的'), '往期的投稿不混进今天的报 (沉到「往期」是界面的事)');
}

console.log('\n--- 一期只登一则 ---');
const 已有 = [{ 日期: '霜降月第一日', 版面: '广告', 标题: 'x', 正文: 'y', 署名: '' }];
断言(装.今天投过(已有, '霜降月第一日'), '今天投过就是投过');
断言(!装.今天投过(已有, '霜降月第二日'), '换一天就又能投了');

console.log('\n--- 版面费: 随等级涨, 且 D 级开局就买不起 ---');
console.log('  版面费 D/S: ' + 投.投稿版面次序.map(b => `${b} ${投.算版面费(b, 'D')}/${投.算版面费(b, 'S')}`).join('  '));
for (const b of 投.投稿版面次序) {
  断言(投.算版面费(b, 'S') > 投.算版面费(b, 'D'), `${b} 在 S 级比 D 级贵`);
  断言(投.算版面费(b, 'D') % 10 === 0, `${b} 的报价是整十 (「447 金」很出戏)`);
}
断言(投.算版面费('社会', 'D') > 投.算版面费('广告', 'D'), '新闻版比分类广告贵 —— 位置是有价的');
// D 级一次治疗约 100 金。最便宜的一版也该换得动一场治疗, 否则「花钱登报」这件事没有分量。
断言(投.算版面费('广告', 'D') >= 100, '最便宜的版面也值一场治疗以上, 不是零钱');
const 最贵 = Math.max(...投.投稿版面次序.map(b => 投.算版面费(b, 'D')));
断言(最贵 <= 1000, `最贵的版面没贵到遥不可及 (D 级攒十来场也够得上, 实得 ${最贵})`);

console.log('\n--- 拦下的理由 ---');
const 拦 = (改, b = '广告', 级 = 'D') => 投.拦下({ 金钱: 9999, 今天投过: false, 标题: '标题', 正文: '正文', ...改 }, b, 级);
断言(拦({}) === null, '钱够、没投过、有标题有正文 → 放行');
断言(!!拦({ 标题: '  ' }), '没标题拦下');
断言(!!拦({ 正文: '' }), '没正文拦下');
断言(!!拦({ 今天投过: true }), '今天投过拦下');
断言(!!拦({ 金钱: 0 }), '钱不够拦下 —— 开局金钱就是 0, 这正是设计要的 (spec §2.3)');
断言(拦({ 金钱: 投.算版面费('广告', 'D') }) === null, '钱**刚好等于**版面费时放行 (边界不是 >)');
const 差一 = 投.拦下({ 金钱: 投.算版面费('广告', 'D') - 1, 今天投过: false, 标题: 'a', 正文: 'b' }, '广告', 'D');
断言(!!差一 && 差一.includes(String(投.算版面费('广告', 'D'))), `差一金也拦下, 且把价钱说清楚: 「${差一}」`);

console.log('\n--- 媚u 防线 (spec §6.4): 池子里不许有玩家 ---');
// 收钱办事的报纸不会在玩家开业第一天就登他的诊所。所以池子里**一个字**都不该提到
// 诊所/主角/第二人称。想让报纸提到诊所, 只有玩家自己掏钱投稿这一条路。
//
// ⚠ 阴性断言。先自检仪表: 拿一个**已知违规**的样本喂进去, 探针必须数得出来。
const 禁词 = ['你', '主角', '本诊所', '听雨', '林晚', '诊所'];
const 探针 = 文本 => 禁词.filter(w => 文本.includes(w));
断言(探针('你推开诊所的门').length === 2, `(自检) 探针在「你推开诊所的门」上数出「你」「诊所」两处 (实得 ${探针('你推开诊所的门').length})`);
断言(探针('铜铃响了一声。').length === 0, '(自检) 探针在一句干净的话上数出 0 —— 它不是恒真');
const 违规 = [];
for (const 条 of 池.池子) {
  const 中 = 探针(条.标题 + 条.正文);
  if (中.length) 违规.push(`${池.版面名[条.版面]}「${条.标题}」命中 ${中.join('/')}`);
}
断言(违规.length === 0, `池子 ${池.池子.length} 条里没有一条提到玩家或诊所${违规.length ? ':\n      ' + 违规.join('\n      ') : ''}`);

// 供稿与投稿是另一回事: 那是 AI 和玩家自己写的, 提到诊所天经地义。这里只管池子。

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
