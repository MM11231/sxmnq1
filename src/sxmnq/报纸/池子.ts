// 《白塔日报》的氛围池。
//
// 报纸的主体就是这一池子字。AI 那条供稿是可选的, 池子是保底 —— 所以**池子必须大**:
// 一期抽 10 条, 池子 130 条的话大约十几期才会开始眼熟, 而重复的报纸比没有报纸更伤
// 沉浸感。这是这个模块唯一的真实成本, 也是它唯一值得写长的地方。
//
// 三条硬约束 (spec §2, 全是玩家给的):
//
//   ① **世界不围着玩家转。** 这里一个字都不提主角和诊所 —— 四大特区的政治、航线、
//      物价、讣告、广告, 世界自顾自运转才好看。想让报纸提到诊所, 只有一条路: 玩到
//      名声够高, 由 AI 自己写进「报纸供稿」里。开局就发奖状是最出戏的写法。
//   ② **不必强绑定剧情。** 这些都是背景音, 跟当下这一楼有没有关系都行。
//   ③ 素材锚在旧卡世界书上 (归档/白塔-原始备份.json), 四个特区、白塔的功能分区、
//      深渊 T1–T5、极南暗雨街区的黑市、年度节庆 —— 让读过世界书的玩家认得出来。
//
// ⚠ 别写具体日期 (「3 月 15 日」这种)。这张卡的历法是「霜降月第一日」那种, 跟公历
//   对不上, 写死了就直接穿帮。节日只提名字不提起止日。
//
// ── 版面这一层 2026-10-05 重排过 (玩家要求) ──────────────────────────
//
// 原来是 要闻/社会/经济·军事/讣告/广告/天气 六版, 现在新闻收成三块:
// **社会 / 学术科技 / 趣闻**。理由是原来那六版里有三版在说同一件事 —— 「要闻」的
// 边境政治和「经济·军事」的军备订单读起来是一回事, 而「社会」反而被挤成了趣闻。
// 现在按**读者为什么读它**分: 社会 = 这个世界在怎么运转, 学术科技 = 白塔在琢磨什么,
// 趣闻 = 普通人今天在干什么。三块互不重叠, 一眼就知道该往哪读。
//
// 天气版整版撤掉了: 天气是**诊所页那个格子**的事 (那里已经显示 季节·天气·温度),
// 报纸再登一遍是重复; 而报纸真正想要的那点天候味道, 靠下面那些 `天` 闸的条目就够了。
//
// 讣告版留着, 但**从投稿价目表里去掉了** —— 见 投稿.ts 顶部。

